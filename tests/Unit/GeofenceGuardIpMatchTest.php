<?php

namespace Tests\Unit;

use App\Services\Attendance\GeofenceGuard;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

/**
 * مطابقةُ عناوين الشبكة بمدياتها.
 *
 * **ما يقيسه هذا الاختبار**
 *
 * `AttendanceDeterminant::isValidIP()` كانت تُطابق بـ`in_array` الحرفية:
 * شبكةُ مقرٍّ بـDHCP تعني تعدادَ ٢٥٤ عنواناً يدوياً، ثم بطلانَها كلَّها
 * حين يتغيّر المدى. `GeofenceGuard::ipMatches()` تفهم CIDR.
 *
 * والحالاتُ المُنتقاة هنا هي التي تُسقط التطبيقاتِ الساذجة: الحدُّ الأعلى
 * للمدى، والقناعُ غيرُ المحاذي للبايت (/25)، والخلطُ بين IPv4 وIPv6،
 * والمدى المشوَّه الذي يجب أن يُتجاهَل لا أن يُطابِق كلَّ شيء.
 */
class GeofenceGuardIpMatchTest extends TestCase
{
    public static function cases(): array
    {
        return [
            'عنوان مفرد مطابق' => ['192.168.1.10', ['192.168.1.10'], true],
            'عنوان مفرد غير مطابق' => ['192.168.1.11', ['192.168.1.10'], false],

            'داخل /24' => ['192.168.1.200', ['192.168.1.0/24'], true],
            'خارج /24' => ['192.168.2.1', ['192.168.1.0/24'], false],
            'حدّ /24 الأعلى' => ['192.168.1.255', ['192.168.1.0/24'], true],

            // قناعٌ لا يحاذي حدَّ البايت: النصفُ الأول من الشبكة فقط
            'داخل /25' => ['10.0.0.100', ['10.0.0.0/25'], true],
            'خارج /25' => ['10.0.0.200', ['10.0.0.0/25'], false],

            'مدى واسع /8' => ['10.55.99.3', ['10.0.0.0/8'], true],
            'المدى الكامل /0' => ['8.8.8.8', ['0.0.0.0/0'], true],

            'أولُ مدىً يطابق من عدّة' => ['172.16.0.5', ['192.168.1.0/24', '172.16.0.0/16'], true],

            'IPv6 داخل مداه' => ['2001:db8::1', ['2001:db8::/32'], true],
            'IPv6 خارج مداه' => ['2001:dba::1', ['2001:db8::/32'], false],

            // عائلتان مختلفتان لا تتقابلان — ولا يُطابق أحدُهما الآخر بالخطأ
            'IPv4 مقابل مدى IPv6' => ['192.168.1.1', ['2001:db8::/32'], false],
            'IPv6 مقابل مدى IPv4' => ['2001:db8::1', ['192.168.1.0/24'], false],

            // المشوَّهُ يُتجاهَل: لا يُطابِق، ولا يُسقِط بقيّةَ القائمة
            'مدى مشوَّه يُتجاهَل' => ['192.168.1.1', ['not-an-ip/24'], false],
            'قناع خارج المجال يُتجاهَل' => ['192.168.1.1', ['192.168.1.0/99'], false],
            'مشوَّه ثم صحيح' => ['192.168.1.1', ['نص/24', '192.168.1.0/24'], true],

            'قائمة فارغة' => ['192.168.1.1', [], false],
            'سطر فارغ يُتخطّى' => ['192.168.1.1', ['', '  '], false],
        ];
    }

    #[DataProvider('cases')]
    public function test_ip_matching(string $ip, array $ranges, bool $expected): void
    {
        $this->assertSame($expected, GeofenceGuard::ipMatches($ip, $ranges));
    }
}
