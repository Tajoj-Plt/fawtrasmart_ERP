    /**
     * عرض صفحة التحصيلات بالتفصيل
     * Generated by Copilot - دعم الفلاتر المتعددة (الموظف، الفرع، العميل، الفترة)
     */
    public function index(Request $request)
    {
        try {
            // الحصول على الفلاتر من الطلب
            $filterType = $request->input('filter_type', 'month'); // month, day, range
            $month = $request->input('month', now()->format('Y-m'));
            $day = $request->input('day', now()->format('Y-m-d'));
            $fromDate = $request->input('from_date');
            $toDate = $request->input('to_date');
            $branchId = $request->input('branch_id');
            $employeeId = $request->input('employee_id');
            $clientId = $request->input('client_id');
            $neighborhoodId = $request->input('neighborhood_id'); // فلتر المجموعة الجديد

            // خيارات العرض الجديدة
            $viewType = $request->input('view_type', 'details'); // summary أو details
            $groupBy = $request->input('group_by') ?: 'day_employee'; // التجميع حسب - الافتراضي اليوم والموظف
            $isSummary = $viewType === 'summary';

            // تسمية التجميع للعرض
            $groupByLabel = $this->groupByOptions[$groupBy] ?? 'التصنيف';

            // تحديد الفترة الزمنية بناءً على نوع الفلتر
            if ($filterType === 'day' && $day) {
                $startDate = Carbon::parse($day)->startOfDay();
                $endDate = Carbon::parse($day)->endOfDay();
            } elseif ($filterType === 'range' && $fromDate && $toDate) {
                $startDate = Carbon::parse($fromDate)->startOfDay();
                $endDate = Carbon::parse($toDate)->endOfDay();
            } else {
                // الافتراضي: شهر
                [$year, $monthNum] = explode('-', $month);
                $startDate = Carbon::createFromDate($year, $monthNum, 1)->startOfMonth();
                $endDate = Carbon::createFromDate($year, $monthNum, 1)->endOfMonth();
            }

            /*
                نطاقُ الرؤية من السلَّم الموحَّد لا من `is_main`.

                كان: من وقف على الفرع الرئيسيّ في الشريط (`users.branch_id`) يرى
                تحصيلاتِ المنشأة كلِّها ويختار أيَّ فرع — والوقوفُ عليه متاحٌ لكل
                موظفٍ في فرعٍ تحته. الآن:
                  • الموظفون المشمولون = accessibleUserIds(): `data_scope_all`/غيرُ
                    الموظف ⇒ الكلّ، نطاقُ فرع/منطقة ⇒ موظفو فروعه، وإلّا ⇒ هو
                    ومن يديرهم.
                  • فلترُ الفرع يُقبل إن كان ضمن ما يحقّ له اختيارُه، وإلّا أُهمل.
            */
            $user = auth()->user();
            $currentBranchId = $user->branch_id;
            $isMainBranch = DataScope::isUnrestricted();
            $allowedUserIds = $this->accessibleUserIds();

            $effectiveBranchId = null;
            if ($branchId && $branchId !== '0') {
                $selectable = DataScope::selectableBranchIds();
                if ($selectable === null || in_array((int) $branchId, $selectable, true)) {
                    $effectiveBranchId = (int) $branchId;
                }
            }

            // الحصول على بيانات التحصيلات
            $collectionsData = $this->getCollectionsDetail(
                $startDate,
                $endDate,
                $effectiveBranchId,
                $employeeId,
                $clientId,
                $neighborhoodId,
                $allowedUserIds
