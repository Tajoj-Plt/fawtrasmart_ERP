            $statistics = $this->calculateStatistics($collectionsData, $startDate);

            // تجميع البيانات حسب الخيار المحدد (للملخص)
            $reportData = [];
            $totals = [
                'count' => $collectionsData->count(),
                'amount' => $collectionsData->sum('amount'),
            ];

            if ($isSummary) {
                $reportData = $this->groupCollectionsData($collectionsData, $groupBy);
            } else {
                // للعرض التفصيلي، نجمع البيانات أيضاً مع تفاصيل كل عنصر
                $reportData = $this->groupCollectionsDataWithDetails($collectionsData, $groupBy);
            }

            // الحصول على قائمة الفروع للفلترة
            $branches = $this->getBranchesForFilter();

            // الحصول على قائمة الموظفين للفلترة
            $employees = $this->getEmployeesForFilter($allowedUserIds, $effectiveBranchId);

            // الحصول على قائمة العملاء
            $clients = $this->getClientsForFilter($effectiveBranchId);

            // الحصول على قائمة المجموعات (Region Groups)
            $regionGroups = $this->getRegionGroupsForFilter($effectiveBranchId);

            // خيارات التجميع
            $groupByOptions = $this->groupByOptions;

            return view('account::collections.detail-report', compact(
                'collectionsData',
                'reportData',
                'totals',
                'month',
                'day',
                'fromDate',
                'toDate',
                'filterType',
                'branches',
                'employees',
                'clients',
                'regionGroups',
                'effectiveBranchId',
                'employeeId',
                'clientId',
                'neighborhoodId',
                'isMainBranch',
                'statistics',
                'startDate',
                'endDate',
                'viewType',
                'groupBy',
                'groupByLabel',
                'isSummary',
                'groupByOptions'
            ));

        } catch (\Exception $e) {
            // يبلغ جدول «سجلّ الأخطاء»، لا ملفّ اللوق وحده
            OperationLog::failure($e, 'Account.CollectionsDetail', 'index');

            Log::error('Collections Detail Error', [
                'message' => $e->getMessage(),
                'trace' => $e->getTraceAsString(),
                'line' => $e->getLine(),
            ]);

            return redirect()->back()->withErrors(['error' => 'حدث خطأ أثناء تحميل بيانات التحصيلات: '.$e->getMessage()]);
        }
    }

    /**
     * تجميع بيانات التحصيلات حسب الخيار المحدد (للملخص)
     */
    private function groupCollectionsData($collectionsData, $groupBy)
    {
        $grouped = [];

        foreach ($collectionsData as $collection) {
            $key = $this->getGroupKey($collection, $groupBy);
            $name = $this->getGroupName($collection, $groupBy);

            if (! isset($grouped[$key])) {
                $grouped[$key] = [
                    'name' => $name,
                    'count' => 0,
                    'amount' => 0,
                    'date_key' => $key, // للترتيب
                ];
            }

            $grouped[$key]['count']++;
            $grouped[$key]['amount'] += $collection['amount'];
        }

        // ترتيب حسب التاريخ تنازلياً عند التجميع باليوم، وإلا حسب المبلغ
        if (in_array($groupBy, ['day', 'day_employee'])) {
            uksort($grouped, function ($a, $b) {
                return strcmp($b, $a); // ترتيب تنازلي حسب التاريخ
            });
        } else {
            uasort($grouped, function ($a, $b) {
                return $b['amount'] <=> $a['amount'];
            });
        }

        return $grouped;
    }

    /**
     * تجميع بيانات التحصيلات مع التفاصيل (للعرض التفصيلي)
     */
    private function groupCollectionsDataWithDetails($collectionsData, $groupBy)
    {
        $grouped = [];

        foreach ($collectionsData as $collection) {
            $key = $this->getGroupKey($collection, $groupBy);
            $name = $this->getGroupName($collection, $groupBy);

            if (! isset($grouped[$key])) {
                $grouped[$key] = [
                    'name' => $name,
                    'count' => 0,
                    'amount' => 0,
                    'items' => [],
                ];
            }

            $grouped[$key]['count']++;
            $grouped[$key]['amount'] += $collection['amount'];
            $grouped[$key]['items'][] = $collection;
        }

        // ترتيب حسب التاريخ تنازلياً عند التجميع باليوم، وإلا حسب المبلغ
        if (in_array($groupBy, ['day', 'day_employee'])) {
            uksort($grouped, function ($a, $b) {
                return strcmp($b, $a); // ترتيب تنازلي حسب التاريخ
            });
        } else {
            uasort($grouped, function ($a, $b) {
                return $b['amount'] <=> $a['amount'];
            });
        }

        return $grouped;
    }

    /**
     * الحصول على مفتاح التجميع
     */
    private function getGroupKey($collection, $groupBy)
    {
        switch ($groupBy) {
            case 'day':
                $date = $collection['date'];

                return $date instanceof Carbon ? $date->format('Y-m-d') : $date;
            case 'day_employee':
                $date = $collection['date'];
                $dateStr = $date instanceof Carbon ? $date->format('Y-m-d') : $date;

                return $dateStr.'_'.($collection['employee_id'] ?? 'unknown');
            case 'employee':
                return $collection['employee_id'] ?? 'unknown';
            case 'client':
                return $collection['client_id'] ?? 'unknown';
            case 'branch':
                return $collection['branch_id'] ?? 'unknown';
            case 'region':
                return $collection['region_id'] ?? 'unknown';
            case 'account_type':
                return $collection['account_type'] ?? 'unknown';
            case 'treasury':
                return $collection['account_id'] ?? 'unknown';
            default:
                return 'unknown';
        }
    }

    /**
     * الحصول على اسم المجموعة للعرض
     */
    private function getGroupName($collection, $groupBy)
    {
        switch ($groupBy) {
            case 'day':
                $date = $collection['date'];
                if ($date instanceof Carbon) {
                    return $date->format('Y-m-d').' ('.$this->getArabicDayName($date->dayOfWeek).')';
                }

                return $date;
            case 'day_employee':
                $date = $collection['date'];
                $dateStr = $date instanceof Carbon ? $date->format('Y-m-d') : $date;
                $dayName = $date instanceof Carbon ? ' ('.$this->getArabicDayName($date->dayOfWeek).')' : '';
                $employeeName = $collection['employee_name'] ?? 'غير محدد';

                return $dateStr.$dayName.' - '.$employeeName;
            case 'employee':
                return $collection['employee_name'] ?? 'غير محدد';
            case 'client':
                return $collection['client_name'] ?? 'غير محدد';
            case 'branch':
                return $collection['branch_name'] ?? 'غير محدد';
            case 'region':
                return $collection['region_name'] ?? 'غير محدد';
            case 'account_type':
                return $collection['account_type'] ?? 'غير محدد';
            case 'treasury':
                return $collection['treasury_account'] ?? 'غير محدد';
            default:
                return 'غير محدد';
        }
    }

    /**
     * الحصول على اسم اليوم بالعربية
     */
    private function getArabicDayName($dayOfWeek)
    {
        $days = [
            0 => 'الأحد',
            1 => 'الاثنين',
            2 => 'الثلاثاء',
            3 => 'الأربعاء',
            4 => 'الخميس',
            5 => 'الجمعة',
            6 => 'السبت',
        ];

        return $days[$dayOfWeek] ?? '';
    }

    /**
     * جلب تفاصيل التحصيلات - نفس طريقة EmployeePerformanceController::getEmployeeCollections
     * Generated by Copilot - جميع التحصيلات مع تفاصيل كاملة
     */
    private function getCollectionsDetail($startDate, $endDate, $branchId, $employeeId = null, $clientId = null, $neighborhoodId = null, ?array $allowedUserIds = null)
    {
        // جلب جميع حسابات الخزينة والبنوك
        $treasuryAndBankAccounts = Account::whereIn('parent_id', [
            AccountingSettings::id('cash_treasuries_parent', SystemAccountIds::CASH_TREASURIES_PARENT),  // 13
            AccountingSettings::id('bank_accounts_parent', SystemAccountIds::BANK_ACCOUNTS_PARENT),     // 15
        ])->pluck('id')->toArray();

        if (empty($treasuryAndBankAccounts)) {
            return collect([]);
        }

        $collectionsDetail = [];

        // جلب جميع الموظفين (أو موظف محدد إذا تم تصفيته)
        $employeesQuery = User::whereNotNull('employee_id')
            ->whereHas('employee', function ($q) {
                $q->where(function ($subQ) {
                    $subQ->where('status', 'active')
                        ->orWhere('status', '1')
                        ->orWhere('status', 1);
                });
            });

        // نطاقُ الرؤية أوّلاً — `null` = بلا قيد
        if ($allowedUserIds !== null) {
            $employeesQuery->whereIn('id', $allowedUserIds ?: [0]);
        }

        // تطبيق فلتر الفرع
        if ($branchId) {
            $employeesQuery->where('branch_id', $branchId);
        }

        // تطبيق فلتر الموظف
        if ($employeeId) {
            $employeesQuery->where('id', $employeeId);
        }

        $employees = $employeesQuery->with(['employee', 'branch'])->get();

        // لكل موظف، جلب التحصيلات باستخدام نفس منطق getEmployeeCollections
        foreach ($employees as $employee) {
            $userId = $employee->id;

            // جلب القيود المحاسبية للموظف في الفترة المحددة
            $journalEntryIds = JournalEntry::where('created_by_employee', $userId)
                ->whereBetween('date', [$startDate, $endDate])
                ->where('status', 1) // معتمد فقط
                ->pluck('id')
                ->toArray();

            if (empty($journalEntryIds)) {
                continue;
            }

            // تحميل بيانات القيود لتصنيفها
            $entriesInfo = JournalEntry::whereIn('id', $journalEntryIds)
                ->select('id', 'reference_type')
                ->get()
                ->keyBy('id');

            // استثناء التحويلات بين الخزائن/البنوك (لكن ليس قيود المرتجع SR)
            $transferEntryIds = [];
            foreach ($journalEntryIds as $entryId) {
                $entry = $entriesInfo->get($entryId);

                // قيود المرتجع لا تُعامَل كتحويلات حتى لو كان فيها مدين ودائن في الخزينة
                if ($entry && $entry->reference_type === ReferenceType::SALES_RETURN) {
                    continue;
                }

                $details = JournalEntryDetail::where('journal_entry_id', $entryId)->get();

                $hasDebitTreasury = $details->whereIn('account_id', $treasuryAndBankAccounts)->where('debit', '>', 0)->isNotEmpty();
                $hasCreditTreasury = $details->whereIn('account_id', $treasuryAndBankAccounts)->where('credit', '>', 0)->isNotEmpty();

                // إذا كان المدين والدائن كلاهما خزينة/بنك = تحويل
                if ($hasDebitTreasury && $hasCreditTreasury) {
                    $transferEntryIds[] = $entryId;
                }
            }

            // استثناء التحويلات فقط (SR تبقى)
            $validJournalEntryIds = array_diff($journalEntryIds, $transferEntryIds);

            // فصل قيود المرتجع عن قيود التحصيل العادية
            $srEntryIds = [];
            $normalEntryIds = [];
            foreach ($validJournalEntryIds as $entryId) {
                $entry = $entriesInfo->get($entryId);
                if ($entry && $entry->reference_type === ReferenceType::SALES_RETURN) {
                    $srEntryIds[] = $entryId;
                } else {
                    $normalEntryIds[] = $entryId;
                }
            }

            if (empty($validJournalEntryIds)) {
                continue;
            }

            // حساب التحصيلات العادية: فقط المدين (دخول أموال) في حسابات الخزينة والبنوك
            $collections = JournalEntryDetail::whereIn('journal_entry_id', $normalEntryIds)
                ->whereIn('account_id', $treasuryAndBankAccounts)
                ->where('debit', '>', 0) // فقط عندما تكون الخزينة/البنك مدينة
                ->with(['journalEntry.client.Neighborhoodname.Region', 'account'])
                ->get();

            foreach ($collections as $collection) {
                $journalEntry = $collection->journalEntry;

                // تطبيق فلتر العميل إذا تم تحديده
                if ($clientId && $journalEntry->client_id != $clientId) {
                    continue;
                }

                // تطبيق فلتر المجموعة (Region Group) إذا تم تحديده
                // نفس طريقة ClientController: عبر Neighborhoodname.Region
                if ($neighborhoodId) {
                    if (! $journalEntry->client) {
                        continue; // تخطي إذا لم يكن هناك عميل
                    }
                    // الفلترة عبر علاقة neighborhood -> region
                    $clientNeighborhood = $journalEntry->client->Neighborhoodname;
                    if (! $clientNeighborhood || ! $clientNeighborhood->Region || $clientNeighborhood->Region->id != $neighborhoodId) {
                        continue;
                    }
                }

                // الحصول على اسم المجموعة (Region)
                $regionName = null;
                $regionId = null;
                if ($journalEntry->client && $journalEntry->client->Neighborhoodname && $journalEntry->client->Neighborhoodname->Region) {
                    $regionName = $journalEntry->client->Neighborhoodname->Region->name;
                    $regionId = $journalEntry->client->Neighborhoodname->Region->id;
                }

                $collectionsDetail[] = [
                    'id' => $journalEntry->id,
                    'date' => $journalEntry->date,
                    'reference_number' => $journalEntry->reference_number,
                    'description' => $journalEntry->description,
                    'employee_name' => $employee->name ?? 'غير محدد',
                    'employee_id' => $userId,
                    'client_name' => $journalEntry->client?->trade_name ?? $journalEntry->client?->name ?? 'عام',
                    'client_id' => $journalEntry->client_id,
                    'branch_name' => $employee->branch?->name ?? 'غير محدد',
                    'branch_id' => $journalEntry->branch_id,
                    'treasury_account' => $collection->account?->name ?? 'غير محدد',
                    'account_id' => $collection->account_id,
                    'amount' => $collection->debit,
                    'account_type' => $this->getAccountType($collection->account),
                    'note' => $collection->description,
                    'region_name' => $regionName ?? 'غير محدد',
                    'region_id' => $regionId,
                ];
            }

            // طرح مبالغ إرجاع المبيعات (قيود SR - صرف نقدية للعميل) كمبالغ سالبة
            if (! empty($srEntryIds)) {
                $returnPayouts = JournalEntryDetail::whereIn('journal_entry_id', $srEntryIds)
                    ->whereIn('account_id', $treasuryAndBankAccounts)
                    ->where('credit', '>', 0)
                    ->with(['journalEntry.client.Neighborhoodname.Region', 'account'])
                    ->get();

                foreach ($returnPayouts as $returnPayout) {
                    $returnJournalEntry = $returnPayout->journalEntry;

                    if ($clientId && $returnJournalEntry->client_id != $clientId) {
                        continue;
                    }

                    if ($neighborhoodId) {
                        if (! $returnJournalEntry->client) {
                            continue;
                        }
                        $clientNeighborhood = $returnJournalEntry->client->Neighborhoodname;
                        if (! $clientNeighborhood || ! $clientNeighborhood->Region || $clientNeighborhood->Region->id != $neighborhoodId) {
                            continue;
                        }
                    }

                    $regionName = null;
                    $regionId = null;
                    if ($returnJournalEntry->client && $returnJournalEntry->client->Neighborhoodname && $returnJournalEntry->client->Neighborhoodname->Region) {
                        $regionName = $returnJournalEntry->client->Neighborhoodname->Region->name;
                        $regionId = $returnJournalEntry->client->Neighborhoodname->Region->id;
                    }

                    $collectionsDetail[] = [
                        'id' => $returnJournalEntry->id,
                        'date' => $returnJournalEntry->date,
                        'reference_number' => $returnJournalEntry->reference_number,
                        'description' => $returnJournalEntry->description,
                        'employee_name' => $employee->name ?? 'غير محدد',
                        'employee_id' => $userId,
                        'client_name' => $returnJournalEntry->client?->trade_name ?? $returnJournalEntry->client?->name ?? 'عام',
                        'client_id' => $returnJournalEntry->client_id,
                        'branch_name' => $employee->branch?->name ?? 'غير محدد',
                        'branch_id' => $returnJournalEntry->branch_id,
                        'treasury_account' => $returnPayout->account?->name ?? 'غير محدد',
                        'account_id' => $returnPayout->account_id,
                        'amount' => -$returnPayout->credit, // مبلغ سالب = مرتجع من الخزينة
                        'account_type' => $this->getAccountType($returnPayout->account),
                        'note' => $returnPayout->description,
                        'region_name' => $regionName ?? 'غير محدد',
                        'region_id' => $regionId,
                    ];
                }
            }
        }

        // ترتيب النتائج حسب التاريخ
        usort($collectionsDetail, function ($a, $b) {
            return strtotime($b['date']) - strtotime($a['date']);
        });

        return collect($collectionsDetail);
    }

    /**
     * تحديد نوع الحساب (خزينة أم بنك)
     */
    private function getAccountType($account)
    {
        if (! $account || ! $account->parent_id) {
            return 'غير محدد';
        }

        if ($account->parent_id == AccountingSettings::id('cash_treasuries_parent', SystemAccountIds::CASH_TREASURIES_PARENT)) {
            return 'خزينة';
        } elseif ($account->parent_id == AccountingSettings::id('bank_accounts_parent', SystemAccountIds::BANK_ACCOUNTS_PARENT)) {
            return 'بنك';
        }

        return 'غير محدد';
    }

    /**
     * حساب الإحصائيات الإجمالية
     */
    private function calculateStatistics($collectionsData, $startDate)
    {
        $totalCollections = $collectionsData->sum('amount');
        $collectionCount = $collectionsData->count();

        // حساب الرصيد الافتراضي في البداية (اختياري)
        $openingBalance = 0;

        return [
            'opening_balance' => $openingBalance,
            'total_collections' => $totalCollections,
            'collection_count' => $collectionCount,
            'average_collection' => $collectionCount > 0 ? $totalCollections / $collectionCount : 0,
            'closing_balance' => $openingBalance + $totalCollections,
        ];
    }

    /**
     * الحصول على الفروع للفلترة
     */
    private function getBranchesForFilter()
    {
        // ما يحقّ له اختيارُه وحدَه — لا كلُّ الفروع لمن وقف على الرئيسيّ
        return DataScope::branchOptions(Branch::where('status', 'active')->orderBy('name'));
    }

    /**
     * الحصول على قائمة الموظفين للفلترة
     */
    private function getEmployeesForFilter(?array $allowedUserIds, $effectiveBranchId)
    {
        $query = User::whereNotNull('employee_id')
            ->whereHas('employee', function ($q) {
                $q->where(function ($subQ) {
                    $subQ->where('status', 'active')
                        ->orWhere('status', '1')
                        ->orWhere('status', 1);
                });
            });

        if ($allowedUserIds !== null) {
            $query->whereIn('users.id', $allowedUserIds ?: [0]);
        }

        if ($effectiveBranchId) {
            $query->where('branch_id', $effectiveBranchId);
        }

        return $query->orderBy('users.name')->get();
    }

    /**
     * الحصول على قائمة العملاء
     */
    private function getClientsForFilter($branchId = null)
    {
        $query = Client::where('status', 'active');

        if ($branchId) {
            // يمكن إضافة علاقة الفرع إذا كانت موجودة
            $query->where('branch_id', $branchId);
        }

        return $query->orderBy('trade_name')->get();
    }

    /**
     * الحصول على قائمة المجموعات (Region Groups)
     */
    private function getRegionGroupsForFilter($branchId = null)
    {
        $query = Region_groub::query();

        if ($branchId) {
            // جلب المجموعات التي تتبع الفرع المحدد
            $query->where('branch_id', $branchId);
        }

        return $query->orderBy('name')->get();
    }
