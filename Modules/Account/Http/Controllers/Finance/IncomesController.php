    /**
     * حساب الرصيد السابق للعميل
     * Generated by Copilot
     *
     * الرصيد السابق = رصيد الحساب (balance) - إجمالي الفواتير غير المسددة أو المسددة جزئياً
     * هذا يمثل الديون القديمة التي ليس لها فواتير في النظام
     *
     * ملاحظة: يجب استدعاء هذه الدالة مع تمرير المبلغ المستلم لأن رصيد الحساب
     * يكون قد تم تحديثه (خصم المبلغ) قبل استدعاء هذه الدالة
     *
     * @param  int  $clientId  معرف العميل
     * @param  float  $receivedAmount  المبلغ المستلم (الذي تم خصمه من الحساب)
     * @return array معلومات الرصيد السابق
     */
    private function calculatePreviousBalance($clientId, $receivedAmount = 0)
    {
        // جلب حساب العميل
        $client_account = Account::ledger()->where('client_id', $clientId)->first();

        if (! $client_account) {
            return [
                'account_balance' => 0,
                'total_invoices_due' => 0,
                'previous_balance' => 0,
                'remaining_previous_balance' => 0,
            ];
        }

        /*
            رصيدُ الحساب قبل هذا السند — **بعلامته** ومن سطور القيود.

            كان `abs(balance)`: عميلٌ دائنٌ (دفع مقدّماً ٥٠٠) يُقرأ مديناً بـ٥٠٠،
            فيُحسب عليه «رصيدٌ سابق» لا وجود له ويُسجَّل السندُ سداداً لدَينٍ
            وهمي. والرصيدُ من الأستاذ لا من العمود — كما في
            `ClientDebtSettlement`. وقيدُ هذا السند مُرحَّلٌ قبل التوزيع،
            فيُعاد مبلغُه ليُقرأ الرصيدُ قبله.
        */
        $ledgerBalance = app(CustomerLedgerService::class)->balancesAt([$client_account->id], null)[$client_account->id] ?? 0;
        $account_balance = (float) $ledgerBalance + $receivedAmount;

        // حساب إجمالي المتبقي من الفواتير غير المسددة أو المسددة جزئياً
        // مع استثناء فواتير المرتجع والفواتير المرتبطة بمرتجع
        $unpaid_invoices = $this->getUnpaidClientInvoices($clientId);
        $total_invoices_due = 0;

        foreach ($unpaid_invoices as $invoice) {
            // المتبقّي بعد النقد **و«مرتجع»** — ومنه ما أرجعه إشعارٌ دائن
            $invoice_due = $invoice->calculateRemainingAmount();
            if ($invoice_due > 0) {
                $total_invoices_due += $invoice_due;
            }
        }

        // الرصيد السابق = رصيد الحساب الأصلي - إجمالي المتبقي من الفواتير
        $previous_balance = max(0, $account_balance - $total_invoices_due);

        /*
            **هو المتبقّي نفسُه — لا يُطرح منه ما سُدِّد.**

            الرصيدُ أعلاه نزل بكلّ سدادٍ سابقٍ للرصيد السابق (قيدُ سنده دائنٌ
            على الحساب)، فطرحُ مجموع تلك السدادات مرّةً ثانية كان يُنقص الباقي
            مرّتين: دَينٌ قديم ١٠٠٠ سُدِّد منه ٤٠٠ يُقرأ باقيه ٢٠٠ لا ٦٠٠،
            ويذهب الفرقُ إلى فواتير لم يُقصد سدادُها.
        */
        $remaining_previous_balance = $previous_balance;

        return [
            'account_balance' => $account_balance,
            'total_invoices_due' => $total_invoices_due,
            'previous_balance' => $previous_balance,
            'remaining_previous_balance' => $remaining_previous_balance,
        ];
    }

    /**
     * جلب الفواتير غير المسددة أو المسددة جزئياً للعميل
     * Generated by Copilot
     *
     * تستثني هذه الدالة:
     * 1. فواتير المرتجع (type = 'returned')
     * 2. الفواتير التي لديها مرتجع مرتبط بها عبر reference_number
     *
     * @param  int  $clientId  معرف العميل
     * @return \Illuminate\Database\Eloquent\Collection مجموعة الفواتير غير المسددة مرتبة من الأقدم
     */
    private function getUnpaidClientInvoices($clientId)
    {
        // الحصول على معرفات الفواتير التي لها مرتجع مرتبط بها
        // فاتورة المرتجع تحتوي على reference_number يشير إلى الفاتورة الأصلية
        $invoices_with_returns = Invoice::where('type', 'returned')
            ->whereNotNull('reference_number')
            ->pluck('reference_number')
            ->toArray();

        return Invoice::where('client_id', $clientId)
            ->where('is_paid', false)
            // استثناء فواتير المرتجع
            ->where('type', '!=', 'returned')
            // استثناء الفواتير التي لها مرتجع مرتبط بها
            ->whereNotIn('id', $invoices_with_returns)
            // ترتيب من الأقدم إلى الأحدث
            ->orderBy('invoice_date', 'asc')
            ->orderBy('id', 'asc')
            ->get();
    }

    /**
     * توزيع مبلغ السند على الرصيد السابق ثم الفواتير
     * Generated by Copilot
     *
     * يتم التسديد بالترتيب التالي:
     * 1. حساب الرصيد السابق (رصيد الحساب - إجمالي الفواتير غير المسددة)
     * 2. تسديد الرصيد السابق أولاً
     * 3. ثم تسديد الفواتير حسب تاريخها (الأقدم أولاً)
     *
     * @param  int  $clientId  معرف العميل
     * @param  float  $amount  المبلغ المراد توزيعه
     * @param  int|null  $receiptId  معرف سند القبض
     * @param  int|null  $journalEntryId  معرف القيد المحاسبي
     * @param  string|null  $paymentDate  تاريخ السند — تاريخُ الدفعات وفترتُها
     * @return void
     */
    private function applyPaymentToInvoices($clientId, $amount, $receiptId = null, $journalEntryId = null, $paymentDate = null)
    {
        /*
            الدفعةُ بتاريخ السند لا بتاريخ اليوم: كانت `now()`، فسندٌ بتاريخ
            25 سبتمبر يُدخَل في أكتوبر تُسجَّل دفعاتُه في أكتوبر — تُختم بفترةٍ
            غير فترته وتظهر في تقارير التحصيل بيومٍ لم يُقبض فيه شيء.
        */
        $paymentDate = $paymentDate ?: now();
        $remaining = $amount;
        $paidInvoices = [];
        $invoiceLinks = [];

        Log::info('========== بدء توزيع المدفوعات ==========');
        Log::info('سند القبض #'.$receiptId.' - المبلغ المستلم: '.$amount);

        // الخطوة الأولى: حساب الرصيد السابق للعميل
        // نمرر المبلغ المستلم لأن رصيد الحساب تم تحديثه (خصم المبلغ) قبل استدعاء هذه الدالة
        $balance_info = $this->calculatePreviousBalance($clientId, $amount);

        Log::info('تحليل رصيد العميل:', [
            'رصيد_الحساب_الأصلي' => $balance_info['account_balance'],
            'إجمالي_المتبقي_من_الفواتير' => $balance_info['total_invoices_due'],
            'الرصيد_السابق_الأصلي' => $balance_info['previous_balance'],
            'الرصيد_السابق_المتبقي' => $balance_info['remaining_previous_balance'],
        ]);

        // الخطوة الثانية: تسديد الرصيد السابق أولاً (إن وجد)
        if ($balance_info['remaining_previous_balance'] > 0) {
            $previous_balance_pay = min($remaining, $balance_info['remaining_previous_balance']);

            if ($previous_balance_pay > 0) {
                Log::info('تسديد الرصيد السابق', [
                    'المبلغ_المدفوع' => $previous_balance_pay,
                    'من_أصل' => $balance_info['remaining_previous_balance'],
                ]);

                // تسجيل دفعة للرصيد السابق
                PaymentsProcess::create([
                    'client_id' => $clientId,
                    'invoice_id' => null, // لا يوجد فاتورة مرتبطة
                    'amount' => $previous_balance_pay,
                    'type' => 'previous_balance_payment',
                    'payment_date' => $paymentDate,
                    'payment_status' => 1,
                    'payment_method' => 1,
                    'reference_number' => $receiptId,
                    'receipt_id' => $receiptId,
                ]);

                $remaining -= $previous_balance_pay;

                Log::info('تم تسديد الرصيد السابق. المتبقي للفواتير: '.$remaining);
            }
        } else {
            Log::info('لا يوجد رصيد سابق للتسديد. سيتم توزيع المبلغ على الفواتير مباشرة.');
        }

        // إذا لم يتبقى مبلغ، لا داعي للاستمرار
        if ($remaining <= 0) {
            Log::info('تم تسديد الرصيد السابق بالكامل. لا يوجد مبلغ متبقي للفواتير.');

            return;
        }

        // الخطوة الثالثة: تسديد الفواتير غير المسددة (الأقدم أولاً)
        $invoices = $this->getUnpaidClientInvoices($clientId);

        Log::info('عدد الفواتير غير المسددة (بعد استثناء المرتجعات): '.$invoices->count());

        foreach ($invoices as $invoice) {
            // ما أرجعه إشعارٌ دائن («مرتجع» الفاتورة) لا يُحصَّل ثمنُه
            $due = $invoice->calculateRemainingAmount();
            if ($due <= 0) {
                continue;
            }

            $pay = min($remaining, $due);

            /* «منع السداد الجزئي» — فاتورةُ اشتراكٍ دوريّ ضُبط عليه الخيار لا
               يُوزَّع عليها جزءٌ من السند: تُتخطّى إلى التالية، ويبقى ما لم
               يُوزَّع رصيداً دائناً للعميل كما يبقى أيُّ فائضٍ من السند. */
            if (PartialPaymentRule::blocks($invoice, $pay, $due)) {
                Log::info('تُخطّيت الفاتورة #'.$invoice->id.' — تمنع السداد الجزئي', [
                    'due_amount' => $due,
                    'available' => $pay,
                ]);

                continue;
            }

            if ($pay > 0) {
                Log::info('معالجة الفاتورة #'.$invoice->id, [
                    'invoice_number' => $invoice->invoice_number,
                    'due_amount' => $due,
                    'payment_amount' => $pay,
                ]);

                PaymentsProcess::create([
                    'client_id' => $clientId,
                    'invoice_id' => $invoice->id,
                    'amount' => $pay,
                    'type' => 'client payments',
                    'payment_date' => $paymentDate,
                    'payment_status' => 1,
                    'payment_method' => 1,
                    'reference_number' => $receiptId,
                    'receipt_id' => $receiptId,
                ]);

                $invoice->updatePaymentStatus();

                // إعداد روابط الفواتير للقيد
                if ($journalEntryId) {
                    $invoiceLinks[] = [
                        'entry_id' => $journalEntryId,
                        'invoice_id' => $invoice->id,
                        'invoice_type' => InvoiceType::SALE->value,
                        'allocation_amount' => $pay,
                    ];
                }

                $paidInvoices[] = $invoice->invoice_number ?? $invoice->id;
                $remaining -= $pay;

                Log::info('تم تسديد مبلغ '.$pay.' للفاتورة #'.$invoice->id);
            }
            if ($remaining <= 0) {
                break;
            }
        }

        // ربط القيد بالفواتير المدفوعة باستخدام جدول journal_entry_invoices
        if (! empty($invoiceLinks) && $journalEntryId) {
            foreach ($invoiceLinks as $link) {
                JournalEntryInvoice::create($link);
            }

            // تحديث القيد ليكون من نوع متعدد الربط
            $journalEntry = JournalEntry::find($journalEntryId);
            if ($journalEntry) {
                $journalEntry->linking_type = LinkingType::MULTIPLE;
                $journalEntry->batch_reference = implode(', ', $paidInvoices);
                $journalEntry->save();

                Log::info('تم ربط القيد #'.$journalEntryId.' بـ '.count($invoiceLinks).' فاتورة');
            }
        }

        Log::info('انتهى توزيع المدفوعات. المبلغ المتبقي: '.$remaining);
    }

    /**
     * إلغاء تسديد الفواتير عند حذف السند
     */
    private function reversePaymentFromInvoices($receiptId, $journalEntryId = null)
    {
        Log::info('إلغاء تسديد الفواتير للسند #'.$receiptId);

        // 1. حذف روابط القيد المحاسبي بالفواتير
        if ($journalEntryId) {
            $linkedInvoices = JournalEntryInvoice::where('entry_id', $journalEntryId)->get();
            Log::info('عدد الفواتير المرتبطة بالقيد: '.$linkedInvoices->count());

            JournalEntryInvoice::where('entry_id', $journalEntryId)->delete();
            Log::info('تم حذف روابط القيد المحاسبي');
        }

        /*
            2. حذف المدفوعات — بمعرّف السند لا بـ`reference_number`.

            المرجعُ نصٌّ يكتبه المستخدمُ بيده في دفعات المبيعات، فكان إلغاءُ
            السند رقم 2344 يحذف دفعةَ عميلٍ آخر مرجعُها «2344».
        */
        $payments = PaymentsProcess::where('receipt_id', $receiptId)->get();
        Log::info('عدد المدفوعات المرتبطة بالسند: '.$payments->count());

        foreach ($payments as $payment) {
            $invoice = $payment->invoice;
            Log::info('حذف دفعة #'.$payment->id.' للفاتورة #'.($invoice ? $invoice->id : 'N/A'));

            $payment->delete();

            if ($invoice) {
                $invoice->updatePaymentStatus();
                Log::info('تم تحديث حالة الفاتورة #'.$invoice->id);
            }
        }

        Log::info('انتهى إلغاء تسديد الفواتير');
    }

    /**
     * إرجاع معرفات الفرع المحدد + كل أحفاده فقط (بدون الأجداد).
     * يعني لما يختار المستخدم فرع ابن، يجلب سندات هذا الابن وأحفاده تحديداً،
     * ولما يختار الأب يجلب الأب + كل الأبناء والأحفاد.
     */
    private function resolveBranchTreeIds($branchId): array
    {
        // الفرعُ المطلوب مقصوصاً على نطاق المستخدم — الرئيسيّ أو غيرُه لا يفتح ما ليس له
        $branchId = $this->requestedBranchNode($branchId);
        if (! $branchId) {
            return [0];
        }

        $branch = Branch::find($branchId);
        if (! $branch) {
            return [(int) $branchId];
        }

        return $branch->descendantBranchIds()
            ->push((int) $branch->id)
            ->unique()
            ->values()
            ->all();
    }

    public function index(Request $request)
    {
        // التحقق من كون الطلب AJAX
        if ($request->ajax() || $request->is_ajax) {
            return $this->getData($request);
        }

        $user = auth()->user();

        // جلب البيانات المرتبطة للعرض الأولي
        $categories = ReceiptCategory::all();
        $suppliers = Supplier::all();
        $users = User::select('id', 'name')->whereNotNull('employee_id')->get();
        $account_setting = AccountSetting::where('user_id', $user->id)->first();

        // الفروع الرئيسية (الجذور) فقط — الفلترة تشمل أحفادها تلقائياً
        $branches = $this->branchFilterOptions();

        // فلترة الحسابات حسب دور المستخدم
        if ($user->isEmployee()) {
            $employeeGroupIds = EmployeeGroup::where('employee_id', $user->employee_id)->pluck('group_id');

            if ($employeeGroupIds->isNotEmpty()) {
                $Accounts = Account::whereNotNull('client_id')
                    ->whereHas('client.Neighborhoodname.Region', function ($q) use ($employeeGroupIds) {
                        $q->whereIn('id', $employeeGroupIds);
                    })
                    ->get();
            } else {
                $Accounts = collect();
            }
        } else {
            $Accounts = Account::whereNotNull('client_id')->get();
        }

        // تحميل البيانات الأولية لسندات القبض
        $initialIncomes = $this->getInitialIncomesData($request);

        // نفس حساب `canEdit` في getData()/show() — الجدول الجزئي
        // (`partials.table`) يقرأه، وكان غائباً عن التحميل الأول للصفحة
        // فيسقط بخطأ "Undefined variable $canEdit" قبل أي بحث AJAX.
        $canEdit = auth()->user()->hasRolePermission('account.incomes.edit');

        return view('account::finance.incomes.index', [
            'categories' => $categories,
            'Accounts' => $Accounts,
            'users' => $users,
            'canEdit' => $canEdit,
            'account_setting' => $account_setting,
            'branches' => $branches,
            'initialIncomes' => $initialIncomes,
            // القائمة يجلبها القالب من AccountingPeriodOptions؛ هنا تُمرَّر
            // الفترةُ المطبَّقة وحدها لأنّ الترويسة تعرض اسمها
            'period' => AccountingPeriodFilter::resolve($request),
        ]);
    }

    // دالة لجلب البيانات الأولية لسندات القبض
    private function getInitialIncomesData(?Request $request = null)
    {
        $user = auth()->user();

        // إنشاء الاستعلام الأساسي مع الترتيب
        /*
            المدى الافتراضي هو الفترة المحاسبية الجارية لا «كل
            السجلّات»: كانت الشاشة تفتح على الجدول كلّه، فسنداتُ
            سنواتٍ مضت تزاحم سندات الشهر الذي يعمل عليه المحاسب.
        */
        /*
            **الفلترة بالعلاقة لا بالمدى.**

            `accounting_period_id` مختومٌ في السند لحظةَ إنشائه، فالسؤالُ عن
            فترةٍ صار مقارنةَ عمودٍ بمعرّف — لا حدَّين يُحسبان في كلّ شاشة ثمّ
            يُقارَنان بـ`date`.

            وكانت الشاشة تفتح على الجدول كلّه: سنداتُ سنواتٍ مضت في صفحةٍ
            واحدة، والإجماليات أعلاها لا تخصّ الفترة التي يعمل عليها المحاسب.
        */
        $period = AccountingPeriodFilter::resolve($request ?? request());

        // سياقُ الفرع من الشريط العلوي — كان السند يُعرض في كل الفروع
        // فرعُ الشريط يُطبَّق داخل scopeReceiptsForViewing() — سنداتُ العملاء المسنَدين تُعرض من أيّ فرع
        $query = Receipt::with(['account', 'user.branch', 'branch'])
            ->orderBy('id', 'DESC');

        // نطاق البيانات: سنداته هو، أو سندات من يديرهم إن كان يديرهم، أو الكل بلا قيد
        // — ومعها سندات عملائه المسنَدين إليه متى مُنح «عرض سندات قبض العملاء المسندين إليه»
        $this->scopeReceiptsForViewing($query, $this->headerBranchNode());

        // جلب البيانات مع ترقيم الصفحات (10 عناصر في الصفحة الأولى)
        AccountingPeriodFilter::apply($query, $period);

        $incomes = $query->paginate(10);

        // حساب إجمالي الإيرادات لفترات مختلفة مع مراعاة الصلاحيات
        /*
            الإجمالي الأوّل صار على الفترة المعروضة لا على «آخر ٧ أيام»:
            رقمٌ لا يوافق ما في الجدول تحته يُقرأ خطأً. والنافذتان الأخريان
            تبقيان للمقارنة.
        */
        $totalPeriodQuery = AccountingPeriodFilter::apply(Receipt::query()->forBranch($this->headerBranchNode()), $period);
        $totalLast30DaysQuery = Receipt::forBranch($this->headerBranchNode())->where('date', '>=', now()->subDays(30));
        $totalLast365DaysQuery = Receipt::forBranch($this->headerBranchNode())->where('date', '>=', now()->subDays(365));

        $accessibleUserIds = $this->accessibleUserIds();
        if ($accessibleUserIds !== null) {
            $totalPeriodQuery->whereIn('created_by', $accessibleUserIds ?: [0]);
            $totalLast30DaysQuery->whereIn('created_by', $accessibleUserIds ?: [0]);
            $totalLast365DaysQuery->whereIn('created_by', $accessibleUserIds ?: [0]);
        }

        /*
            الإحصاءُ على الإجمالي بعد الضريبة — وهو ما خرج من الخزينة فعلاً.

            كان الجمعُ على `amount` (قبل الضريبة)، فتقول البطاقةُ رقماً
            والسنداتُ تحته تقول غيرَه، ولا يطابق أيٌّ منهما دفترَ الخزينة.

            و`COALESCE` لأن السنداتِ القديمة قد لا تحمل إجمالياً محسوباً.
        */
        $totalPeriod = $totalPeriodQuery->sum(DB::raw('COALESCE(NULLIF(total_amount, 0), amount)'));
        $totalLast30Days = $totalLast30DaysQuery->sum(DB::raw('COALESCE(NULLIF(total_amount, 0), amount)'));
        $totalLast365Days = $totalLast365DaysQuery->sum(DB::raw('COALESCE(NULLIF(total_amount, 0), amount)'));

        $account_setting = AccountSetting::where('user_id', $user->id)->first();

        return [
            'incomes' => $incomes,
            'totals' => [
                'totalPeriod' => $totalPeriod,
                'totalLast30Days' => $totalLast30Days,
                'totalLast365Days' => $totalLast365Days,
            ],
            'account_setting' => $account_setting,
        ];
    }

    public function getData(Request $request)
    {
        $user = auth()->user();

        // جلب البيانات مع تطبيق شروط البحث
        /*
            **الفلترة بالعلاقة لا بالمدى.**

            `accounting_period_id` مختومٌ في السند لحظةَ إنشائه، فالسؤالُ عن
            فترةٍ صار مقارنةَ عمودٍ بمعرّف — لا حدَّين يُحسبان في كلّ شاشة ثمّ
            يُقارَنان بـ`date`.

            وكانت الشاشة تفتح على الجدول كلّه: سنداتُ سنواتٍ مضت في صفحةٍ
            واحدة، والإجماليات أعلاها لا تخصّ الفترة التي يعمل عليها المحاسب.
        */
        $period = AccountingPeriodFilter::resolve($request);

        // سياقُ الفرع من الشريط العلوي — كان السند يُعرض في كل الفروع
        $query = Receipt::with(['account', 'user.branch', 'branch'])
            ->orderBy('id', 'DESC')
            ->when($request->keywords, function ($query, $keywords) {
                return $query->where('code', 'like', '%'.$keywords.'%')->orWhere('description', 'like', '%'.$keywords.'%');
            })
            // مركز التكلفة يسكن سطور القيد لا السند — انظر scopeCostCenter()
            ->when($request->cost_center_id, fn ($q, $center) => $this->scopeCostCenter(
                $q,
                $center,
                ReferenceType::CUSTOMER_COLLECTION->value,
                'reference_number',
                'receipts.code'
            ))
            /*
                فلترُ «ضريبي»: `when` تتخطّى القيمةَ الفارغة، و'0' فارغةٌ
                عندها — فلا تُطبَّق «غير الضريبية». ولهذا يُفحص الوجودُ صراحةً.
            */
            ->when($request->filled('taxable'), function ($query) use ($request) {
                return $query->where('is_taxable', $request->input('taxable') === '1');
            })
            ->when($request->added_by, function ($query, $added_by) {
                return $query->where('created_by', $added_by);
            })
            ->when($request->sub_account, function ($query, $sub_account) {
                return $query->where('account_id', $sub_account);
            })
            // فلترة الفرع: تشمل الفرع المحدد وكل أبنائه (شجرة كاملة)
            ->when($request->branch, function ($query, $branch) {
                $branchIds = $this->resolveBranchTreeIds($branch);

                return $query->whereIn('branch_id', $branchIds);
            });

        // فلترة بناءً على الصلاحيات (عرض الكل أم الخاص به فقط)
        // نطاق البيانات: سنداته هو، أو سندات من يديرهم إن كان يديرهم، أو الكل بلا قيد
        // — ومعها سندات عملائه المسنَدين إليه متى مُنح «عرض سندات قبض العملاء المسندين إليه»
        $this->scopeReceiptsForViewing($query, $this->headerBranchNode());

        // استخدام قيمة per_page من الطلب مع التحقق من صحتها
        $perPage = (int) $request->input('per_page', 10);

        // التحقق من أن القيمة صالحة
        if (! in_array($perPage, [10, 25, 50, 100])) {
            $perPage = 10; // القيمة الافتراضية إذا كانت القيمة غير صالحة
        }

        AccountingPeriodFilter::apply($query, $period);

        $incomes = $query->paginate($perPage);

        // حساب الإجماليات مع مراعاة دور المستخدم
        $totalQuery = Receipt::query()->forBranch($this->headerBranchNode());
        $totalPeriodQuery = AccountingPeriodFilter::apply(Receipt::query()->forBranch($this->headerBranchNode()), $period);
        $totalLast30DaysQuery = Receipt::forBranch($this->headerBranchNode())->where('date', '>=', now()->subDays(30));
        $totalLast365DaysQuery = Receipt::forBranch($this->headerBranchNode())->where('date', '>=', now()->subDays(365));

        $accessibleUserIds = $this->accessibleUserIds();
        if ($accessibleUserIds !== null) {
            $totalQuery->whereIn('created_by', $accessibleUserIds ?: [0]);
            $totalPeriodQuery->whereIn('created_by', $accessibleUserIds ?: [0]);
            $totalLast30DaysQuery->whereIn('created_by', $accessibleUserIds ?: [0]);
            $totalLast365DaysQuery->whereIn('created_by', $accessibleUserIds ?: [0]);
        }

        // تطبيق فلتر الحساب على الإجماليات إذا كان موجوداً
        if ($request->sub_account) {
            $totalQuery->where('account_id', $request->sub_account);
            $totalPeriodQuery->where('account_id', $request->sub_account);
            $totalLast30DaysQuery->where('account_id', $request->sub_account);
            $totalLast365DaysQuery->where('account_id', $request->sub_account);
        }

        // فلترة الفرع على الإجماليات: الفرع المحدد + أبناؤه
        if ($request->branch) {
            $branchIds = $this->resolveBranchTreeIds($request->branch);
            $totalQuery->whereIn('branch_id', $branchIds);
            $totalPeriodQuery->whereIn('branch_id', $branchIds);
            $totalLast30DaysQuery->whereIn('branch_id', $branchIds);
            $totalLast365DaysQuery->whereIn('branch_id', $branchIds);
        }

        $totalPeriod = $totalPeriodQuery->sum(DB::raw('COALESCE(NULLIF(total_amount, 0), amount)'));
        $totalLast30Days = $totalLast30DaysQuery->sum(DB::raw('COALESCE(NULLIF(total_amount, 0), amount)'));
        $totalLast365Days = $totalLast365DaysQuery->sum(DB::raw('COALESCE(NULLIF(total_amount, 0), amount)'));

