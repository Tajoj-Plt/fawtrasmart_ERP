    /**
     * معرّفات العملاء المسموح عرض حساباتهم لهذا المستخدم في سند القبض —
     * `null` فلا قيد (يُعرَضون كلّهم).
     *
     * **محوران لا محور واحد** (قرار صاحب النظام 2026-09-22):
     *
     *   ١. خطّ سير اليوم — `EmployeeClientVisit::eligibleClientIdsForCreate()`،
     *      بحسب إعداد «تقييد إضافة العملاء لخط السير». هذا المحور بخوارزميته
     *      الفردية بلا تغيير — نفس النداء بمعرّف موظفٍ واحد كما كان دائماً.
     *   ٢. من يرى عملاء مَن — `accessibleUserIds()` تحسم الثلاثة: `null`
     *      لمن يملك `data_scope_all` أو ليس موظفاً (مديرٌ غير مرتبط بحساب
     *      موظف) ⇐ بلا قيدٍ هنا إطلاقاً حتى لو كان المحور الأول مفعَّلاً.
     *      موظفٌ عاديٌّ لا يشرف على أحد: مصفوفةٌ من عنصرٍ واحد فيَؤول إلى
     *      نفس نداء المحور الأول بمفرده. ومن يشرف على مجموعة: اتحاد نتيجة
     *      المحور الأول لكلّ من يديرهم + نفسه.
     *
     * مصدرٌ واحد تقرؤه `formData()` (عرضاً) و`store()`/`update()` (حفظاً)
     * — لا نسختان تفترقان.
     */
    /** عامّة — تُنادَى أيضاً من Integration\Api\FinanceController (سند قبض بالجوال). */
    public function eligibleReceiptClientIds(?User $user = null): ?Collection
    {
        $user = $user ?: auth()->user();

        $teamUserIds = $user->isEmployee() ? $this->accessibleUserIds() : null;

        if ($teamUserIds === null) {
            return null;
        }

        if (count($teamUserIds) <= 1) {
            return EmployeeClientVisit::eligibleClientIdsForCreate($user->id);
        }

        $perUser = collect($teamUserIds)->map(
            fn ($uid) => EmployeeClientVisit::eligibleClientIdsForCreate($uid)
        );

        // أيّ عضوٍ في الفريق بلا قيدٍ (إعدادٌ عامّ لا شخصي) يجعل اتحاد الفريق بلا قيد
        return $perUser->contains(null)
            ? null
            : $perUser->flatten()->map(fn ($id) => (int) $id)->unique()->values();
    }

    /**
     * حراسة الحفظ المقابلة لـ eligibleReceiptClientIds() عرضاً: يرمي خطأ
     * تحقّقٍ إن كان عميل الحساب المُرسَل خارج نطاق «عملاء الفريق» لهذا
     * المستخدم — يمنع إرسال `account_id` يدوياً خارج القائمة المعروضة.
     * عميلُ زيارة مساحة العمل الجارية مستثنًى دائماً، كما في القائمة.
     */
    private function assertReceiptAccountInScope(int $accountId): void
    {
        $eligible = $this->eligibleReceiptClientIds();
        if ($eligible === null) {
            return;
        }

        $clientId = (int) Account::whereKey($accountId)->value('client_id');

        $allowed = $eligible
            ->merge(Visit::openWorkspaceClientIdsFor((int) auth()->id()))
            ->map(fn ($id) => (int) $id)
            ->unique();

        if (! $clientId || ! $allowed->contains($clientId)) {
            throw ValidationException::withMessages([
                'account_id' => ['هذا الحساب خارج نطاق عملائك.'],
            ]);
        }
    }

    /**
     * قوائم اختيار شاشة سند القبض — منتزَعةٌ من `create()` لتُستدعى أيضاً
     * من `VisitWorkspaceController::show()` عند تضمين نموذج سند القبض
     * مودالاً في مساحة عمل الزيارة، بدل تكرار منطق نطاق الخزائن والحسابات
     * هناك.
     *
     * @return array<string, mixed>
     */
    public function formData(?int $clientId = null): array
    {
        $user = auth()->user();

        $incomes_categories = ReceiptCategory::select('id', 'name')->get();

        $selectedAccountId = null;

        // معرّفات عملاء خط سير اليوم — أو `null` فلا قيد، بحسب إعداد
        // «تقييد إضافة العملاء لخط السير» في إعدادات وحدات العملاء
        //
        // ونطاقٌ إضافي فوقها — من يرى عملاء مَن (قرار صاحب النظام
        // 2026-09-22): مصدرٌ واحد يستدعيه الحفظ أيضاً — راجع
        // eligibleReceiptClientIds()
        $eligibleClientIds = $this->eligibleReceiptClientIds($user);

        $accountsQuery = Account::with('client')->whereNotNull('client_id');

        if ($eligibleClientIds !== null) {
            $accountsQuery->whereIn('client_id', $eligibleClientIds);
        }

        $accounts = $accountsQuery->get();

        Log::info('فلترة الحسابات حسب خط السير للموظف', [
            'employee_id' => $user->id,
            'restricted' => $eligibleClientIds !== null,
            'accounts_count' => $accounts->count(),
        ]);

        // إذا تم تمرير معرف عميل، ابحث عن حسابه وحدده تلقائياً
        if ($clientId) {
            Client::findOrFail($clientId);
            $selectedAccount = Account::with('client')->ledger()->where('client_id', $clientId)->first();
            if ($selectedAccount) {
                $selectedAccountId = $selectedAccount->id;

                /* القادمُ من شاشة العميل (`?client_id=`) يجد عميلَه في القائمة.
                   كانت القائمة مقصورةً على عملاء خط سير اليوم، فعميلٌ خارجها
                   يُحدَّد معرّفُه ولا خيارَ له في السيلكت — فيفتح السند فارغاً.
                   يُضاف ما دام المستخدم يرى هذا العميل أصلاً. */
                $visibleClientIds = ClientVisibilityScope::eligibleClientIds($user);

                if (! $accounts->contains('id', $selectedAccount->id)
                    && ($visibleClientIds === null || $visibleClientIds->contains($clientId))) {
                    $accounts->prepend($selectedAccount);
                }
            }

            // حسابٌ لم يدخل القائمة لا يُختار سلفاً — كان يُعاد معرّفُه والقائمة
            // خاليةٌ منه، فتختاره الشاشة ثم يرفضه الحفظ «خارج نطاق عملائك»
            if ($selectedAccountId && ! $accounts->contains('id', $selectedAccountId)) {
                $selectedAccountId = null;
            }
        }

        // حساب الرقم التلقائي باستخدام دالة generateCode
        // معاينة بلا استهلاك: الرقم يُحجَز عند الحفظ لا عند فتح النموذج
        $nextCode = peek_document_number('receipt-voucher');

        $MainTreasury = null;
        $treasury_id = null;

        if ($user && $user->employee_id) {
            $TreasuryEmployee = TreasuryEmployee::where('employee_id', $user->employee_id)->first();

            if ($TreasuryEmployee && $TreasuryEmployee->treasury_id) {
                $MainTreasury = Account::where('id', $TreasuryEmployee->treasury_id)->first();
                $treasury_id = $TreasuryEmployee->treasury_id;
            } else {
                $MainTreasury = Account::find(AccountingSettings::id('main_treasury', SystemAccountIds::MAIN_TREASURY));
                $treasury_id = $MainTreasury->id ?? null;
            }
        } else {
            $MainTreasury = Account::find(AccountingSettings::id('main_treasury', SystemAccountIds::MAIN_TREASURY));
            $treasury_id = $MainTreasury->id ?? null;
        }

        if (! $MainTreasury) {
            throw new \Exception('لا توجد خزينة متاحة. يرجى التحقق من إعدادات الخزينة.');
        }

        $taxs = TaxSitting::all();
        $account_setting = AccountSetting::where('user_id', $user->id)->first();
        $branches = Branch::all();

        // خزائنه هو أو خزائن من يديرهم فقط (ScopesToEmployeeHierarchy) — لا
        // كل خزائن المنشأة كما كانت.
        //
        // كانت هذه القائمة تُمرَّر إلى الواجهة باسم `treas` عبر compact()
        // بينما المتغيّر الفعلي `$treasuries` — والقالب يقرأ `$treasuries`،
        // فكانت قائمة الخزائن تصل فارغةً دائماً لكل مدير فتح شاشة سند قبض
        // جديد (`$treasuries ?? []` يُخفي الخطأ بصمت بدل أن يُسقط الصفحة).
        // ولا تُعرض إلا خزينةٌ يجوز له الإيداع فيها: كانت القائمة تعرض
        // خزائن الزملاء، فيُملأ السند كلُّه ثم يُردّ عند الحفظ
        $treasuries = $this->depositableTreasuryAccounts();

        /* والافتراضيُّ من القائمة نفسها: خزينةُ الموظف المعيَّنة قد تكون
           ممنوعةً عليه بشرطها، فلا يصحّ أن تُختار له سلفاً. */
        if ($MainTreasury && $treasuries->isNotEmpty() && ! $treasuries->contains('id', $MainTreasury->id)) {
            $MainTreasury = $treasuries->first();
            $treasury_id = $MainTreasury->id;
        }

        $otherAccounts = $this->otherCounterAccounts();

        return compact(
            'otherAccounts',
            'incomes_categories',
            'taxs',
            'treasuries',
            'accounts',
            'account_setting',
            'nextCode',
            'MainTreasury',
            'treasury_id',
            'selectedAccountId',
            'branches'
        );
    }

