            'description' => 'nullable|string|max:500',
            'attachments' => 'nullable|file|mimes:jpg,jpeg,png,pdf,doc,docx,xls,xlsx|max:5120',
            // الضريبة من «إعدادات الضرائب» — معرّفٌ غير موجود كان يبلغ الحفظ فيسقط 500
            'tax1' => 'nullable|exists:tax_sittings,id',
            'tax2' => 'nullable|exists:tax_sittings,id',
            'tax1_account_id' => 'nullable|exists:accounts,id',
            'tax2_account_id' => 'nullable|exists:accounts,id',
        ], [
            'amount.required' => 'المبلغ مطلوب',
            'amount.numeric' => 'المبلغ يجب أن يكون رقماً',
            'amount.min' => 'المبلغ يجب أن يكون أكبر من صفر',
            'date.required' => 'التاريخ مطلوب',
            'date.date' => 'التاريخ غير صالح',
            'account_id.required' => 'الحساب المقابل مطلوب',
            'account_id.exists' => 'الحساب المحدد غير موجود',
            'treasury_id.required' => 'الخزينة مطلوبة',
            'treasury_id.exists' => 'الخزينة المحددة غير موجودة',
            'incomes_category_id.exists' => 'التصنيف المحدد غير موجود',
            'payment_method_id.exists' => 'طريقة القبض المختارة غير معرَّفة في الإعدادات',
            'attachments.mimes' => 'المرفق يجب أن يكون من نوع: jpg, jpeg, png, pdf, doc, docx, xls, xlsx',
            'attachments.max' => 'حجم المرفق يجب ألا يتجاوز 5 ميجابايت',
        ]);

        // «إضافة ضرائب» بلا اختيار نوعها — لا يُحفظ السند
        TaxableDocument::assertChosenWhenAdded($request->all());

        /*
            الفترة وشرط الإيداع **بعد** التحقّق من المدخلات — كانا قبله،
            فمن كتب المبلغ «مية» جاءه «لا يُسمح لك بالإيداع في الخزينة».
            وسند القبض **إيداعٌ** في الخزينة — يُفحص شرط إيداعها.
        */
        $this->guardPeriod($request->input('date'));
        $this->guardTreasuryDeposit($request->input('treasury_id'));

        // حراسة الحفظ المقابلة لـ formData() عرضاً — منع إرسال account_id
        // يدوياً لعميلٍ خارج نطاق «عملاء الفريق» لهذا المستخدم
        $this->assertReceiptAccountInScope((int) $request->input('account_id'));

        /*
            نقرتان على «حفظ» — أو ضغطٌ ثانٍ قبل استجابة الزرّ لأولاهما —
            كانتا تُنشئان سندي قبضٍ متطابقين فيُقيَّد المبلغ مرّتين على
            الخزينة والعميل معاً.
        */
        $duplicateLock = $this->guardDuplicateSubmission($request, 'income', [
            'amount', 'date', 'account_id', 'treasury_id', 'incomes_category_id', 'description',
        ]);

        try {
            DB::beginTransaction();

            // الحصول على المستخدم الحالي
            $user = auth()->user();

            // إنشاء سند القبض
            $income = new Receipt;
            // توليد الكود تلقائياً
            $income->code = next_document_number('receipt-voucher');
            $income->amount = $request->input('amount');
            $income->description = $request->input('description');
            $income->date = $request->input('date');
            $income->incomes_category_id = $request->input('incomes_category_id');
            $income->seller = $request->input('seller');
            $income->account_id = $request->input('account_id');
            // خزينته هو أو خزينة من يديرهم فقط — لم يكن هذا مقيَّداً هنا
            // إطلاقاً: `treasury_id` كان يُقبل كما أُرسل بلا أي تحقّق نطاق.
            $this->assertTreasuryAccess((int) $request->input('treasury_id'));
            $income->treasury_id = $request->input('treasury_id');
            // طريقة الدفع من شاشة الإعدادات — اختيارية، فقد لا تُسجَّل
            $income->payment_method_id = $request->input('payment_method_id') ?: null;
            $income->is_recurring = $request->has('is_recurring') ? 1 : 0;
            $income->recurring_frequency = $request->input('recurring_frequency');
            $income->end_date = $request->input('end_date');
            $income->tax1 = $request->input('tax1');
            $income->tax2 = $request->input('tax2');
            $income->created_by = auth()->id();
            // مبلغا الضريبة يُحسبان أدناه من معرّف الضريبة المحفوظ،
            // ولا يُؤخذان من الطلب
            /*
                حسابا الضريبة يأتيان من «الحسابات المحاسبية» في الإعدادات
                (`vat_payable` و`vat_paid`) لا من ثابتٍ مكتوب في الشيفرة —
                والنموذج يرسل المعرّف المختار. بلا هذين العمودين كانت مبالغ
                الضريبة تُحفظ في السجلّ ولا تُرحَّل إلى أي حساب في القيد.
            */
            $income->tax1_account_id = $request->input('tax1_account_id') ?: null;
            $income->tax2_account_id = $request->input('tax2_account_id') ?: null;

            /*
                وسمُ «سندٌ ضريبي» يُضبط من المدخلات لا بخانةٍ يؤشّرها
                المستخدم: ما يُترك لتذكّره يُنسى، فيخرج الإقرارُ ناقصاً
                بمقدار ما نُسي. والقاعدةُ في `TaxableDocument` — موضعٌ
                واحد لسندات الصرف والقبض والقيود.
            */
            $income->is_taxable = TaxableDocument::fromVoucherInput($request->all());

            /*
                **الضريبةُ تُحسب هنا، لا تُؤخذ من الطلب.**

                كان `tax1_amount` و`total_amount` يُحفظان كما أرسلهما
                المتصفّح. فمن عبث بالطلب — أو أخطأ حسابُ الشاشة — حُفظ
                رقمُه كما هو، وخرج القيدُ والإقرارُ عليه.

                والحسابُ الآن من **معرّف الضريبة المحفوظ**: النسبةُ
                وطريقتُها من «إعدادات الضرائب» لا من الشاشة.

                **والطريقة المصرية:** الإجمالي يشمل الضريبة دائماً، و`amount`
                يُخزَّن **أساساً قبل الضريبة**. فإن كانت الضريبة «شاملة»
                (`included`) كان ما أدخله المستخدم حاملاً لها، فتُستخرَج منه
                ويُردّ المبلغُ إلى أساسه؛ وإن كانت «مضافة» (`excluded`) فما
                أدخله هو الأساسُ نفسه. وباستقرار `amount` على الأساس يصحّ
                سطرُ الإيراد الدائن في القيد، ويصحّ مجموعُ التقارير:
                `total_amount = amount + الضريبة` في الحالَين.
            */
            $taxLines = TaxCalculator::forDocument($income->amount, $income->tax1, $income->tax2);

            $income->amount = $taxLines['base'];
            $income->tax1_amount = $taxLines['tax1'];
            $income->tax2_amount = $taxLines['tax2'];
            $income->total_amount = $taxLines['total'];
            /*
                مركز التكلفة اختياري ولا يُخزَّن في السند: جدول `receipts`
                لا يحمل إلا الراية، والمركز نفسه يسكن سطور القيد منذ هجرة
                `move_cost_center_to_journal_entry_details`.
            */
            $costCenterId = $request->filled('cost_center_id')
                ? (int) $request->input('cost_center_id')
                : null;

            $income->cost_centers_enabled = $costCenterId !== null ? 1 : 0;
            $income->branch_id = $request->input('branch_id');

            // معالجة المرفقات
            if ($request->hasFile('attachments')) {
                $income->attachments = $this->UploadImage('assets/uploads/incomes', $request->file('attachments'));
            }

            // حفظ سند القبض
            $income->save();

            // تحديث رصيد الخزينة
            // الداخل إلى الخزينة هو الإجمالي شامل الضريبة لا المبلغ قبلها
            $receivedTotal = (float) $income->total_amount;

            $MainTreasury = Account::find($income->treasury_id);
            if ($MainTreasury) {
                $MainTreasury->balance += $receivedTotal;
                $MainTreasury->save();
            }

            // تحديث رصيد حساب العميل
            $clientAccount = Account::find($income->account_id);
            if ($clientAccount) {
                $clientAccount->balance -= $income->amount;
                $clientAccount->save();
            }

            // إنشاء القيد المحاسبي
            $journalEntry = JournalEntry::create([
                'reference_number' => $income->code,
                'date' => $income->date,
                'description' => 'سند قبض رقم '.$income->code,
                'status' => 1,
                'currency' => $income->documentCurrency(),
                'client_id' => $clientAccount->client_id ?? null,
                'reference_type' => ReferenceType::CUSTOMER_COLLECTION,
                'linking_type' => LinkingType::SINGLE,
                'created_by_employee' => $user->id,
                'approved_by_employee' => $user->id,
            ]);

            /*
                **ما كان**

                سطران اثنان لا غير: الخزينة مدينة بالمبلغ، والحساب المقابل
                دائن به. فمبلغ الضريبة المحسوب في الشاشة والمحفوظ في السجلّ
                لا يُرحَّل إلى أي حساب — لا يظهر في «ضريبة القيمة المضافة
                المحصَّلة» ولا في الإقرار الضريبي، والمقبوض فعلاً في الخزينة
                أكبر ممّا يقوله القيد.

                **ما صار**

                الخزينة تُدين بالإجمالي شامل الضريبة، والحساب المقابل يُدان
                بالمبلغ قبلها، وكل ضريبةٍ تُرحَّل دائنةً إلى حسابها المضبوط
                في «الحسابات المحاسبية» — فيتوازن القيد ويصحّ الإقرار.
            */
            $tax1Amount = (float) $income->tax1_amount;
            $tax2Amount = (float) $income->tax2_amount;
            // الإجمالي شامل الضريبة — كما حُسب عند الحفظ
            $grossAmount = (float) $income->total_amount;

            JournalEntryDetail::create([
                'journal_entry_id' => $journalEntry->id,
                'account_id' => $MainTreasury->id,
                'description' => 'استلام مبلغ من سند قبض',
                'debit' => $grossAmount,
                'credit' => 0,
                'is_debit' => true,
            ]);

            JournalEntryDetail::create([
                'journal_entry_id' => $journalEntry->id,
                'account_id' => $income->account_id,
                'description' => 'إيرادات من سند قبض',
                'debit' => 0,
                'credit' => $income->amount,
                'is_debit' => false,
                // المركز على سطر الإيراد وحده: تحميل الخزينة به يُضاعف
                // الرقم في تقرير مراكز التكلفة
                'cost_center_id' => $costCenterId,
            ]);

            /*
                **سطرا الضريبة لا يجوز أن يسقطا.**

                الخزينة تُدان بالإجمالي شاملاً الضريبة، بينما كان سطرُ
                الضريبة الدائن مشروطاً باختيار المستخدم حساباً لها. فمن
                أدخل ضريبةً ولم يختر حسابها خرج قيدُه **غير متوازن**
                بمقدارها — والإقرارُ ناقصاً بها.

                والحساب يُلتمس من «الحسابات المحاسبية» (`vat_payable` —
                ضريبة المبيعات المستحقّة، وهي وجهةُ ضريبة الإيراد) متى لم
                يُختر، وإلا رُمي الخطأ بدل حفظ قيدٍ مختلّ.
            */
            $resolveTaxAccount = function ($chosen) {
                if ($chosen && Account::whereKey($chosen)->exists()) {
                    return (int) $chosen;
                }

                $fallback = AccountingSettings::id('vat_payable', SystemAccountIds::VAT_PAYABLE);

                if (! $fallback || ! Account::whereKey($fallback)->exists()) {
                    throw new \RuntimeException(
                        'تعذّر تحديد حساب الضريبة: اختر حساباً للضريبة في السند، '
                        .'أو اضبط «ضريبة المبيعات المستحقّة» في الحسابات المحاسبية.'
                    );
                }

                return (int) $fallback;
            };

            foreach ([
                [$tax1Amount, $income->tax1_account_id, 'الضريبة الأولى'],
                [$tax2Amount, $income->tax2_account_id, 'الضريبة الثانية'],
            ] as [$taxAmount, $chosenAccount, $taxLabel]) {
                if ($taxAmount <= 0) {
                    continue;
                }

                JournalEntryDetail::create([
                    'journal_entry_id' => $journalEntry->id,
                    'account_id' => $resolveTaxAccount($chosenAccount),
                    'description' => 'ضريبة القيمة المضافة — '.$taxLabel,
                    'debit' => 0,
                    'credit' => $taxAmount,
                    'is_debit' => false,
                    'cost_center_id' => $costCenterId,
                ]);
            }

            /*
                نسخةُ «سند مكرَّر» يُصدرها `RecurringVoucherGenerator` تمرّ بهذه
                الدالّة نفسها — القيدُ والخزينة والترقيم كسندٍ يدوي — لكنّها لا
                توزَّع على فواتير العميل، ولا تُكمل زيارةَ اليوم، ولا تمنح نقاطاً:
                لم يقبض أحدٌ شيئاً من فاتورةٍ بعينها ولم يزر أحدٌ عميلاً.
                والسِّمةُ في `attributes` لا تصل من مدخلات HTTP.
            */
            $isRecurringCopy = RecurringVoucherGenerator::isGenerating($request);

            // تسديد الفواتير تلقائياً بعد إنشاء القيد المحاسبي
            $account = Account::with('client')->find($income->account_id);
            if ($account && $account->client && ! $isRecurringCopy) {
                $this->applyPaymentToInvoices($account->client->id, $income->amount, $income->id, $journalEntry->id, $income->date);
            }

            // تعليم زيارة اليوم مكتملة — لا «آخر زيارة» بلا تقييدٍ بالتاريخ
            if ($account && $account->client && ! $isRecurringCopy) {
                EmployeeClientVisit::markCompletedFor(auth()->id(), $account->client->id);
            }

            // إشعار الإنشاء
            $income_account_name = Account::find($income->account_id);

            notifications::create([
                'user_id' => $user->id,
                'type' => 'Receipt',
                'title' => $user->name.' أنشأ سند قبض',
                'description' => 'سند قبض رقم '.$income->code.' لـ '.$income_account_name->name.' بقيمة '.number_format($income->amount, 2).' ر.س',
            ]);

            // تسجيل النشاط
            OperationLog::record(
                'created',
                'finance_log',
                $income->id,
                sprintf('تم انشاء سند قبض رقم **%s** بقيمة **%d**', $income->code, $income->amount)
            );

            // ** إضافة ملاحظة تلقائية للعميل مع الحفاظ على العهدة التراكمية **
            if ($clientAccount && $clientAccount->client_id) {
                try {
                    // جلب آخر عهدة مسجلة للعميل
                    $lastClientNote = ClientRelation::where('client_id', $clientAccount->client_id)
                        ->whereNotNull('deposit_count')
                        ->where('deposit_count', '>', 0)
                        ->orderBy('created_at', 'desc')
                        ->first();

                    // الحفاظ على العهدة كما هي
                    $currentDeposit = $lastClientNote ? intval($lastClientNote->deposit_count) : 0;

                    // إنشاء الملاحظة التلقائية
                    ClientRelation::create([
                        'client_id' => $clientAccount->client_id,
                        'employee_id' => auth()->id(),
                        'type' => 'invoice', // نستخدم invoice ليظهر في نفس السياق
                        'invoice_id' => null,
                        'description' => 'سند قبض رقم: '.$income->code.' - القيمة: '.number_format($income->amount, 2).' ر.س',
                        'deposit_count' => $currentDeposit,
                        'date' => now()->toDateString(),
                        'time' => now()->toTimeString(),
                        'status' => 'completed',
                        'process' => 'سند قبض',
                        'additional_data' => ['receipt_id' => $income->id],
                    ]);

                    Log::info('تم إنشاء ملاحظة تلقائية لسند القبض', [
                        'client_id' => $clientAccount->client_id,
                        'receipt_id' => $income->id,
                        'deposit_count' => $currentDeposit,
                    ]);
                } catch (\Exception $noteException) {
                    $this->recordFailure($noteException, 'finance_log', 'receipt_note', $income);
                }
            }

            // === معالجة نقاط سند القبض (receipt_created) ===
            // فقط إذا كان المستخدم موظفاً (لديه employee_id) — ولا نقاط لنسخةٍ مولَّدة
            if ($user->employee_id && ! $isRecurringCopy) {
                try {
                    $pointsContext = [
                        'employee_id' => $user->employee_id,
                        'client_id' => $clientAccount->client_id ?? null,
                        'amount' => $income->amount,
                        'branch_id' => $income->branch_id,
                        'reference_type' => Receipt::class,
                        'reference_id' => $income->id,
                        'description' => 'سند قبض رقم '.$income->code,
                    ];
                    app(PointsService::class)->processAction('receipt_created', $pointsContext);
                } catch (\Throwable $e) {
                    // النقاط أثرٌ جانبي: لا تُسقط السند، لكنّها تُسجَّل حيث تُرى
                    $this->recordFailure($e, 'finance_log', 'receipt_points', $income);
                }
            }

            DB::commit();

            $this->recordOperation(
                'created',
                'Receipt',
                $income,
                'تم إنشاء سند قبض رقم <strong>'.$income->code.'</strong> بمبلغ '.$income->formatMoney($income->amount)
            );

            /* شاشة الإنشاء تُرسل بـ`fetch` وتنتظر JSON (`data.success`
               و`data.redirect`). كان الردّ إعادة توجيهٍ يتبعها `fetch`
               صامتاً إلى صفحة HTML فيفشل `response.json()` — فيظهر «خطأ في
               الشبكة» لسندٍ حُفظ فعلاً، ولا يعود المندوب إلى زيارته
               (`ReturnToVisitWorkspace` يستبدل `redirect` هنا). */
            if ($request->ajax() || $request->wantsJson()) {
                return response()->json([
                    'success' => true,
                    'message' => 'تم إضافة سند القبض بنجاح!',
                    'redirect' => route('incomes.index'),
                ]);
            }

            return redirect()->route('incomes.index')->with('success', 'تم إضافة سند القبض بنجاح!');
        } catch (ValidationException $e) {
            // تحقّقٌ مرفوض ليس تكراراً فعلياً — يُفكّ القفل فوراً ليعيد
            // المندوب المحاولة بعد تصحيح البيانات بلا انتظار مهلته
            $duplicateLock->release();

            // كان الاستثناء يُبتلع: يُبلَّغ المستخدم بخطأ ولا يبقى منه أثر
            OperationLog::failure($e, 'Account.Incomes', 'store');

            /*
                خطأ التحقّق لا يُبتلع مع بقيّة الأخطاء.

                كان `catch` العامّ يلتقطه ويعرضه شريطَ تنبيهٍ يحمل نصّ لارافيل
                الإنجليزي — «The incomes category id field is required» —
                بلا إشارةٍ إلى الحقل الناقص. الآن يعود إلى النموذج مُعلَّقاً
                على حقله برسالته العربية.
            */
            if (DB::transactionLevel() > 0) {
                DB::rollBack();
            }

            if (request()->ajax() || request()->wantsJson()) {
                return response()->json([
                    'success' => false,
                    'message' => 'خطأ في البيانات المدخلة',
                    'errors' => $e->errors(),
                ], 422);
            }

            return back()->withErrors($e->errors())->withInput();
        } catch (\Throwable $e) {
            // فشل الحفظ فعلاً: يُفكّ القفل فوراً ليعيد المندوب المحاولة
            $duplicateLock->release();

            // كان الاستثناء يُبتلع: يُبلَّغ المستخدم بخطأ ولا يبقى منه أثر
            OperationLog::failure($e, 'Account.Incomes', 'store');

            DB::rollBack();

            $message = $this->recordFailure($e, 'Receipt', 'store');

            if ($request->ajax() || $request->wantsJson()) {
                // بلوغ حدّ الباقة قاعدةُ عملٍ لا عطل — 402 برسالته، كوسيط plan.limit
                if ($e instanceof PlanLimitExceededException) {
                    return response()->json(['success' => false, 'message' => $e->getMessage(), 'code' => 'PLAN_LIMIT_REACHED'], 402);
                }

                return response()->json(['success' => false, 'message' => $message], 500);
            }

            return back()
                ->withInput()
                ->with('error', $message);
        }
    }

    public function update(Request $request, $id)
    {
        try {
            DB::beginTransaction();

            // البحث عن السند أولاً
            $income = Receipt::findOrFail($id);

            // التحقق من الصلاحية
            $this->authorizeCreatorScope($income->created_by);

            $request->validate([
                'code' => 'required',
                'amount' => 'required|numeric',
                'date' => 'required|date',
                'account_id' => 'required',

                'incomes_category_id' => 'required',
                'treasury_id' => 'required|exists:accounts,id',
                'cost_center_id' => 'nullable|exists:cost_centers,id',
                'payment_method_id' => 'nullable|exists:payment_methods,id',
                // الضريبة من «إعدادات الضرائب» — معرّفٌ غير موجود كان يبلغ الحفظ فيسقط 500
                'tax1' => 'nullable|exists:tax_sittings,id',
                'tax2' => 'nullable|exists:tax_sittings,id',
                'tax1_account_id' => 'nullable|exists:accounts,id',
                'tax2_account_id' => 'nullable|exists:accounts,id',
            ]);

            // «إضافة ضرائب» بلا اختيار نوعها — لا يُحفظ السند
            TaxableDocument::assertChosenWhenAdded($request->all());

            // الفترة وشرط الإيداع بعد التحقّق — والتعديل قد ينقل السند إلى خزينةٍ أخرى
            $this->guardPeriod($request->input('date'));
            $this->guardTreasuryDeposit($request->input('treasury_id'));

            // حراسة الحفظ المقابلة لـ formData() عرضاً — منع إرسال account_id
            // يدوياً لعميلٍ خارج نطاق «عملاء الفريق» لهذا المستخدم
            $this->assertReceiptAccountInScope((int) $request->input('account_id'));

            // البحث باستخدام النموذج الصحيح (Receipt بدلاً من Income)
            $income = Receipt::findOrFail($id);

            // حفظ القيم القديمة
            $oldCode = $income->code; // حفظ الكود القديم للبحث عن القيد
            $oldAmount = $income->amount;
            $oldAccountId = $income->account_id;
            $oldTreasuryId = $income->treasury_id;

            /*
                خزينة السند لم تكن تُحدَّث هنا إطلاقاً — القيمة المرسلة من
                نموذج التعديل كانت تُقرأ في `$oldTreasuryId` وحده، ولا سطر
                يكتبها في `$income->treasury_id`، فيبقى السند على خزينته
                الأصلية مهما اختار المستخدم. ويترتّب على ذلك أن فرع «تغيّرت
                الخزينة» في `updateAccountBalances()` (المقارنة
                `$oldTreasuryId == $income->treasury_id`) كان ميتاً دائماً:
                القيمتان متطابقتان حتماً لأن الثانية لم تتغيّر قط.

                التحقّق من النطاق قبل الإسناد: خزينته هو أو خزينة من يديرهم
                فقط.
            */
            $this->assertTreasuryAccess((int) $request->input('treasury_id'));
            $income->treasury_id = $request->input('treasury_id');

            // تحديث البيانات - الكود لا يتغير (يبقى كما هو)
            // $income->code = $income->code; // الكود ثابت لا يتم تغييره
            $income->amount = $request->input('amount');
            $income->description = $request->input('description');
            $income->date = $request->input('date');
            $income->incomes_category_id = $request->input('incomes_category_id');
            $income->seller = $request->input('seller');
            $income->account_id = $request->input('account_id');
            $income->is_recurring = $request->has('is_recurring') ? 1 : 0;
            $income->recurring_frequency = $request->input('recurring_frequency');
            $income->end_date = $request->input('end_date');
            $income->tax1 = $request->input('tax1');
            $income->tax2 = $request->input('tax2');
            // مبلغا الضريبة يُحسبان أدناه من معرّف الضريبة المحفوظ،
            // ولا يُؤخذان من الطلب
            /*
                حسابا الضريبة يأتيان من «الحسابات المحاسبية» في الإعدادات
                (`vat_payable` و`vat_paid`) لا من ثابتٍ مكتوب في الشيفرة —
                والنموذج يرسل المعرّف المختار. بلا هذين العمودين كانت مبالغ
                الضريبة تُحفظ في السجلّ ولا تُرحَّل إلى أي حساب في القيد.
            */
            $income->tax1_account_id = $request->input('tax1_account_id') ?: null;
            $income->tax2_account_id = $request->input('tax2_account_id') ?: null;

            /*
                وسمُ «سندٌ ضريبي» يُضبط من المدخلات لا بخانةٍ يؤشّرها
                المستخدم: ما يُترك لتذكّره يُنسى، فيخرج الإقرارُ ناقصاً
                بمقدار ما نُسي. والقاعدةُ في `TaxableDocument` — موضعٌ
                واحد لسندات الصرف والقبض والقيود.
            */
            $income->is_taxable = TaxableDocument::fromVoucherInput($request->all());

            /*
                **الضريبةُ تُحسب هنا، لا تُؤخذ من الطلب.**

                كان `tax1_amount` و`total_amount` يُحفظان كما أرسلهما
                المتصفّح. فمن عبث بالطلب — أو أخطأ حسابُ الشاشة — حُفظ
                رقمُه كما هو، وخرج القيدُ والإقرارُ عليه.

                والحسابُ الآن من **معرّف الضريبة المحفوظ**: النسبةُ
                وطريقتُها من «إعدادات الضرائب» لا من الشاشة.

                **والطريقة المصرية:** الإجمالي يشمل الضريبة دائماً، و`amount`
                يُخزَّن **أساساً قبل الضريبة**. فإن كانت الضريبة «شاملة»
                (`included`) كان ما أدخله المستخدم حاملاً لها، فتُستخرَج منه
                ويُردّ المبلغُ إلى أساسه؛ وإن كانت «مضافة» (`excluded`) فما
                أدخله هو الأساسُ نفسه. وباستقرار `amount` على الأساس يصحّ
                سطرُ الإيراد الدائن في القيد، ويصحّ مجموعُ التقارير:
                `total_amount = amount + الضريبة` في الحالَين.
            */
            $taxLines = TaxCalculator::forDocument($income->amount, $income->tax1, $income->tax2);

            $income->amount = $taxLines['base'];
            $income->tax1_amount = $taxLines['tax1'];
            $income->tax2_amount = $taxLines['tax2'];
            $income->total_amount = $taxLines['total'];
            // طريقة الدفع من شاشة الإعدادات — اختيارية، فقد لا تُسجَّل
            $income->payment_method_id = $request->input('payment_method_id') ?: null;
            /*
                مركز التكلفة اختياري ولا يُخزَّن في السند: جدول `receipts`
                لا يحمل إلا الراية، والمركز نفسه يسكن سطور القيد منذ هجرة
                `move_cost_center_to_journal_entry_details`.
            */
            $costCenterId = $request->filled('cost_center_id')
                ? (int) $request->input('cost_center_id')
                : null;

            $income->cost_centers_enabled = $costCenterId !== null ? 1 : 0;

            // تعيين الفرع تلقائياً إذا كان المستخدم موظفاً
            $user = auth()->user();
            if ($user->isEmployee() && $user->branch_id) {
                $income->branch_id = $user->branch_id;
            } else {
                $income->branch_id = $request->input('branch_id');
            }

            // معالجة المرفقات
            if ($request->hasFile('attachments')) {
                $income->attachments = $this->UploadImage('assets/uploads/incomes', $request->file('attachments'));
            }

            $income->save();

            // الحصول على القيد المحاسبي المرتبط
            $journalEntry = JournalEntry::where('reference_number', $income->code)->first();

            if ($journalEntry) {
                // حذف المدفوعات القديمة والروابط المرتبطة بالسند
                $this->reversePaymentFromInvoices($income->id, $journalEntry->id);

                // تحديث أرصدة الحسابات
                $this->updateAccountBalances($income, $oldAmount, $oldAccountId, $oldTreasuryId);

                // تحديث القيد المحاسبي
                $this->updateJournalEntry($income, $journalEntry, $costCenterId);

                // إعادة تسديد الفواتير بالمبلغ الجديد مع ربطها بالقيد
                $account = Account::with('client')->find($income->account_id);
                if ($account && $account->client) {
                    $this->applyPaymentToInvoices($account->client->id, $income->amount, $income->id, $journalEntry->id, $income->date);
                }
            } else {
                Log::warning('لم يتم العثور على قيد محاسبي للسند #'.$income->id);
            }

            DB::commit();

            // التحقق إذا كان الطلب AJAX
            if (request()->ajax() || request()->wantsJson()) {
                return response()->json([
                    'success' => true,
                    'message' => 'تم تعديل سند القبض بنجاح',
                    'redirect' => route('incomes.index'),
                ]);
            }

            OperationLog::record('updated', 'Account.Incomes', $income ?? $id,
                'عدّل سند القبض رقم '.($income->code ?? $id));

            return redirect()->route('incomes.index')->with('success', 'تم تعديل سند القبض بنجاح');
        } catch (ValidationException $e) {
            /*
                خطأ التحقّق لا يُبتلع مع بقيّة الأخطاء.

                كان `catch` العامّ يلتقطه ويعرضه شريطَ تنبيهٍ يحمل نصّ لارافيل
                الإنجليزي — «The incomes category id field is required» —
                بلا إشارةٍ إلى الحقل الناقص. الآن يعود إلى النموذج مُعلَّقاً
                على حقله برسالته العربية.
            */
            if (DB::transactionLevel() > 0) {
                DB::rollBack();
            }

            if (request()->ajax() || request()->wantsJson()) {
                return response()->json([
                    'success' => false,
                    'message' => 'خطأ في البيانات المدخلة',
                    'errors' => $e->errors(),
                ], 422);
            }

            return back()->withErrors($e->errors())->withInput();
        } catch (\Exception $e) {
            // يبلغ جدول «سجلّ الأخطاء»، لا ملفّ اللوق وحده
            OperationLog::failure($e, 'Account.Incomes', 'update');

            DB::rollback();
            Log::error('خطأ في تعديل سند قبض: '.$e->getMessage().' | Stack: '.$e->getTraceAsString());

            // التحقق إذا كان الطلب AJAX
            if (request()->ajax() || request()->wantsJson()) {
                return response()->json([
                    'success' => false,
                    'message' => 'حدث خطأ أثناء تعديل سند القبض: '.$e->getMessage(),
                ], 422);
            }

            return back()
                ->with('error', 'حدث خطأ أثناء تعديل سند القبض: '.$e->getMessage())
                ->withInput();
        }
    }

    private function updateAccountBalances($income, $oldAmount, $oldAccountId, $oldTreasuryId)
    {
        // تحديث رصيد الحساب (العميل)
        if ($oldAccountId == $income->account_id) {
            $account = Account::find($income->account_id);
            if ($account) {
                $account->balance += $oldAmount; // نرجع المبلغ القديم
                $account->balance -= $income->amount; // نطرح المبلغ الجديد
                $account->save();
            }
        } else {
            // رجع المبلغ للحساب القديم
            $oldAccount = Account::find($oldAccountId);
            if ($oldAccount) {
                $oldAccount->balance += $oldAmount;
                $oldAccount->save();
            }

            // خصم المبلغ من الحساب الجديد
            $newAccount = Account::find($income->account_id);
            if ($newAccount) {
                $newAccount->balance -= $income->amount;
                $newAccount->save();
            }
        }

        // تحديث الخزينة
        if ($oldTreasuryId == $income->treasury_id) {
            $treasury = Account::find($income->treasury_id);
            if ($treasury) {
                $treasury->balance -= $oldAmount; // نقص القديم
                $treasury->balance += $income->amount; // أضف الجديد
                $treasury->save();
            }
        } else {
            // طرح المبلغ من الخزينة القديمة
            $oldTreasury = Account::find($oldTreasuryId);
            if ($oldTreasury) {
                $oldTreasury->balance -= $oldAmount;
                $oldTreasury->save();
            }

            // إضافة المبلغ للخزينة الجديدة
            $newTreasury = Account::find($income->treasury_id);
            if ($newTreasury) {
                $newTreasury->balance += $income->amount;
                $newTreasury->save();
            }
        }
    }

    /**
     * @param  int|null  $costCenterId  مركز التكلفة الجديد — `null` يمسح القديم
     */
    private function updateJournalEntry($income, $journalEntry, $costCenterId = null)
    {
        // تحديث بيانات القيد الأساسي
        $journalEntry->date = $income->date;
        $journalEntry->description = 'سند قبض رقم '.$income->code;
        $journalEntry->status = 1; // معتمد
        $journalEntry->approved_by_employee = auth()->id(); // المعتمد
        $journalEntry->save();

        $tax1Amount = (float) $income->tax1_amount;
        $tax2Amount = (float) $income->tax2_amount;
        // الإجمالي شامل الضريبة — كما حُسب عند الحفظ
        $grossAmount = (float) $income->total_amount;

        /*
            **ما كان**

            التعديل يبحث عن «أوّل سطرٍ مدين» و«أوّل سطرٍ دائن» ويحدّثهما،
            ويترك ما عداهما. فسطور الضريبة — إن وُجدت — تبقى على قيمها
            القديمة بعد تغيير المبلغ، ولو أُزيلت الضريبة بقيت سطورها في
            القيد إلى الأبد: قيدٌ لا يتوازن ولا يوافق سنده.

            **ما صار**

            تُمحى سطور القيد وتُبنى من جديد من حالة السند بعد التعديل —
            وهو ما يفعله سند الصرف أصلاً. القيد أربعة سطور على الأكثر،
            فإعادة بنائه أرخص من مطاردة أيّها تغيّر.
        */
        JournalEntryDetail::where('journal_entry_id', $journalEntry->id)->delete();

        JournalEntryDetail::create([
            'journal_entry_id' => $journalEntry->id,
            'account_id' => $income->treasury_id,
            'description' => 'استلام مبلغ من سند قبض',
            'debit' => $grossAmount,
            'credit' => 0,
            'is_debit' => true,
        ]);

        JournalEntryDetail::create([
            'journal_entry_id' => $journalEntry->id,
            'account_id' => $income->account_id,
            'description' => 'إيرادات من سند قبض',
            'debit' => 0,
            'credit' => $income->amount,
            'is_debit' => false,
            // إزالة المركز عند التعديل تُمسح فعلاً لا تُترك على القديم
            'cost_center_id' => $costCenterId,
        ]);

        /*
            **سطرا الضريبة لا يجوز أن يسقطا.**

            الخزينة تُدان بالإجمالي شاملاً الضريبة، بينما كان سطرُ
            الضريبة الدائن مشروطاً باختيار المستخدم حساباً لها. فمن
            أدخل ضريبةً ولم يختر حسابها خرج قيدُه **غير متوازن**
            بمقدارها — والإقرارُ ناقصاً بها.

            والحساب يُلتمس من «الحسابات المحاسبية» (`vat_payable` —
            ضريبة المبيعات المستحقّة، وهي وجهةُ ضريبة الإيراد) متى لم
            يُختر، وإلا رُمي الخطأ بدل حفظ قيدٍ مختلّ.
        */
        $resolveTaxAccount = function ($chosen) {
            if ($chosen && Account::whereKey($chosen)->exists()) {
                return (int) $chosen;
            }

            $fallback = AccountingSettings::id('vat_payable', SystemAccountIds::VAT_PAYABLE);

            if (! $fallback || ! Account::whereKey($fallback)->exists()) {
                throw new \RuntimeException(
                    'تعذّر تحديد حساب الضريبة: اختر حساباً للضريبة في السند، '
                    .'أو اضبط «ضريبة المبيعات المستحقّة» في الحسابات المحاسبية.'
                );
            }

            return (int) $fallback;
        };

        foreach ([
            [$tax1Amount, $income->tax1_account_id, 'الضريبة الأولى'],
            [$tax2Amount, $income->tax2_account_id, 'الضريبة الثانية'],
        ] as [$taxAmount, $chosenAccount, $taxLabel]) {
            if ($taxAmount <= 0) {
                continue;
            }

            JournalEntryDetail::create([
                'journal_entry_id' => $journalEntry->id,
                'account_id' => $resolveTaxAccount($chosenAccount),
                'description' => 'ضريبة القيمة المضافة — '.$taxLabel,
                'debit' => 0,
                'credit' => $taxAmount,
                'is_debit' => false,
                'cost_center_id' => $costCenterId,
            ]);
        }
    }

    /**
     * عملاء المستخدم المسنَدون إليه (`client_employee.employee_id` = `employees.id`) متى مُنح
     * `account.incomes.view_assigned_clients` — و`null` بلا الصلاحية أو بلا سجلّ موظف.
     */
    public function assignedClientIdsForReceipts(): ?array
    {
        $user = auth()->user();
        if (! $user || ! $user->employee_id || ! $user->hasRolePermission('account.incomes.view_assigned_clients')) {
            return null;
        }

        return DB::table('client_employee')->where('employee_id', $user->employee_id)->distinct()->pluck('client_id')->map(fn ($id) => (int) $id)->all();
    }

    /**
     * نطاقُ **العرض** لسندات القبض: فرعُ الشريط ونطاقُ المنشئ (سنداته وفريقه، أو الكلّ)، وفوقه سنداتُ
     * عملائه المسنَدين إليه — بعميل السند أو بحسابه، ومن أيّ فرع. التعديل والإلغاء على نطاق المنشئ وحده.
     */
    private function scopeReceiptsForViewing($query, $branchNode = null)
    {
        $creators = $this->accessibleUserIds();
        $assigned = $creators === null ? null : $this->assignedClientIdsForReceipts();
        if (! $assigned) {
            $query->forBranch($branchNode);

            return $creators === null ? $query : $query->whereIn('created_by', $creators ?: [0]);
        }

        // سنداتُه وفريقه بفرع الشريط، أو سندُ عميلٍ مسنَدٍ إليه من أيّ فرعٍ قُبض فيه
        return $query->where(fn ($q) => $q->where(fn ($own) => $own->forBranch($branchNode)->whereIn('created_by', $creators ?: [0]))
            ->orWhereIn('client_id', $assigned)
            ->orWhereIn('account_id', Account::ledger()->whereIn('client_id', $assigned)->select('id')));
    }

    /** يجوز للمستخدم **عرض** هذا السند (تفاصيله وطباعته) — نطاقُ المنشئ أو عميلٌ مسنَدٌ إليه */
    public function canViewReceipt(Receipt $income): bool
    {
        if ($this->canAccessCreator($income->created_by)) {
            return true;
        }
        $assigned = $this->assignedClientIdsForReceipts();
        if (! $assigned) {
            return false;
        }
        if ($income->client_id && in_array((int) $income->client_id, $assigned, true)) {
            return true;
        }

        return $income->account_id
            && Account::ledger()->where('id', $income->account_id)->whereIn('client_id', $assigned)->exists();
    }

    public function show($id)
    {
        $income = Receipt::with(['branch', 'account', 'user', 'incomes_category', 'treasury'])->findOrFail($id);

        // نطاق العرض: سنداته وفريقه (أو الكلّ)، وسندات عملائه المسنَدين إليه متى مُنح صلاحيتها
        abort_unless($this->canViewReceipt($income), 403, 'لا تملك صلاحية الوصول إلى هذا السجل.');

        // جلب القيد المحاسبي المرتبط بالسند
        // البحث باستخدام code السند و reference_type = REC (CUSTOMER_COLLECTION)
        $journalEntry = JournalEntry::with('details')
            ->where('reference_number', $income->code)
            ->where('reference_type', ReferenceType::CUSTOMER_COLLECTION)
            ->first();

        // إذا لم يتم العثور عليه، جرب البحث باستخدام RECEIPT_VOUCHER
        if (! $journalEntry) {
            $journalEntry = JournalEntry::with('details')
                ->where('reference_number', $income->code)
                ->where('reference_type', ReferenceType::RECEIPT_VOUCHER)
                ->first();
        }

        // جلب سجل النشاطات - استخدام type و type_id بدلاً من loggable_type و loggable_id
        $logs = ModelsLog::where('type', 'receipt')
            ->where('type_id', $income->id)
            ->with('user.branch')
            ->orderBy('created_at', 'desc')
            ->get()
            ->groupBy(function ($log) {
                return $log->created_at->format('Y-m-d');
            });

        // العرضُ أُجيز أعلاه بنطاقه (منشئه أو عميلٌ مسنَد) — والتعديلُ على نطاق المنشئ وحده (`edit()`)،
        // فسندُ عميلٍ مسنَدٍ يُعرض بلا زرّ تعديل. لا صلاحيات النظام القديم
        // (`finance_edit_delete_own/all_receipts`)
        $canEdit = auth()->user()->hasRolePermission('account.incomes.edit') && $this->canAccessCreator($income->created_by);

        return view('account::finance.incomes.show', compact('income', 'journalEntry', 'logs', 'canEdit'));
    }

    public function edit($id)
    {
        $income = Receipt::findOrFail($id);

        // التحقق من النطاق
        $this->authorizeCreatorScope($income->created_by);

        $incomes_categories = ReceiptCategory::select('id', 'name')->get();
        $accounts = Account::all();
        $taxs = TaxSitting::all();

        $user = Auth::user();

        // جلب خزينة الموظف الافتراضية (تُستخدم إذا كان المستخدم موظفاً)
        $MainTreasury = null;
        if ($user && $user->employee_id) {
            $TreasuryEmployee = TreasuryEmployee::where('employee_id', $user->employee_id)->first();
            if ($TreasuryEmployee && $TreasuryEmployee->treasury_id) {
                $MainTreasury = Account::find($TreasuryEmployee->treasury_id);
            }
        }
        // إذا لم يكن للموظف خزينة أو كان المستخدم مديراً، استخدم خزينة السند الحالية
        if (! $MainTreasury) {
            $MainTreasury = Account::find($income->treasury_id);
        }

        $account_setting = AccountSetting::where('user_id', auth()->user()->id)->first();
        $branches = Branch::all();

        // خزائنه هو أو خزائن من يديرهم، ثم ما يجوز له الإيداع فيه — وخزينةُ
        // السند الحالية تبقى معروضةً وإن مُنعت، وإلّا ضاعت قيمتُه المحفوظة
        $treasuries = $this->depositableTreasuryAccounts($income->treasury_id);

        // المركز مسجَّلٌ في سطر القيد لا في السند — انظر شاشة المصروفات
        $currentCostCenterId = optional(
            JournalEntryDetail::whereIn(
                'journal_entry_id',
                JournalEntry::where('reference_number', $income->code)->select('id')
            )->whereNotNull('cost_center_id')->first()
        )->cost_center_id;

        // القائمة في التعديل كانت `Account::all()` — بما فيها الحسابات الأب
        // التي لا يُقيَّد عليها؛ صارت كقائمة الإضافة: عملاءُ ثمّ طرفيّات
        $accounts = Account::with('client')->whereNotNull('client_id')->orderBy('code')->get();
        $otherAccounts = $this->otherCounterAccounts();

        return view('account::finance.incomes.edit', compact('income', 'incomes_categories', 'accounts', 'otherAccounts', 'taxs', 'account_setting', 'MainTreasury', 'branches', 'treasuries', 'currentCostCenterId'));
    }

