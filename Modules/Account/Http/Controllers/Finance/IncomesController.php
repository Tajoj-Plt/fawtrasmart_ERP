    public function print($id, $type = 'normal')
    {
        $income = Receipt::findOrFail($id);

        /* قالبٌ من «قوالب المستندات» (النوع `receipt_voucher` — مُطبِّعه في
           `DocumentTemplateDataService` يقرأ `receipts` نفسها) متى طُلب بـ
           `?template=`. كانت هذه الطباعة لا تعرف القوالب أصلاً: نسختان
           مدمجتان فقط، ومن صمّم قالب سند قبضٍ لا سبيل له إليه من هنا. بلا
           المعامل تبقى النسختان المدمجتان كما كانتا. */
        if (is_numeric($templateId = request('template'))) {
            $template = DocumentTemplate::where('id', (int) $templateId)
                ->where('document_type', 'receipt_voucher')
                ->where('is_active', true)
                ->first();

            if ($template) {
                try {
                    $data = app(DocumentTemplateDataService::class)->getDocumentData('receipt_voucher', $income->id);
                    $html = app(DocumentTemplateRenderer::class)->render($template, $data);

                    return response(DocumentPrintPage::wrap($html));
                } catch (\Throwable $e) {
                    // تعذّر التصيير لا يمنع الطباعة: يُسجَّل وتعود النسخة المدمجة
                    OperationLog::failure($e, 'Account.Incomes', 'print_template', $income);
                }
            }
        }

        if ($type == 'thermal') {
            // عرض نسخة حرارية
            return view('account::finance.incomes.print_thermal', compact('income'));
        } else {
            // عرض نسخة عادية
            return view('account::finance.incomes.print_normal', compact('income'));
        }
    }

    public function cancel($id)
    {
        // قيدٌ عكسي يُرحَّل اليوم — كتابةٌ محاسبية تلزمها حراسة الفترة
        $this->guardPeriod(now()->toDateString());

        try {
            Log::info('======= بداية دالة cancel =======');
            Log::info('معرف السند المراد إلغاؤه: '.$id);

            DB::beginTransaction();

            // البحث عن السند أولاً
            $income = Receipt::findOrFail($id);

            // التحقق من النطاق
            $this->authorizeCreatorScope($income->created_by);

            $user = Auth::user();
            Log::info('تم جلب السند #'.$income->id.' - كود: '.$income->code);

            // استرجاع رصيد الخزينة
            $mainTreasuryAccount = Account::find($income->treasury_id);
            if ($mainTreasuryAccount) {
                $mainTreasuryAccount->balance -= $income->amount;
                $mainTreasuryAccount->save();
                Log::info('تم استرجاع رصيد الخزينة: -'.$income->amount);
            }

            // استرجاع رصيد حساب العميل
            $clientAccount = Account::find($income->account_id);
            if ($clientAccount) {
                $clientAccount->balance += $income->amount;
                $clientAccount->save();
                Log::info('تم استرجاع رصيد حساب العميل: +'.$income->amount);
            }

            // إلغاء المدفوعات المرتبطة بهذا السند
            $this->reversePaymentFromInvoices($income->id);

            // الحصول على القيد المحاسبي المرتبط
            $referenceNumber = $income->code;

            // البحث عن القيد المحاسبي الأصلي
            $originalJournalEntry = JournalEntry::with('details')
                ->where('reference_number', $referenceNumber)
                ->where('status', 1)
                ->where('reference_type', ReferenceType::CUSTOMER_COLLECTION)
                ->orderBy('created_at', 'desc')
                ->first();

            // إذا لم نجد القيد بهذه الطريقة، نبحث عنه بطريقة أخرى
            if (! $originalJournalEntry) {
                $originalJournalEntry = JournalEntry::with('details')
                    ->where('reference_number', $referenceNumber)
                    ->where('status', 1)
                    ->orderBy('created_at', 'desc')
                    ->first();
            }

            if ($originalJournalEntry) {
                // إنشاء قيد عكسي بدلاً من حذف القيد الأصلي
                /*
                    **من ألغى السند؟**

                    السند نفسه يُحذف حذفاً نهائياً (لا `SoftDeletes` على
                    `Receipt`)، فعمودا `cancelled_by` و`cancelled_at` في
                    جدوله لا يمكن أن يبقيا. فالأثر الوحيد الباقي هو **القيد
                    العكسي** — وهو ما تعرضه شاشة القيود.

                    وكان ذلك القيد يُنشأ بحالة «معتمد» (`status = 1`) بلا
                    `approved_by_employee` إطلاقاً، فتقول شاشة عرض القيد
                    «اعتمد بواسطة: -» عن قيدٍ معتمَد. ولم يكن في وصفه اسمُ
                    من ألغى، فشاشة الفهرس — وهي تعرض الوصف — لا تدلّ عليه.

                    الاسم يُكتب في ثلاثة مواضع الآن: المنشئ، والمعتمِد،
                    والوصف. الأوّلان لجداول التقارير، والثالث لِمن يقرأ
                    السطر بعينه.
                */
                $reversalJournalEntry = JournalEntry::create([
                    'reference_number' => 'REV-'.$originalJournalEntry->reference_number,
                    'date' => now(),
                    'description' => 'قيد عكسي لإلغاء سند قبض رقم '.$income->code
                        .' - ألغاه '.$user->name
                        .' في '.now()->format('Y-m-d H:i')
                        .' (القيد الأصلي #'.$originalJournalEntry->id.')',
                    'status' => 1,
                    'currency' => $income->documentCurrency(),
                    'client_id' => $clientAccount->client_id ?? null,
                    'reference_type' => ReferenceType::PAYMENT_CANCELLATION,
                    'linking_type' => LinkingType::SINGLE,
                    'created_by_employee' => $user->id,
                    // القيد يُنشأ معتمَداً، فمن أنشأه هو من اعتمده
                    'approved_by_employee' => $user->id,
                ]);

                // إنشاء قيد عكسي لتفاصيل السند
                foreach ($originalJournalEntry->details as $originalDetail) {
                    JournalEntryDetail::create([
                        'journal_entry_id' => $reversalJournalEntry->id,
                        'account_id' => $originalDetail->account_id,
                        'description' => 'عكس: '.$originalDetail->description,
                        'debit' => $originalDetail->credit, // عكس المبالغ
                        'credit' => $originalDetail->debit, // عكس المبالغ
                        'is_debit' => ! $originalDetail->is_debit, // عكس نوع القيد
                        // بلا نقل المركز يظهر التحصيل في تقرير مراكز التكلفة
                        // ولا يظهر إلغاؤه
                        'cost_center_id' => $originalDetail->cost_center_id,
                    ]);
                }

                /*
                    **القيد المرحَّل لا يُنزَع اعتمادُه.**

                    كان الإلغاء يُرجع القيد الأصلي إلى `status = 0` — وهي
                    حالة «معلّق» أي *لم يُعتمد بعد*. والقيد قد اعتُمد ورُحِّل
                    فعلاً، وإنما عُكس بقيدٍ آخر. فإرجاعُه إلى «معلّق» يكذب
                    على قارئ الدفتر ويُظهر في اللوحة قيوداً تنتظر اعتماداً
                    لا تنتظره.

                    والقاعدة المحاسبية أن المرحَّل يبقى مرحَّلاً وإلى جانبه
                    عكسُه — وهو ما يفعله إلغاء سند الصرف في الملفّ المقابل:
                    يُحدّث الوصف ولا يمسّ الحالة.
                */
                $originalJournalEntry->update([
                    'description' => $originalJournalEntry->description.' [ملغي - القيد العكسي #'.$reversalJournalEntry->id.']',
                ]);

                Log::info('تم إنشاء قيد عكسي لإلغاء السند', [
                    'original_journal_id' => $originalJournalEntry->id,
                    'reversal_journal_id' => $reversalJournalEntry->id,
                    'income_id' => $income->id,
                    'amount' => $income->amount,
                ]);
            } else {
                Log::warning('لم يتم العثور على قيد محاسبي مرتبط بهذا السند', [
                    'income_id' => $income->id,
                    'reference_number' => $referenceNumber,
                ]);
            }

            // تسجيل النشاط
            OperationLog::record(
                'cancelled',
                'finance_log',
                $income->id,
                sprintf('تم إلغاء سند قبض رقم **%s** بقيمة **%d**', $income->code, $income->amount)
            );

            // إنشاء إشعار إلغاء
            $accountName = $clientAccount ? $clientAccount->name : 'غير محدد';
            notifications::create([
                'type' => 'receipt_cancelled',
                'title' => $user->name.' ألغى سند قبض',
                'description' => 'تم إلغاء سند قبض رقم '.$income->code.' لـ '.$accountName.' بقيمة '.number_format($income->amount, 2).' ر.س',
            ]);

            // حذف المرفقات
            if ($income->attachments && file_exists(public_path('assets/uploads/incomes/'.$income->attachments))) {
                unlink(public_path('assets/uploads/incomes/'.$income->attachments));
                Log::info('تم حذف الملفات المرفقة');
            }

            // === عكس نقاط سند القبض عند الإلغاء ===
            try {
                app(PointsService::class)->reverseByReference(Receipt::class, $income->id, 'إلغاء سند قبض رقم '.$income->code);
            } catch (\Throwable $e) {
                $this->recordFailure($e, 'finance_log', 'receipt_points_reversal', $income);
            }

            // حذف السند
            $income->delete();
            Log::info('تم حذف السند');

            DB::commit();
            Log::info('======= انتهت دالة cancel بنجاح =======');

            return redirect()
                ->route('incomes.index')
                ->with(['success' => 'تم إلغاء سند القبض بنجاح وإنشاء قيد عكسي']);

        } catch (\Exception $e) {
            // يبلغ جدول «سجلّ الأخطاء»، لا ملفّ اللوق وحده
            OperationLog::failure($e, 'Account.Incomes', 'cancel');

            DB::rollback();
            Log::error('======= حدث خطأ في دالة cancel =======');
            Log::error('الخطأ: '.$e->getMessage());
            Log::error('Stack Trace: '.$e->getTraceAsString());

            return back()->with('error', 'حدث خطأ أثناء إلغاء سند القبض: '.$e->getMessage());
        }
    }
