        $totalAllDebit = $filteredAccountIds ? (clone $journalDetailsBaseQuery)->whereIn('journal_entry_details.account_id', $filteredAccountIds)->sum('journal_entry_details.debit') : 0;
        $totalAllCredit = $filteredAccountIds ? (clone $journalDetailsBaseQuery)->whereIn('journal_entry_details.account_id', $filteredAccountIds)->sum('journal_entry_details.credit') : 0;
        $totalAllCount = $filteredAccountIds
            ? (clone $journalDetailsBaseQuery)->whereIn('journal_entry_details.account_id', $filteredAccountIds)->distinct('journal_entry_details.journal_entry_id')->count('journal_entry_details.journal_entry_id')
            : 0;

        // جلب كل القيود دفعة واحدة بدل N+1
        $entriesByAccount = collect();
        if (! empty($accountIds)) {
            $entriesByAccount = JournalEntryDetail::with(['journalEntry'])
                ->join('journal_entries', 'journal_entry_details.journal_entry_id', '=', 'journal_entries.id')
                ->where('journal_entries.status', 1)
                ->tap($scopeToAccessibleEmployees)
                ->whereIn('journal_entry_details.account_id', $accountIds)
                ->when($fromDate && $toDate, function ($q) use ($fromDate, $toDate) {
                    $q->whereBetween('journal_entries.date', [$fromDate, $toDate]);
                })
                ->when($fromDate && ! $toDate, function ($q) use ($fromDate) {
                    $q->where('journal_entries.date', '>=', $fromDate);
                })
                ->when($toDate && ! $fromDate, function ($q) use ($toDate) {
                    $q->where('journal_entries.date', '<=', $toDate);
                })
                ->when($branchFilter, function ($q) use ($branchFilter) {
                    $q->where('journal_entries.branch_id', $branchFilter);
                })
                ->when($employeeFilter, function ($q) use ($employeeFilter) {
                    $q->where(function ($subQ) use ($employeeFilter) {
                        $subQ->where('journal_entries.employee_id', $employeeFilter)
                            ->orWhere('journal_entries.created_by_employee', $employeeFilter)
                            ->orWhere('journal_entries.approved_by_employee', $employeeFilter);
                    });
                })
                ->when($costCenterFilter, function ($q) use ($costCenterFilter) {
                    $q->where('journal_entry_details.cost_center_id', $costCenterFilter);
                })
                ->orderBy('journal_entries.date', 'asc')
                ->orderBy('journal_entries.id', 'asc')
                ->select('journal_entry_details.*')
                ->get()
                ->groupBy('account_id');
        }

        // جلب الأرصدة الافتتاحية دفعة واحدة (قبل تاريخ البداية)
        $openingByAccount = collect();
        if ($fromDate && ! empty($accountIds)) {
            $openingByAccount = JournalEntryDetail::query()
                ->join('journal_entries', 'journal_entry_details.journal_entry_id', '=', 'journal_entries.id')
                ->where('journal_entries.status', 1)
                ->tap($scopeToAccessibleEmployees)
                ->where('journal_entries.date', '<', $fromDate)
                ->whereIn('journal_entry_details.account_id', $accountIds)
                ->when($branchFilter, function ($q) use ($branchFilter) {
                    $q->where('journal_entries.branch_id', $branchFilter);
                })
                ->when($employeeFilter, function ($q) use ($employeeFilter) {
                    $q->where(function ($subQ) use ($employeeFilter) {
                        $subQ->where('journal_entries.employee_id', $employeeFilter)
                            ->orWhere('journal_entries.created_by_employee', $employeeFilter)
                            ->orWhere('journal_entries.approved_by_employee', $employeeFilter);
                    });
                })
                ->when($costCenterFilter, function ($q) use ($costCenterFilter) {
                    $q->where('journal_entry_details.cost_center_id', $costCenterFilter);
                })
                ->groupBy('journal_entry_details.account_id')
                ->select(
                    'journal_entry_details.account_id',
                    DB::raw('SUM(journal_entry_details.debit) as total_debit'),
                    DB::raw('SUM(journal_entry_details.credit) as total_credit')
                )
                ->get()
                ->keyBy('account_id');
        }

        foreach ($accounts as $account) {
            $entries = $entriesByAccount->get($account->id, collect());
            $openingRow = $openingByAccount->get($account->id);

            $openingDebit = (float) ($openingRow->total_debit ?? 0);
            $openingCredit = (float) ($openingRow->total_credit ?? 0);
            $openingBalance = 0;
            if ($fromDate) {
                $openingBalance = $account->balance_type === 'debit'
                    ? ($openingDebit - $openingCredit)
                    : ($openingCredit - $openingDebit);
            }

            if ($entries->isEmpty() && $openingBalance == 0) {
                continue;
            }

            $totalDebit = (float) $entries->sum('debit');
            $totalCredit = (float) $entries->sum('credit');

            $finalBalance = $account->balance_type === 'debit'
                ? ($openingBalance + $totalDebit - $totalCredit)
                : ($openingBalance + $totalCredit - $totalDebit);

            $accountsWithEntries[] = [
                'account' => $account,
                'entries' => $entries,
                'opening_balance' => $openingBalance,
                'total_debit' => $totalDebit,
                'total_credit' => $totalCredit,
                'final_balance' => $finalBalance,
                'count' => $entries->count(),
            ];

            $totalAllBalance += $finalBalance;
        }

        usort($accountsWithEntries, function ($a, $b) {
            return $b['count'] <=> $a['count'];
        });

        // أنواع الحسابات للفلترة
        $accountTypes = [
            'assets' => 'الأصول',
            'liabilities' => 'الخصوم',
            'equity' => 'حقوق الملكية',
            'revenues' => 'الإيرادات',
            'expenses' => 'المصروفات',
        ];

        // جلب الفروع
        $branches = Branch::select('id', 'name')->get();
        $accountsForFilter = Account::select('id', 'code', 'name')->orderBy('code')->get();

        /*
            الموظفون بلا حساب مستخدم كانوا يصلون إلى القالب، وهو يقرأ منهم
            `$employee->user->id` — لأن فلتر الموظف يقارن بـ
            `journal_entries.created_by_employee` وهو **معرّف مستخدم** لا
            معرّف موظف. فأوّل موظفٍ بلا مستخدم يرمي
