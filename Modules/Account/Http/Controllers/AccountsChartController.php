                'branch_id.exists' => 'الفرع المحدد غير موجود.',
                'balance_type.required' => 'نوع الرصيد (مدين أو دائن) مطلوب.',
                'balance_type.in' => 'نوع الرصيد غير صالح.',
                'opening_balance.numeric' => 'الرصيد الافتتاحي يجب أن يكون رقماً.',
                'opening_balance.min' => 'الرصيد الافتتاحي لا يمكن أن يكون سالباً.',
                'opening_balance_type.in' => 'نوع الرصيد الافتتاحي غير صالح.',
            ],
        );

        try {
            $account = new Account;
            $account->code = $request->code;
            $account->type = $request->type;
            $account->parent_id = $isMainAccount ? null : $request->parent_id;
            $account->name = $request->name;
            $account->branch_id = $request->branch_id;
            $account->balance_type = $request->balance_type;

            // Respect explicitly selected account_type.
            // If not provided for sub account, inherit from parent.
            if ($request->filled('account_type')) {
                $account->account_type = $request->account_type;
            } elseif (! $isMainAccount && $request->parent_id) {
                $parentAccount = Account::findOrFail($request->parent_id);
                $account->account_type = $parentAccount->account_type;
            } else {
                $account->account_type = $request->account_type;
            }

            // Set opening balance fields
            $account->opening_balance = $request->opening_balance ?? 0;
            $account->opening_balance_type = $request->opening_balance_type ?? $request->balance_type;

            // Save the account first
            $account->save();

            // Update all child accounts with the same account_type
            if ($request->account_type) {
                $account->updateChildrenAccountTypes($request->account_type);
            }

            // Update the account balance based on opening balance
            if ($account->opening_balance > 0) {
                $account->balance = $account->opening_balance;
                $account->save();
            }

            // Clear accounts tree cache
            Cache::forget('accounts_tree');

            // تسجيل السجل
            OperationLog::record(
                'created',
                'finance_log',
                $account->id, // ID النشاط المرتبط
