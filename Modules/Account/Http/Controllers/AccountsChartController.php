                $parentAccount = Account::findOrFail($request->parent_id);
                $account->account_type = $parentAccount->account_type;
            } else {
                $account->account_type = $request->account_type;
            }

            // Check if opening balance has changed before updating
            $newOpeningBalance = $request->opening_balance ?? 0;
            $newOpeningBalanceType = $request->opening_balance_type ?? $request->balance_type;

            // Only update if opening balance or type has changed
            $openingBalanceChanged = $account->opening_balance == $newOpeningBalance;

            // Set opening balance fields
            $account->opening_balance = $newOpeningBalance;
            $account->opening_balance_type = $newOpeningBalanceType;

            // Update the account balance based on opening balance
            if (! $openingBalanceChanged) {
                $account->balance = $account->opening_balance;
            } else {
                // إذا لم يُرسل حقل balance من الفورم، احتفظ بالقيمة الحالية
                $account->balance = $request->filled('balance') ? $request->balance : $account->balance;
            }

            $account->save();

            // Update all child accounts with the same account_type
            if ($request->account_type) {
                $account->updateChildrenAccountTypes($request->account_type);
            }

            // Only create/update journal entry if opening balance has changed
            if (! $openingBalanceChanged) {
                $account->createOrUpdateOpeningBalanceJournalEntry();
            }
            // Clear accounts tree cache
            Cache::forget('accounts_tree');

            // Add aggregated balance to the response
            $account->aggregated_balance = $account->aggregated_balance;

            OperationLog::record(
                'updated',
                'finance_log',
                $account->id, // ID النشاط المرتبط
                'تم تعديل الحساب **'.$request->name.'**'
            );

            return response()->json(
                [
                    'success' => true,
                    'message' => 'تم تحديث بيانات الحساب بنجاح.',
                    'data' => $account,
                ],
                200,
            );
        } catch (\Exception $e) {
            // يبلغ جدول «سجلّ الأخطاء»، لا ملفّ اللوق وحده
            OperationLog::failure($e, 'Account.AccountsChart', 'update');

            \Log::error('Account update failed', [
                'id' => $id,
                'error' => $e->getMessage(),
                'trace' => $e->getTraceAsString(),
            ]);

            return response()->json(
                [
                    'success' => false,
                    'message' => 'حدث خطأ أثناء التحديث: '.$e->getMessage(),
                ],
                500,
            );
        }
    }

