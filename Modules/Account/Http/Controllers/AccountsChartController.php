    public function generalLedger(Request $request)
    {
        /*
            **الفترة المختارة كانت لا أثر لها.**

            الشاشة تعرض قائمة الفترات، والمتحكّم يقرأ `fromDate`/`toDate`
            وحدهما — فاختيارُ سنةٍ أو شهرٍ لا يغيّر شيئاً ما لم يملأ السكربتُ
            الحقلين، والقائمةُ تبدو على «السنة الجارية» والدفترُ يعرض التاريخَ
            كلَّه منذ أوّل قيد. وصار كبقية التقارير: مدًى مكتوبٌ يخالف حدَّي
            الفترة يتقدّم، وإلا فحدّا الفترة المختارة، والافتراضيُّ السنةُ الجارية.
        */
        $reportPeriod = AccountingPeriodFilter::resolve($request);
        $fromDate = $request->input('fromDate');
        $toDate = $request->input('toDate');
        $typedRange = ($fromDate || $toDate)
            && ! ((string) $fromDate === (string) $reportPeriod['from'] && (string) $toDate === (string) $reportPeriod['to']);

        if (! $typedRange) {
            $unbounded = $reportPeriod['all'] || $reportPeriod['none'] || $reportPeriod['no_calendar'];
            $fromDate = $unbounded ? null : $reportPeriod['from'];
            $toDate = $unbounded ? null : $reportPeriod['to'];
        }

        $accountIdFilter = $request->input('account_id');
        $accountTypeFilter = $request->input('account_type'); // للفلترة حسب نوع الحساب
        $branchFilter = $request->input('branch_id'); // للفلترة حسب الفرع
        $employeeFilter = $request->input('employee_id'); // للفلترة حسب الموظف
        $costCenterFilter = $request->input('cost_center_id'); // للفلترة حسب مركز التكلفة
        $accountLevelFilter = $request->input('account_level'); // رئيسي أو فرعي أو الكل
        $accountsPerPage = (int) $request->input('accounts_per_page', 12);
        if ($accountsPerPage < 1) {
            $accountsPerPage = 12;
        }

        // نطاق الرؤية: قيوده هو أو قيود من يديرهم — فوق أي فلترٍ يدوي بالموظف
        // لا بدلاً منه (نفس نطاق `journal/index`، بعمود `created_by_employee` نفسه)
        $accessibleUserIds = $this->accessibleUserIds();
        $scopeToAccessibleEmployees = function ($query) use ($accessibleUserIds) {
            if ($accessibleUserIds !== null) {
                $query->whereIn('journal_entries.created_by_employee', $accessibleUserIds ?: [0]);
            }
        };

        // فلتر مشترك على قيود اليومية المعتمدة لتحسين الأداء
        $journalDetailsBaseQuery = JournalEntryDetail::query()
            ->join('journal_entries', 'journal_entry_details.journal_entry_id', '=', 'journal_entries.id')
            ->where('journal_entries.status', 1)
            ->tap($scopeToAccessibleEmployees);

        if ($fromDate && $toDate) {
            $journalDetailsBaseQuery->whereBetween('journal_entries.date', [$fromDate, $toDate]);
        } elseif ($fromDate) {
            $journalDetailsBaseQuery->where('journal_entries.date', '>=', $fromDate);
        } elseif ($toDate) {
            $journalDetailsBaseQuery->where('journal_entries.date', '<=', $toDate);
        }

        if ($branchFilter) {
            $journalDetailsBaseQuery->where('journal_entries.branch_id', $branchFilter);
        }

        if ($employeeFilter) {
            $journalDetailsBaseQuery->where(function ($subQ) use ($employeeFilter) {
                $subQ->where('journal_entries.employee_id', $employeeFilter)
                    ->orWhere('journal_entries.created_by_employee', $employeeFilter)
                    ->orWhere('journal_entries.approved_by_employee', $employeeFilter);
            });
        }

        if ($costCenterFilter) {
            $journalDetailsBaseQuery->where('journal_entry_details.cost_center_id', $costCenterFilter);
        }

        // بناء استعلام الحسابات بناءً على الفلاتر
        $accountsQuery = Account::query();

        if ($accountLevelFilter === 'parent') {
            $accountsQuery->whereExists(function ($query) {
                $query->select(DB::raw(1))
                    ->from('accounts as child')
                    ->whereColumn('child.parent_id', 'accounts.id');
            });
        } elseif ($accountLevelFilter === 'child') {
            $accountsQuery->whereNotExists(function ($query) {
                $query->select(DB::raw(1))
                    ->from('accounts as child')
                    ->whereColumn('child.parent_id', 'accounts.id');
            });
        }

        if ($accountTypeFilter) {
            $accountsQuery->where('account_type', $accountTypeFilter);
        }

        if ($branchFilter) {
            $accountsQuery->where('branch_id', $branchFilter);
        }

        if ($accountIdFilter) {
            $accountsQuery->where('id', $accountIdFilter);
        }

        // جلب معرفات الحسابات التي لديها حركات ضمن الفلاتر المحددة
        $activeAccountIds = (clone $journalDetailsBaseQuery)
            ->select('journal_entry_details.account_id')
            ->distinct()
            ->pluck('journal_entry_details.account_id')
            ->toArray();

        if (! $accountIdFilter) {
            $accountsQuery->whereIn('id', $activeAccountIds ?: [-1]);
        }

        // الحصول على كل الحسابات المطابقة للفلاتر لحساب الإجماليات بدقة
        $filteredAccountIds = (clone $accountsQuery)->pluck('id')->toArray();

        // تقليل الحمل: تقسيم الحسابات على صفحات بدلاً من تحميل كل الحسابات دفعة واحدة
        $accountsPagination = $accountsQuery
            ->orderBy('code')
            ->paginate($accountsPerPage)
            ->appends($request->query());
        $accounts = collect($accountsPagination->items());
        $accountIds = $accounts->pluck('id')->toArray();

        $accountsWithEntries = [];
        $totalAllBalance = 0;

