    /**
     * صفحة الحساب المحسَّنة: شريط جانبي للشجرة + لوحة بالأبناء والقيود المباشرة
     * Optimized account view page.
     *
     * يفصل بشكل واضح بين:
     *  - الأبناء المباشرين للحساب (Direct children)
     *  - القيود المحاسبية الخاصة بالحساب نفسه فقط (Direct journal entries)
     */
    public function showAccount(Request $request, $id = null)
    {
        $account = null;
        if ($id) {
            $account = Account::select('id', 'name', 'code', 'parent_id', 'branch_id', 'balance', 'balance_type', 'account_type', 'is_active', 'is_system', 'opening_balance', 'opening_balance_type')
                ->find($id);
            if (! $account) {
                abort(404, 'الحساب غير موجود');
            }
        }

        $branchId = $request->input('branch_id');
        $fromDate = $request->input('from_date');
        $toDate = $request->input('to_date');
        $perPage = (int) $request->input('per_page', 25);
        if ($perPage < 5 || $perPage > 200) {
            $perPage = 25;
        }
        $childrenPerPage = (int) $request->input('children_per_page', 50);
        if ($childrenPerPage < 10 || $childrenPerPage > 500) {
            $childrenPerPage = 50;
        }

        // مسار الفئات (breadcrumb) من الجذر للحساب
        $breadcrumb = [];
        if ($account) {
            $cursor = $account;
            $safety = 0;
            while ($cursor && $safety < 20) {
                array_unshift($breadcrumb, [
                    'id' => $cursor->id,
                    'name' => $cursor->name,
                    'code' => $cursor->code,
                ]);
                if (! $cursor->parent_id) {
                    break;
                }
                $cursor = Account::select('id', 'name', 'code', 'parent_id')->find($cursor->parent_id);
                $safety++;
            }
        }

        // الأبناء المباشرين (direct children) - مع علم has_children بطريقة فعّالة + pagination
        // نستخدم pageName='children_page' لتفادي الاصطدام مع pagination القيود
        $children = null;
        $childrenTotal = 0;
        if ($account) {
            $childrenQuery = Account::select('id', 'name', 'code', 'parent_id', 'balance', 'balance_type', 'account_type', 'is_active')
                ->where('parent_id', $account->id)
                ->orderByRaw('CAST(code AS UNSIGNED) ASC, code ASC');

            $childrenTotal = (clone $childrenQuery)->count();
            $children = $childrenQuery->paginate($childrenPerPage, ['*'], 'children_page')->appends($request->query());

            if ($children->total() > 0) {
                $childIds = collect($children->items())->pluck('id')->toArray();
                $hasGrandChildren = Account::whereIn('parent_id', $childIds)
                    ->pluck('parent_id')->unique()->all();
                $hasGrandSet = array_fill_keys($hasGrandChildren, true);
                foreach ($children->items() as $c) {
                    $c->has_children = isset($hasGrandSet[$c->id]);
                }
            }
        }

        // القيود المباشرة لهذا الحساب فقط (direct entries) — لا تشمل الأبناء
        $directEntries = null;
        $entriesSummary = ['total_debit' => 0, 'total_credit' => 0, 'count' => 0];
        if ($account) {
            $entriesQuery = JournalEntryDetail::query()
                ->select('journal_entry_details.id', 'journal_entry_details.journal_entry_id',
                    'journal_entry_details.account_id', 'journal_entry_details.debit',
                    'journal_entry_details.credit', 'journal_entry_details.description',
                    'journal_entry_details.cost_center_id')
                ->where('journal_entry_details.account_id', $account->id)
                ->with([
                    'journalEntry:id,date,description,reference_number,reference_type,status,branch_id',
                    'costCenter:id,name',
                ]);

            // فلتر التاريخ والفرع - يطبَّق عبر JOIN لتقليل عدد الاستعلامات
            if (($fromDate && $toDate) || $branchId) {
                $entriesQuery->join('journal_entries', 'journal_entries.id', '=', 'journal_entry_details.journal_entry_id');
                if ($fromDate && $toDate) {
                    $entriesQuery->whereBetween('journal_entries.date', [$fromDate, $toDate]);
                }
                if ($branchId && $branchId !== 'all') {
                    $entriesQuery->where('journal_entries.branch_id', $branchId);
                }
                $entriesQuery->orderBy('journal_entries.date', 'desc')
                    ->orderBy('journal_entries.id', 'desc');
            } else {
                $entriesQuery->orderBy('journal_entry_details.id', 'desc');
            }

            $directEntries = $entriesQuery->paginate($perPage)->appends($request->query());

            // ملخص الحركة على الحساب نفسه
            $summaryQuery = JournalEntryDetail::query()->where('account_id', $account->id);
            if (($fromDate && $toDate) || $branchId) {
                $summaryQuery->join('journal_entries', 'journal_entries.id', '=', 'journal_entry_details.journal_entry_id');
                if ($fromDate && $toDate) {
                    $summaryQuery->whereBetween('journal_entries.date', [$fromDate, $toDate]);
                }
                if ($branchId && $branchId !== 'all') {
                    $summaryQuery->where('journal_entries.branch_id', $branchId);
                }
            }
            $entriesSummary = [
                'total_debit' => (float) (clone $summaryQuery)->sum('journal_entry_details.debit'),
                'total_credit' => (float) (clone $summaryQuery)->sum('journal_entry_details.credit'),
                'count' => (int) (clone $summaryQuery)->count(),
            ];
        }

        // قائمة الفروع للفلتر
        $branches = Branch::select('id', 'name')->get();

        // أنواع المراجع لقائمة الفلاتر/العرض
        $referenceTypes = JournalEntry::getReferenceTypes();

        return view('account::accounts_chart.account_view', compact(
            'account',
            'breadcrumb',
            'children',
            'childrenTotal',
            'childrenPerPage',
            'directEntries',
            'entriesSummary',
            'branches',
            'fromDate',
            'toDate',
            'branchId',
            'perPage',
            'referenceTypes'
        ));
    }

    /**
     * شجرة كاملة (مسطّحة) كـ JSON مُجزَّأ بالحسابات لاستخدامها في الشريط الجانبي.
     * تُخزَّن في الكاش لساعة كاملة. مفتاح الكاش يتضمن الفرع لتدعم العزل.
     */
    public function getFlatTreeJson(Request $request)
    {
        $branchId = $request->input('branch_id');
        $cacheKey = 'accounts_flat_tree'.($branchId && $branchId !== 'all' ? ('_b_'.$branchId) : '');

        $data = Cache::remember($cacheKey, 600, function () use ($branchId) {
            $q = Account::select('id', 'name', 'code', 'parent_id', 'balance', 'balance_type', 'account_type', 'branch_id')
                ->orderByRaw('CAST(code AS UNSIGNED) ASC, code ASC');
            if ($branchId && $branchId !== 'all') {
                $q->where('branch_id', $branchId);
            }
            $rows = $q->get();

            // حساب has_children بدفعة واحدة
            $parentIdsWithChildren = Account::whereNotNull('parent_id')
                ->distinct()->pluck('parent_id')->all();
            $set = array_fill_keys($parentIdsWithChildren, true);

            return $rows->map(function ($a) use ($set) {
                return [
                    'id' => $a->id,
                    'name' => $a->name,
                    'code' => $a->code,
                    'parent_id' => $a->parent_id,
                    'balance' => (float) $a->balance,
                    'balance_type' => $a->balance_type,
                    'account_type' => $a->account_type,
                    'has_children' => isset($set[$a->id]),
                ];
            })->values();
        });

        return response()->json($data);
    }

    /**
     * إعادة احتساب رصيد حساب واحد (وآبائه) من القيود.
     * تُستخدم من زر "تحديث الرصيد" بجانب الحساب.
     */
    public function recalculateAccountBalance(Request $request, $id)
    {
        try {
            $account = Account::find($id);
            if (! $account) {
                return response()->json(['success' => false, 'message' => 'الحساب غير موجود'], 404);
            }

            $ok = Account::updateBalancesHierarchically($id);
            if (! $ok) {
                return response()->json(['success' => false, 'message' => 'تعذّر تحديث الرصيد'], 500);
            }

            $account->refresh();
            Cache::forget('accounts_flat_tree');
            Cache::forget('accounts_tree');

            return response()->json([
                'success' => true,
                'message' => 'تم تحديث رصيد الحساب بنجاح',
                'balance' => (float) $account->balance,
                'balance_type' => $account->balance_type,
            ]);
        } catch (\Throwable $e) {
            // يبلغ جدول «سجلّ الأخطاء»، لا ملفّ اللوق وحده
            OperationLog::failure($e, 'Account.AccountsChart', 'recalculateAccountBalance');

            Log::error('recalculateAccountBalance failed', ['id' => $id, 'error' => $e->getMessage()]);

            return response()->json(['success' => false, 'message' => 'خطأ: '.$e->getMessage()], 500);
        }
    }

