            باسمه أصلاً، فلا فائدة من ظهوره في الفلتر.
        */
        $employees = Employee::with('user')
            ->whereHas('user')
            ->selectRaw("
            id,
            TRIM(CONCAT(
                COALESCE(first_name, ''), ' ',
                COALESCE(middle_name, ''), ' ',
                COALESCE(nickname, '')
            )) as name
        ")
            ->get();

        // جلب مراكز التكلفة
        $costCenters = CostCenter::select('id', 'name')->get();

        return view('account::generalLedger.generalLedger', [
