    /**
     * الكودُ التالي تحت أبٍ بعينه — أو كودُ حسابٍ رئيسيّ حين لا أب.
     *
     * **ثلاثُ عللٍ عولجت هنا:**
     *
     * ١) **الحسابُ الرئيسي لا كودَ له.** كان التوقيعُ يُلزم أباً
     *    (`Account $parent`)، فلا سبيل لتوليد كودِ جذرٍ إطلاقاً — وشاشةُ
     *    الإضافة تعرض «رئيسي» خياراً ثم لا تجد له كوداً. صار الأبُ اختيارياً.
     *
     * ٢) **التفرّدُ كان يُفحص بحلقةِ استعلامات.** `while (exists) $n++`
     *    تُطلق استعلاماً لكل محاولة، حتى عشرةِ آلاف. وشجرةٌ مزدحمةٌ تجعل
     *    زرَّ التوليد يقف ثوانيَ. صار الفحصُ **استعلاماً واحداً**: تُجلب
     *    الأكوادُ المأخوذة في المدى المرشَّح مرّةً، ثم يُبحث عن الفجوة في
     *    الذاكرة.
     *
     * ٣) **الأخُ الأكبر كان يُطلب بصفٍّ كامل.** `first()` تجلب الصفَّ كلَّه
     *    ولا يُستعمل منه إلا `code`.
     */
    public function getNextCode(Request $request, ?Account $parent = null)
    {
        $parentCodeStr = (string) ($parent->code ?? '');
        $parentCodeNum = is_numeric($parentCodeStr) ? (int) $parentCodeStr : 0;

        if ($parent) {
            // أكبرُ كودٍ رقميٍّ بين الإخوة — عمودٌ واحد لا صفٌّ كامل
            $lastChildCode = Account::where('parent_id', $parent->id)
                ->orderByRaw('CAST(code AS UNSIGNED) DESC')
                ->orderBy('code', 'desc')
                ->value('code');

            if ($lastChildCode !== null && is_numeric($lastChildCode)) {
                $start = (int) $lastChildCode + 1;
            } elseif ($parentCodeNum > 0) {
                // أوّلُ ابن: كودُ الأب متبوعاً بـ001 (1241 → 1241001)
                $start = (int) ($parentCodeStr.'001');
            } else {
                $start = 1;
            }
        } else {
            /*
                حسابٌ رئيسيّ: الجذورُ تُرقَّم أحاديّاً (1,2,3…) في شجرة
                الحسابات المعتادة، فيبدأ من أكبر جذرٍ زائدَ واحد.
            */
            $lastRootCode = Account::whereNull('parent_id')
                ->orderByRaw('CAST(code AS UNSIGNED) DESC')
                ->orderBy('code', 'desc')
                ->value('code');

            $start = ($lastRootCode !== null && is_numeric($lastRootCode))
                ? (int) $lastRootCode + 1
                : 1;
        }

        $nextNum = $this->firstFreeCode($start);

        return response()->json([
            'nextCode' => (string) $nextNum,
            'parent_code' => $parentCodeStr,
            'parent_id' => $parent->id ?? null,
        ]);
    }

    /**
     * أوّلُ كودٍ غيرِ مستعمل ابتداءً من `$start` — باستعلامٍ واحد.
     *
     * الأكوادُ نصٌّ في الجدول، فتُقارَن رقمياً بـ`CAST`. والمدى محدودٌ
     * بـ`$window`: لا حاجةَ لجلب الجدول كلِّه، وفجوةٌ في أوّل ألفِ رقمٍ
     * كافيةٌ عملياً — وإن امتلأت يُوسَّع المدى مرّةً واحدة.
     */
    private function firstFreeCode(int $start, int $window = 1000): int
    {
        if ($start < 1) {
            $start = 1;
        }

        for ($round = 0; $round < 5; $round++) {
            $end = $start + $window;

            $taken = Account::whereRaw('CAST(code AS UNSIGNED) BETWEEN ? AND ?', [$start, $end])
                ->pluck('code')
                ->map(fn ($c) => (int) $c)
                ->flip();

            for ($n = $start; $n <= $end; $n++) {
                if (! $taken->has($n)) {
                    return $n;
                }
            }

            // المدى كلُّه مأخوذ: نقفز إلى ما بعده
            $start = $end + 1;
        }

        return $start;
    }

