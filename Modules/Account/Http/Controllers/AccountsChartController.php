    public function getJournalEntries($accountId)
    {
        $fromDate = request()->input('from_date');
        $toDate = request()->input('to_date');
        $branchId = request()->input('branch_id');

        $account = Account::find($accountId);
        if (! $account) {
            return response()->json([]);
        }
        $accountIds = $this->getAccountAndDescendantIds($account);

        // Build query for journal entries
        $query = JournalEntryDetail::whereIn('account_id', $accountIds)
            ->with(['journalEntry' => function ($query) {
                $query->select('id', 'date', 'description', 'reference_number', 'reference_type');
            }])
            ->select('id', 'journal_entry_id', 'account_id', 'description', 'debit', 'credit', 'created_at');

        // Apply date filtering ONLY if both dates are provided
        if ($fromDate && $toDate) {
            $query->whereHas('journalEntry', function ($q) use ($fromDate, $toDate) {
                $q->whereDate('date', '>=', $fromDate)
                    ->whereDate('date', '<=', $toDate);
            });
        }
        // If either date is missing, don't apply date filtering at all

        // Apply branch filtering if provided
        if ($branchId) {
            $query->whereHas('journalEntry', function ($q) use ($branchId) {
                $q->where('branch_id', $branchId);
            });
        }

        // Order by journal entry date descending (latest first)
        $journalEntries = $query->orderBy('journal_entry_id', 'desc')
            ->get();

        return response()->json($journalEntries);
    }

    public function transactions($accountId)
    {

