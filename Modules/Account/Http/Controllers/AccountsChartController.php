    public function search(Request $request)
    {
        $searchText = $request->input('search');
        $branchId = $request->input('branch_id');
        $parentId = $request->input('parent_id');

        $query = Account::select('id', 'name', 'code', 'parent_id', 'branch_id', 'balance', 'balance_type', 'account_type');

        if ($searchText) {
            $query->where(function ($q) use ($searchText) {
                $q->where('name', 'like', '%'.$searchText.'%')
                    ->orWhere('code', 'like', '%'.$searchText.'%');
            });
        }

        // تصفية الفرع
        if ($branchId && $branchId !== 'all') {
            $query->where('branch_id', $branchId);
        }

        if ($parentId) {
            $query->where('parent_id', $parentId);
        }

        $results = $query->limit(20)->get();

        // إضافة معلومة هل للحساب أبناء أم لا ورصيد مجمع
        $results->each(function ($account) {
            $account->has_children = Account::where('parent_id', $account->id)->exists();
            // حساب الرصيد المجمع
            $account->aggregated_balance = $account->balance;
            // إضافة ترجمة نوع الحساب
            if ($account->account_type) {
                $account->getAccountTypeTranslationAttribute = $account->getAccountTypeTranslationAttribute();
            }
        });

        return response()->json($results);
    }

    public function showAccountEntries(Request $request, $accountId)
    {
        $account = Account::findOrFail($accountId);

        /*
            فلترُ التاريخ والفرع في القالب كان بلا أثر، والقالبُ يقرأ
            `$fromDate`/`$toDate`/`$branchId`/`$summary` ولا يُمرَّر له منها
            شيء — فالشاشةُ تسقط بـ«Undefined variable $fromDate» قبل أن تُعرض.
            والفرعُ المطلوب يُقصّ على نطاق المستخدم كبقيّة الشاشات.
        */
        $fromDate = $request->input('from_date');
        $toDate = $request->input('to_date');
        $branchId = $request->filled('branch_id') && $request->input('branch_id') !== 'all'
            ? \App\Support\DataScope::clampNode((int) $request->input('branch_id'))
            : null;

        $accountIds = $this->getAccountAndDescendantIds($account);
        $filtered = function () use ($accountIds, $fromDate, $toDate, $branchId) {
            return JournalEntryDetail::whereIn('account_id', $accountIds)
                ->when($fromDate || $toDate || $branchId, fn ($q) => $q->whereHas('journalEntry', function ($e) use ($fromDate, $toDate, $branchId) {
                    $e->when($fromDate, fn ($x) => $x->whereDate('date', '>=', $fromDate))
                        ->when($toDate, fn ($x) => $x->whereDate('date', '<=', $toDate))
                        ->when($branchId, fn ($x) => $x->where('branch_id', $branchId));
                }));
        };

        // جلب القيود المرتبطة بالحساب مع pagination
        $journalEntries = $filtered()
            ->with(['journalEntry' => function ($query) {
                $query->select('id', 'date', 'description', 'reference_number');
            }])
            ->select('id', 'journal_entry_id', 'account_id', 'description', 'debit', 'credit')
            ->orderBy('created_at', 'desc')
            ->paginate(20);

        // الملخّص على الفلتر نفسه — لا على كل حركة الحساب
        $summary = [
            'total_debit' => $filtered()->sum('debit'),
            'total_credit' => $filtered()->sum('credit'),
        ];
        $summary['balance'] = $summary['total_debit'] - $summary['total_credit'];

        // إذا كان طلب AJAX، إرجاع JSON
        if ($request->ajax()) {
            return response()->json([
                'success' => true,
                'account' => $account,
                'entries' => $journalEntries,
                'summary' => $summary,
            ]);
        }

        $branches = \App\Support\DataScope::branchOptions(Branch::query()->orderBy('name'), ['id', 'name']);

        return view('account::accounts_chart.entries', compact('account', 'journalEntries', 'branches', 'summary', 'fromDate', 'toDate', 'branchId'));
    }

