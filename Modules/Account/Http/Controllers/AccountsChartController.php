    /**
     * إرجاع الحساب الحالي مع جميع الحسابات الفرعية التابعة له.
     */
    private function getAccountAndDescendantIds(Account $account): array
    {
        $seen = [$account->id => true];
        $parentIds = [$account->id];

        while (! empty($parentIds)) {
            $childrenIds = Account::whereIn('parent_id', $parentIds)
                ->pluck('id')
                ->toArray();

            // تُستبعد المعرّفات المزارة: حسابٌ أبوه نفسُه (أو حلقةٌ في parent_id)
            // كان يُعيد نفسه ابناً في كل دورة فلا تنتهي الحلقة.
            $parentIds = [];
            foreach ($childrenIds as $cid) {
                if (! isset($seen[$cid])) {
                    $seen[$cid] = true;
                    $parentIds[] = $cid;
                }
            }
        }

        return array_keys($seen);
    }

