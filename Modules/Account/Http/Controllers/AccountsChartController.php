    public function getParents(Request $request)
    {
        $branchId = $request->input('branch_id');

        $cacheKey = 'account_parents_v2';
        if ($branchId && $branchId !== 'all') {
            $cacheKey .= '_branch_'.$branchId;
        }

        $parents = Cache::remember($cacheKey, 300, function () use ($branchId) {
            $query = Account::select('id', 'name', 'code', 'parent_id', 'account_type', 'balance_type')
                ->orderByRaw('CAST(code AS UNSIGNED) ASC, code ASC');

            if ($branchId && $branchId !== 'all') {
                $query->where('branch_id', $branchId);
            }

            $all = $query->get();
            $byId = $all->keyBy('id');

            return $all->map(function ($a) use ($byId) {
                // المسار: من الجذر إلى الأب المباشر. الحدُّ يمنع الدوران
                // لو حمل صفٌّ أباً يشير إلى نفسه أو إلى حلقة.
                $names = [];
                $cursor = $a->parent_id ? $byId->get($a->parent_id) : null;
                $guard = 0;

                while ($cursor && $guard < 20) {
                    array_unshift($names, $cursor->name);
                    $cursor = $cursor->parent_id ? $byId->get($cursor->parent_id) : null;
                    $guard++;
                }

                return [
                    'id' => $a->id,
                    'name' => $a->name,
                    'code' => $a->code,
                    'parent_id' => $a->parent_id,
                    'account_type' => $a->account_type,
                    'balance_type' => $a->balance_type,
                    'depth' => count($names),
                    'path' => $names ? implode(' ← ', $names) : null,
                    'label' => trim($a->code.' — '.$a->name),
                ];
            })->values();
        });

        return response()->json($parents);
    }

