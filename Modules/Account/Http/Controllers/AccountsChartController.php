    /**
     * إصلاح account_type للحسابات بدون نوع - يرث من جذر الشجرة (الأب الأعلى).
     *
     * مثال: حساب "أثاث المكتب" تحت "أثاث" تحت "الأصول الثابتة" تحت "الأصول"
     *  → إن لم يكن له account_type، نرفع للجذر "الأصول" ونأخذ نوعه (assets).
     *
     * يعتمد على حقيقة أن الجذور الكبرى لها account_type مضبوط:
     *   1=الأصول (assets), 2=الخصوم (liabilities), 3=حقوق الملكية (equity),
     *   4=الإيرادات (revenues), 5=المصروفات (expenses)
     *
     * @return int عدد الحسابات التي تم تصحيحها
     */
    private function syncAccountTypesFromRoot(): int
    {
        $count = 0;

        // كل الحسابات بدون account_type
        $accounts = Account::whereNull('account_type')
            ->orWhere('account_type', '')
            ->get(['id', 'name', 'code', 'parent_id', 'account_type']);

        if ($accounts->isEmpty()) {
            return 0;
        }

        // كاش لـ ancestors لتسريع البحث
        $rootTypeCache = [];

        foreach ($accounts as $account) {
            $rootType = $this->resolveRootAccountType($account, $rootTypeCache);
            if ($rootType) {
                $account->account_type = $rootType;
                $account->save();
                $count++;
            }
        }

        return $count;
    }

    /**
     * تتبّع شجرة الآباء حتى نصل إلى أب له account_type محدد.
     */
    private function resolveRootAccountType(Account $account, array &$cache): ?string
    {
        if (isset($cache[$account->id])) {
            return $cache[$account->id];
        }

        $current = $account;
        $depth = 0;
        $maxDepth = 15;

        while ($current && $depth < $maxDepth) {
            // إن كان هذا الحساب له نوع → استخدمه
            if (! empty($current->account_type)) {
                $cache[$account->id] = $current->account_type;

                return $current->account_type;
            }

            if (! $current->parent_id) {
                break;
            }

            // اقرأ الأب من DB (أو من cache إن كان موجوداً)
            $current = Account::find($current->parent_id);
            $depth++;
        }

        $cache[$account->id] = null;

        return null;
    }

