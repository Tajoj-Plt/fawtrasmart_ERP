            ], 500);
        }
    }

    private function buildTree($accounts, $parentId = null)
    {
        // Group accounts by parent_id for faster lookup
        $groupedAccounts = [];
        foreach ($accounts as $account) {
            $groupedAccounts[$account->parent_id][] = $account;
        }

        // Recursive function to build tree
        $buildTreeRecursive = function ($parentId) use (&$buildTreeRecursive, $groupedAccounts) {
            $branch = [];
            if (isset($groupedAccounts[$parentId])) {
                foreach ($groupedAccounts[$parentId] as $account) {
                    $children = $buildTreeRecursive($account->id);
                    $branch[] = [
                        'id' => $account->id,
                        'text' => $account->name,
                        'children' => $children,
                    ];
                }
            }

            return $branch;
        };

        return $buildTreeRecursive($parentId);
    }

