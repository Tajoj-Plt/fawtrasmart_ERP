                        ->find(AccountingSettings::id('clients_account', SystemAccountIds::CLIENTS_ACCOUNT));
                }
            } catch (\Throwable $e) {
                /*
                    تعذّرت قراءة حساب العملاء من الإعدادات — يُلتمَس أدناه
                    بالكود أو بالاسم. الابتلاع مقصود، لكنّه كان **صامتاً
                    تماماً**: لا سطر في أي سجلّ. فإن كان الإعداد معطوباً
                    اشتغل النظام على الحساب البديل بلا أن يعلم أحد.
                */
                OperationLog::failure($e, 'Account.AccountsChart', 'reorder_client_account_codes');
            }

            if (! $clients_parent) {
                $clients_parent = Account::select('id', 'name', 'code', 'parent_id')
                    ->where(function ($q) {
                        $q->where('code', '1241')->orWhere('name', 'العملاء');
                    })
                    ->first();
            }

            if (! $clients_parent) {
                DB::rollBack();

                return response()->json([
                    'success' => false,
                    'message' => 'لم يتم العثور على الحساب الرئيسي للعملاء (العملاء).',
                ], 404);
            }

            $base_code = $clients_parent->code ?? '1241';
            if (! preg_match('/^\d+$/', (string) $base_code)) {
                DB::rollBack();

                return response()->json([
                    'success' => false,
                    'message' => 'كود الحساب الرئيسي للعملاء غير رقمي، لا يمكن إعادة الترتيب.',
                ], 422);
            }

            // Bezpośrednie dzieci (klienci na pierwszym poziomie)
            $client_accounts = Account::select('id', 'name', 'code', 'parent_id')
                ->where('parent_id', $clients_parent->id)
                ->orderBy('id')
                ->get();

            if ($client_accounts->isEmpty()) {
                DB::commit();

                return response()->json([
                    'success' => true,
                    'message' => 'لا توجد حسابات عملاء فرعية لإعادة ترتيب الأكواد.',
                    'updated_count' => 0,
                    'skipped_count' => 0,
                    'errors' => [],
                ]);
            }

            $suffix_length = 3; // np. 1241 + 001, 002, ...
            $seq_index = 1;

            foreach ($client_accounts as $client_acc) {
                $old_prefix = (string) ($client_acc->code ?? '');
                $new_code = $base_code.str_pad((string) $seq_index, $suffix_length, '0', STR_PAD_LEFT);

                // Kolizja kodu
                $exists_collision = Account::where('code', $new_code)
                    ->where('id', '!=', $client_acc->id)
                    ->exists();
                if ($exists_collision) {
                    $skipped_count++;
                    $errors[] = [
                        'account_id' => $client_acc->id,
                        'account_name' => $client_acc->name,
                        'error' => 'تعارض في الكود الجديد: '.$new_code,
                    ];
                    $seq_index++;

                    continue;
                }

                // Aktualizacja kodu klienta
                $client_acc->code = $new_code;
                $client_acc->save();
                $updated_count++;

                // Aktualizacja potomków: podmiana prefiksu starego kodu na nowy
                if ($old_prefix !== '' && $old_prefix !== null) {
                    $descendants = Account::select('id', 'name', 'code', 'parent_id')
                        ->where('parent_id', $client_acc->id)
                        ->get();

                    $queue = collect($descendants);
                    while ($queue->isNotEmpty()) {
                        $node = $queue->shift();
                        $node_old_code = (string) ($node->code ?? '');
                        if ($node_old_code !== '' && strncmp($node_old_code, $old_prefix, strlen($old_prefix)) === 0) {
                            $suffix = substr($node_old_code, strlen($old_prefix));
                            $node_new_code = $new_code.$suffix;

                            $child_collision = Account::where('code', $node_new_code)
                                ->where('id', '!=', $node->id)
                                ->exists();
                            if ($child_collision) {
                                $skipped_count++;
                                $errors[] = [
                                    'account_id' => $node->id,
                                    'account_name' => $node->name,
                                    'error' => 'تعارض في كود الابن الجديد: '.$node_new_code,
                                ];
                            } else {
                                $node->code = $node_new_code;
                                $node->save();
                                $updated_count++;
                            }
                        }

                        // Dodaj dzieci węzła do kolejki (BFS)
                        $children = Account::select('id', 'name', 'code', 'parent_id')
                            ->where('parent_id', $node->id)
                            ->get();
                        foreach ($children as $ch) {
                            $queue->push($ch);
                        }
                    }
                }

                $seq_index++;
            }

            /*
                إعادة ترقيم أكواد حسابات العملاء عمليةٌ جماعية تمسّ مئات
                الحسابات دفعةً واحدة، وكانت تمرّ بلا أثرٍ في أي سجلّ — فلو
                أفسدت ترقيماً لم يكن ثمّة ما يدلّ على متى جرت ولا بيد من.
            */
            OperationLog::record('updated', 'Account.AccountsChart', null, sprintf(
                'أعاد ترقيم أكواد حسابات العملاء: %d حساباً غُيّر، %d تُخطّي، %d خطأ',
                $updated_count, $skipped_count, count($errors)
            ));

            DB::commit();

            return response()->json([
                'success' => true,
                'message' => 'تمت إعادة ترتيب أكواد حسابات العملاء بنجاح.',
                'updated_count' => $updated_count,
                'skipped_count' => $skipped_count,
                'errors' => $errors,
            ]);
        } catch (\Throwable $e) {
            // يبلغ جدول «سجلّ الأخطاء»، لا ملفّ اللوق وحده
            OperationLog::failure($e, 'Account.AccountsChart', 'reorder_client_account_codes');

            DB::rollBack();
            Log::error('Error in reorder_client_account_codes', [
                'error' => $e->getMessage(),
            ]);

            return response()->json([
                'success' => false,
                'message' => 'حدث خطأ أثناء إعادة ترتيب الأكواد: '.$e->getMessage(),
            ], 500);
        }
    }

