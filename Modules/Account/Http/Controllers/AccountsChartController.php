     * Generated by Copilot
     * حساب مجموع أرصدة الأبناء بشكل متكرر
     *
     * @param  int  $parent_id
     * @return float
     */
    private function calculate_children_balance_recursive($parent_id)
    {
        $total_children_balance = 0;

        // جلب الأبناء المباشرين
        $children = Account::where('parent_id', $parent_id)->get();

        foreach ($children as $child) {
            // إضافة رصيد الابن
            $total_children_balance += $child->balance ?? 0;

            // إذا كان للابن أبناء، نحسب أرصدتهم بشكل متكرر
            if (Account::where('parent_id', $child->id)->exists()) {
                $total_children_balance += $this->calculate_children_balance_recursive($child->id);
            }
        }

        return $total_children_balance;
    }

