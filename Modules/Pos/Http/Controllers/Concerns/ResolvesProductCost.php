<?php

namespace Modules\Pos\Http\Controllers\Concerns;

use App\Models\Product;

/**
 * تكلفةُ الوحدة في نقاط البيع — **متوسّطُ التكلفة**، لا سعرُ الشراء.
 *
 * ═════════════════════ ما كان ═════════════════════
 *
 * ترتيبٌ من ثلاث درجات، مكتوبٌ ثلاثَ مرّات (قيدُ البيع، وقيدُ المرتجع،
 * وتجميدُ التكلفة في البند):
 *
 *     ١. `product_details.unit_price` لآخر صفٍّ في المستودع
 *     ٢. `products.purchase_price`
 *     ٣. `AVG(warehouse_permits_products.unit_price)` — متوسّطٌ حسابيّ
 *
 * وكلُّ درجةٍ فيه عطل:
 *
 * **الأولى** تأخذ `unit_price` من **آخر صفٍّ بالمعرّف** في
 * `product_details` — وهو سعرُ آخر إدخالٍ لا متوسّطُ ما في المخزن. فصنفٌ
 * منه مئةٌ بعشرة واشتُري منه واحدٌ بخمسين يُقيَّد المباعُ منه كلُّه بخمسين.
 *
 * **والثانية** `purchase_price` هو **سعرُ الشراء الأخير** الذي تكتبه شاشةُ
 * المشتريات — وهو سعرُ صفقةٍ لا تكلفةُ مخزون. وبيعُ اليوم من بضاعةٍ
 * اشتُريت قبل شهرٍ بسعرٍ آخر يُقيَّد بسعر اليوم، فيظهر ربحٌ أو خسارةٌ لا
 * وجودَ لها.
 *
 * **والثالثة** `avg('unit_price')` متوسّطٌ **غيرُ مرجَّح**: شراءُ ألفِ وحدةٍ
 * بعشرةٍ وشراءُ وحدةٍ بمئة يعطي ٥٥ — وهو رقمٌ لا يمتّ للواقع بصلة. وهي
 * تجمع كذلك حركاتِ **البيع** نفسَها، وسطورُها تحمل **سعرَ البيع** في
 * `unit_price` — فتدخل أسعارُ البيع في حساب التكلفة.
 *
 * ═════════════════════ وما صار ═════════════════════
 *
 * `Product::averageCost()` — **المتوسّطُ المرجَّح** الذي يعرضه النظامُ على
 * بطاقة كل صنف في وحدة المخزون:
 *
 *     Σ(الكمية × السعر) ÷ Σ(الكمية)
 *
 * محسوباً من حركات الإضافة وحدَها؛ إذ تستثني الدالّةُ المبيعاتِ ومرتجعاتِها
 * والإشعاراتِ الدائنة والتحويلاتِ بين المخازن والصرفَ والسحب — فلا يدخل
 * سعرُ بيعٍ في تكلفة.
 *
 * والفائدةُ الأهمّ أنّ **الرقمَ المقيَّد هو الرقمُ المعروض**: ما يقرؤه
 * المحاسب في قيد تكلفة المبيعات هو ما يراه أمينُ المخزن على بطاقة الصنف —
 * فالفرقُ يُراجَع بالنظر لا بحفر السجلّات.
 *
 * ═════════════════════ والتجميدُ يتقدّم ═════════════════════
 *
 * `invoice_items.unit_cost_at_sale` يُكتب لحظةَ البيع. وما دام موجوداً فهو
 * المرجع: مرتجعُ فاتورةٍ يعكس **ما قُيّد عليها**، لا متوسّطَ اليوم. وإلّا
 * لظهر ربحٌ أو خسارةٌ من مجرّد الردّ.
 */
trait ResolvesProductCost
{
    /**
     * متوسّطُ تكلفة الوحدة الأساسية لصنف.
     *
     * `null` — لا صفر — حين يتعذّر: الصفرُ يعني «تكلفةٌ معدومة» والفراغُ
     * يعني «غيرُ معروفة»، والفرقُ بينهما هو الفرقُ بين قيدٍ صحيحٍ وقيدٍ
     * مضلّل.
     *
     * @param  Product|int|null  $product
     */
    protected function averageUnitCost($product): ?float
    {
        $product = $product instanceof Product
            ? $product
            : ($product ? Product::find($product) : null);

        if (! $product) {
            return null;
        }

        try {
            $avg = $product->averageCost();
        } catch (\Throwable $e) {
            // متوسّطٌ لا يُحسب لا يمنع البيع — والقيدُ يُكتب بما جُمّد أو لا يُكتب
            return null;
        }

        return $avg !== null && (float) $avg > 0 ? round((float) $avg, 2) : null;
    }

    /**
     * تكلفةُ بندِ فاتورةٍ للقيد: المجمَّدةُ إن وُجدت، وإلّا المتوسّط.
     *
     * @param  object|null  $item  بندُ الفاتورة (يُقرأ منه `unit_cost_at_sale`)
     * @param  Product|int|null  $product
     */
    protected function itemUnitCost($item, $product): float
    {
        $frozen = $item->unit_cost_at_sale ?? null;

        if ($frozen !== null && (float) $frozen > 0) {
            return round((float) $frozen, 2);
        }

        return $this->averageUnitCost($product) ?? 0.0;
    }
}
