<?php

namespace Modules\Pos\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Modules\Pos\Services\PosCustody;

/**
 * عهدةُ الكاشير: مستودعٌ يُخصم منه، وخزينةٌ يدخلها النقد.
 *
 * ═══════════════════ لماذا هذا الحارس ═══════════════════
 *
 * البيعُ في نقطة البيع يمسّ طرفين: **المخزون** يُخصم منه الصنف، و**النقد**
 * يدخل خزينةً. والأوّلُ إعدادُ وحدةٍ يُختار في شاشة الإعدادات، والثاني
 * عهدةُ الكاشير من ارتباط الموظّف — انظر [PosCustody].
 *
 * وحين لا يُضبط أحدُهما، كان النظامُ يُكمل على أيّة حال:
 *
 *   • **المخزون** كان يسقط إلى `StoreHouse::first()` — أوّلُ مستودعٍ في
 *     الجدول. فتُقرأ الكمّياتُ من مخزنٍ لا شأنَ له به: صنفٌ عنده منه ألف
 *     يظهر «نفدت الكمّية»، وصنفٌ لا يملكه يظهر متاحاً فيبيعه — ثم يُخصم
 *     من مخزن قسمٍ آخر ويظهر العجزُ في جردهم.
 *
 *   • **النقد** يدخل الخزينة الافتراضية، فيجتمع نقدُ الكاشيرين في عهدةٍ
 *     لا صاحبَ لها. وعند الإقفال يظهر فرقٌ لا يُعرف على مَن.
 *
 * والفشلُ في الحالتين **صامت**: لا خطأ، إنما أرقامٌ خاطئةٌ تُبنى عليها
 * قيودٌ محاسبية. وقيدٌ خاطئٌ أصعبُ إصلاحاً من بابٍ مغلق.
 *
 * ═══════════════════ ومَن لا يُحرَس ═══════════════════
 *
 * **غيرُ الموظّف** (مستخدمٌ إداريّ بلا `employee_id`) يمرّ: لا عهدةَ له
 * أصلاً، وهو يفتح الشاشةَ للمراجعة لا للبيع. وهذا يوافق قاعدةَ نطاق
 * البيانات في الوحدة كلِّها: ما لا يرتبط بموظّفٍ لا يُقيَّد بارتباطه.
 *
 * ═══════════════════ وما لا يفعله ═══════════════════
 *
 * لا يمنع من وحدة نقاط البيع كلِّها — إنما من **شاشة البيع** وحدها.
 * فالتقاريرُ والإعداداتُ والجلساتُ لا تمسّ عهدةً، ومشرفٌ بلا مستودعٍ يظلّ
 * يراجعها.
 */
class EnsurePosCustody
{
    public function handle(Request $request, Closure $next)
    {
        $user = auth()->user();

        // غيرُ الموظّف لا عهدةَ له
        if (! $user?->employee_id) {
            return $next($request);
        }

        /*
            العهدةُ عهدةُ **موظّف الجهاز** لا المستخدم الحالي.

            كان الفحصُ على `$user->employee_id` مباشرةً. ومشرفٌ يفتح جلسةً
            على جهاز كاشيرٍ يبيع من عهدة ذلك الكاشير — فلا معنى لفحص عهدةِ
            المشرف. و[PosCustody] هي التي تحسم الموظّفَ ثم عهدتَه، وهي
            نفسُها التي يقرأ منها العرضُ والخصم: فلا يُمنع الدخولُ لسببٍ
            ويُقرأ المخزونُ بآخر.
        */
        $missing = PosCustody::missing($user->id);

        if (! $missing) {
            return $next($request);
        }

        /*
            الرسالةُ تقول **ما ينقص** و**أين يُضبط**.
            «لا تملك صلاحية» تُرسل المستخدمَ إلى المدير بلا سؤالٍ محدَّد.
        */
        $what = implode('، و', $missing);

        $message = "لا يمكن فتح شاشة البيع — ينقص: {$what}. "
            .'فالبيعُ يخصم من مستودع نقطة البيع ويُدخل النقدَ في خزينة الكاشير، '
            .'ولا يصحّ أن يُخمَّن أيٌّ منهما.';

        if ($request->expectsJson()) {
            return response()->json([
                'success' => false,
                'message' => $message,
                'missing' => $missing,
            ], 403);
        }

        return redirect()
            ->route('dashboard.pos')
            ->with('error', $message);
    }
}
