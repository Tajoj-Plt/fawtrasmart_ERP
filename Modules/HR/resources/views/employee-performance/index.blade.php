            document.getElementById('month_filter').style.display = 'block';
        } else if (filterType === 'day') {
            document.getElementById('day_filter').style.display = 'block';
        } else if (filterType === 'range') {
            document.getElementById('from_date_filter').style.display = 'block';
            document.getElementById('to_date_filter').style.display = 'block';
        }
    }

