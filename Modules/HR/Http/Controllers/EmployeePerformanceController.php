        }

        $result = $query->selectRaw('SUM(journal_entry_details.debit) - SUM(journal_entry_details.credit) as total')->first();

        return (float) ($result->total ?? 0);
    }

    /**
     * الحصول على مصروفات الموظف من القيود المحاسبية
     * Generated by Copilot - المصروفات = كل القيود التي تكون فيها خزينة الموظف دائنة (خروج أموال)
     * لا يهم من أنشأ القيد - المهم أن تخرج من خزينة الموظف
     * مع استثناء التحويلات بين الخزائن/البنوك ومردودات المبيعات
     */
    private function getEmployeeExpenses($userId, $startDate, $endDate)
    {
        // جلب employee_id من جدول users
        $user = User::find($userId);
        if (! $user || ! $user->employee_id) {
            return 0;
        }

        // جلب خزينة الموظف المحددة باستخدام employee_id
        $treasuryEmployee = TreasuryEmployee::where('employee_id', $user->employee_id)->first();

        if (! $treasuryEmployee || ! $treasuryEmployee->treasury_id) {
            return 0;
        }

        $employeeTreasuryId = $treasuryEmployee->treasury_id;

        // جلب جميع حسابات الخزينة والبنوك (للتحقق من التحويلات)
        $treasuryAndBankAccounts = Account::whereIn('parent_id', [
            SystemAccountIds::CASH_TREASURIES_PARENT,  // 13
            SystemAccountIds::BANK_ACCOUNTS_PARENT,     // 15
        ])->pluck('id')->toArray();

        // جلب القيود التي تكون فيها خزينة الموظف دائنة (خروج أموال) - بغض النظر عمن أنشأها
        $journalEntryIds = JournalEntryDetail::whereHas('journalEntry', function ($query) use ($startDate, $endDate) {
            $query->whereBetween('date', [$startDate, $endDate])
                ->where('status', 1); // معتمد فقط
        })
            ->where('account_id', $employeeTreasuryId)
            ->where('credit', '>', 0) // خزينة الموظف دائنة = خروج أموال
            ->pluck('journal_entry_id')
            ->unique()
            ->toArray();

        if (empty($journalEntryIds)) {
            return 0;
        }

        // استثناء القيود التي تكون بين خزينتين/بنكين (تحويلات) أو تحتوي على مردودات مبيعات
        $excludedEntryIds = [];
        foreach ($journalEntryIds as $entryId) {
            $details = JournalEntryDetail::where('journal_entry_id', $entryId)->get();

            $hasDebitTreasury = $details->whereIn('account_id', $treasuryAndBankAccounts)->where('debit', '>', 0)->isNotEmpty();
            $hasCreditTreasury = $details->whereIn('account_id', $treasuryAndBankAccounts)->where('credit', '>', 0)->isNotEmpty();
            $hasSalesReturns = $details->where('account_id', SystemAccountIds::SALES_RETURNS)->isNotEmpty();

            // إذا كان المدين والدائن كلاهما خزينة/بنك = تحويل
            // أو إذا كان القيد يحتوي على مردودات مبيعات
            if (($hasDebitTreasury && $hasCreditTreasury) || $hasSalesReturns) {
                $excludedEntryIds[] = $entryId;
            }
        }

        // استثناء التحويلات ومردودات المبيعات
        $validJournalEntryIds = array_diff($journalEntryIds, $excludedEntryIds);

        if (empty($validJournalEntryIds)) {
            return 0;
        }

        // حساب المصروفات: فقط الدائن (خروج أموال) من خزينة الموظف
        $expensesData = JournalEntryDetail::whereIn('journal_entry_id', $validJournalEntryIds)
            ->where('account_id', $employeeTreasuryId)
            ->where('credit', '>', 0)
            ->selectRaw('SUM(credit) as total_credit')
            ->first();

        return $expensesData->total_credit ?? 0;
    }

    /**
     * جلب جميع حسابات المصروفات بشكل تكراري (جميع الأبناء والأحفاد)
     * Generated by Copilot
     * يعتمد على أصناف المصروفات (ExpensesCategory) للبحث عن الحسابات المطابقة
     */
    private function getAllExpenseAccountsRecursive()
    {
        $expenseAccountIds = [];

        // الطريقة الأولى: البحث عن الحسابات بناءً على أصناف المصروفات
        $expenseCategories = ExpensesCategory::where('status', 'active')->get();

        foreach ($expenseCategories as $category) {
            // البحث عن الحسابات التي تطابق اسم الصنف
            $matchingAccounts = Account::where(function ($query) use ($category) {
                $query->where('name', 'LIKE', '%'.$category->name.'%')
                    ->orWhere('name', $category->name);
            })
                ->where('is_active', 1)
                ->pluck('id')
                ->toArray();

            $expenseAccountIds = array_merge($expenseAccountIds, $matchingAccounts);
        }

        // الطريقة الثانية: البحث التكراري من حساب المصروفات الرئيسي
        $parentIds = [SystemAccountIds::EXPENSES]; // 5

        // نضيف حساب المصروفات نفسه
        $expenseAccountIds[] = SystemAccountIds::EXPENSES;

        // نبحث عن جميع الأبناء بشكل تكراري
        while (! empty($parentIds)) {
            $children = Account::whereIn('parent_id', $parentIds)
                ->where('is_active', 1)
                ->pluck('id')
                ->toArray();

            if (empty($children)) {
                break;
            }

            $expenseAccountIds = array_merge($expenseAccountIds, $children);
            $parentIds = $children;
        }

        // إزالة التكرارات وإرجاع المصفوفة
        return array_unique($expenseAccountIds);
    }

    /**
     * الحصول على هدف الموظف
     */
    /**
     * الانضباط — وهو ما تقيسه الموارد البشرية أصلاً.
     *
     * الشاشةُ كانت تعرض المبيعات والتحصيلات والمردودات وحدها، ولا تعرض
     * حرفاً عن الحضور والتأخير والغياب — رغم أن `attendance_days` مملوءٌ
     * ومعالجُ الحضور يحسب دقائق التأخير والانصراف المبكر والعمل الإضافي
     * لكل يوم.
     */
    private function getAttendanceMetrics(int $employeeId, $startDate, $endDate): array
    {
        $days = DB::table('attendance_days')
            ->where('employee_id', $employeeId)
            ->whereBetween('attendance_date', [$startDate->toDateString(), $endDate->toDateString()])
            ->get(['status', 'late_minutes', 'early_leave_minutes', 'overtime_minutes']);

        // أيامُ العطل والإجازات لا تدخل في المقام: نسبةُ حضورٍ تُقسَم على
        // أيامٍ لا عمل فيها تظلم صاحبها.
        $workingDays = $days->whereNotIn('status', [
            AttendanceDays::STATUS_HOLIDAY,
            AttendanceDays::STATUS_LEAVE,
        ]);

        $present = $workingDays->whereIn('status', [
            AttendanceDays::STATUS_PRESENT,
            AttendanceDays::STATUS_LATE,
            AttendanceDays::STATUS_HALF_DAY,
        ])->count();

        $workingCount = $workingDays->count();

        return [
            'working_days' => $workingCount,
            'present_days' => $present,
            'absent_days' => $workingDays->where('status', AttendanceDays::STATUS_ABSENT)->count(),
            'late_days' => $workingDays->where('status', AttendanceDays::STATUS_LATE)->count(),
            'attendance_rate' => $workingCount > 0 ? round(($present / $workingCount) * 100, 1) : null,
            'late_minutes' => (int) $days->sum('late_minutes'),
            'early_leave_minutes' => (int) $days->sum('early_leave_minutes'),
            'overtime_minutes' => (int) $days->sum('overtime_minutes'),
        ];
    }

    /** الإجازات: المستهلك في الفترة، وما ينتظر قرار المدير. */
    private function getLeaveMetrics(int $employeeId, $startDate, $endDate): array
    {
        $requests = DB::table('leave_requests')
            ->where('employee_id', $employeeId)
            ->whereBetween('start_date', [$startDate->toDateString(), $endDate->toDateString()])
