    private function getCollectionsTrendData($branchId)
    {
        $treasuryAndBankAccounts = Account::whereIn('parent_id', [
            SystemAccountIds::CASH_TREASURIES_PARENT,
            SystemAccountIds::BANK_ACCOUNTS_PARENT,
        ])->pluck('id')->toArray();

        $results = JournalEntryDetail::join('journal_entries', 'journal_entry_details.journal_entry_id', '=', 'journal_entries.id')
            ->whereYear('journal_entries.date', Carbon::now()->year)
            ->where('journal_entries.status', 1)
            ->whereIn('journal_entry_details.account_id', $treasuryAndBankAccounts)
            ->where('journal_entry_details.debit', '>', 0)
            ->when($branchId, function ($q) use ($branchId) {
                $q->join('clients', 'journal_entries.client_id', '=', 'clients.id')->whereIn('clients.branch_id', BranchTree::ids($branchId) ?? [$branchId]);
            })
            ->whereNotExists(function ($sub) use ($treasuryAndBankAccounts) {
                $sub->select(DB::raw(1))->from('journal_entry_details as jed2')
                    ->whereColumn('jed2.journal_entry_id', 'journal_entry_details.journal_entry_id')
                    ->whereIn('jed2.account_id', $treasuryAndBankAccounts)->where('jed2.credit', '>', 0);
            })
            ->select(DB::raw('MONTH(journal_entries.date) as month'), DB::raw('SUM(journal_entry_details.debit) as total'))
            ->groupBy('month')->get()->keyBy('month');

        $data = [];
        for ($m = 1; $m <= 12; $m++) {
            $data[] = isset($results[$m]) ? (float) $results[$m]->total : 0;
        }

        return $data;
    }

