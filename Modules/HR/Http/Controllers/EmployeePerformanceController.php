    /**
     * تصدير البيانات إلى Excel
     */
    /**
     * تصديرُ الشاشة إلى Excel.
     *
     * كانت تعيد `{"message": "قريباً"}` بلا ملف. والمكتبة مثبّتةٌ في المشروع،
     * وتستعملها شاشةُ الموظفين في الوحدة نفسها.
     */
    public function export(Request $request)
    {
        // نفسُ الفترة ونفسُ الفلاتر التي تعرضها الشاشة — لا تصديرَ لبياناتٍ
        // غير التي أمام المستخدم
        [$startDate, $endDate] = $this->resolvePeriod($request);

        $branchId = $request->input('branch_id');
        $effectiveBranchId = in_array($branchId, ['0', '', null], true) ? null : (int) $branchId;

        $performance = $this->getEmployeesPerformance(
            $startDate,
            $endDate,
            $effectiveBranchId,
            $request->input('employee_id'),
            false
        );

        $fileName = 'employee-performance-'.$startDate->format('Y-m-d').'_'.$endDate->format('Y-m-d').'.xlsx';

        return Excel::download(new EmployeePerformanceExport($performance), $fileName);
    }

    /**
     * الفترةُ الزمنية من الفلاتر — مستخلَصةٌ ليشترك فيها العرضُ والتصدير.
     */
    private function resolvePeriod(Request $request): array
    {
        $filterType = $request->input('filter_type', 'month');

        if ($filterType === 'day' && $request->filled('day')) {
            $day = Carbon::parse($request->input('day'));

            return [$day->copy()->startOfDay(), $day->copy()->endOfDay()];
        }

        if ($filterType === 'range' && $request->filled('from_date') && $request->filled('to_date')) {
            return [
                Carbon::parse($request->input('from_date'))->startOfDay(),
                Carbon::parse($request->input('to_date'))->endOfDay(),
            ];
        }

        $month = $request->input('month', now()->format('Y-m'));

        if (str_contains((string) $month, '-')) {
            [$year, $monthNum] = explode('-', $month);

            return [
                Carbon::createFromDate((int) $year, (int) $monthNum, 1)->startOfMonth(),
                Carbon::createFromDate((int) $year, (int) $monthNum, 1)->endOfMonth(),
            ];
        }

        return [now()->startOfMonth(), now()->endOfMonth()];
    }

