    private function calculateTotalStats($employeesPerformance)
    {
        return [
            'total_employees' => $employeesPerformance->count(),
            'total_clients' => $employeesPerformance->sum('clients_count'),
            'total_sales' => $employeesPerformance->sum('sales'),
            'total_collections' => $employeesPerformance->sum('collections'),
            'total_returns' => $employeesPerformance->sum('returns'),
            'total_expenses' => $employeesPerformance->sum('expenses'),
            'total_target' => $employeesPerformance->sum('target'),

            /*
                متوسّطُ التحقيق على أصحاب الأهداف وحدهم. حسابُه على الجميع
                يقسم على موظفين بلا هدفٍ أصلاً فيهبط المتوسّط بلا معنى.
            */
            'average_achievement' => $employeesPerformance
                ->where('target', '!=', null)
                ->avg('achievement_percentage') ?? 0,

            // ملخّصُ الانضباط — ما يخصّ الموارد البشرية من هذه الشاشة
            'total_late_days' => $employeesPerformance->sum('late_days'),
            'total_absent_days' => $employeesPerformance->sum('absent_days'),
            'total_late_minutes' => $employeesPerformance->sum('late_minutes'),
            'total_overtime_minutes' => $employeesPerformance->sum('overtime_minutes'),
            'total_leave_days' => $employeesPerformance->sum('leave_days_taken'),
            'total_leave_pending' => $employeesPerformance->sum('leave_pending'),
            'total_deductions' => $employeesPerformance->sum('deductions_amount'),
            'average_attendance_rate' => round(
                $employeesPerformance->whereNotNull('attendance_rate')->avg('attendance_rate') ?? 0, 1
            ),
            'commercial_count' => $employeesPerformance->where('has_commercial_activity', true)->count(),
        ];
    }

