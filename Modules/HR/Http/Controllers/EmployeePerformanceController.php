            $query->whereAccountOrEmployeeBranchTree($effectiveBranchId);
        }

        return $query->orderBy('name')->get();
    }

    /**
     * حساب الإحصائيات الإجمالية (من صفوف الجدول؛ تُستبدل المبيعات/التحصيلات/المردودات من الداشبورد عند عرض الجميع)
