    /**
     * عرض صفحة أداء الموظفين
     * Generated by Copilot - دعم الفلاتر المتعددة
     */
    public function index(Request $request)
    {
        try {
            /*
                الصلاحيةُ على المسار (`performance.index`) و«على أيّ موظفين»
                نطاقُ الرؤية — لا حارسٌ ثالث يفتح الشاشةَ لكل من له سجلُّ موظف.
            */

            // الحصول على الفلاتر من الطلب
            $filterType = $request->input('filter_type', 'month'); // month, day, range
            $month = $request->input('month', now()->format('Y-m'));
            $day = $request->input('day', now()->format('Y-m-d'));
            $fromDate = $request->input('from_date');
            $toDate = $request->input('to_date');
            $branchId = $request->input('branch_id');
            $employeeId = $request->input('employee_id');
            $targetFilter = $request->input('target_filter'); // all, achieved, not_achieved

            // تحديد الفترة الزمنية بناءً على نوع الفلتر
            if ($filterType === 'day' && $day) {
                $startDate = Carbon::parse($day)->startOfDay();
                $endDate = Carbon::parse($day)->endOfDay();
            } elseif ($filterType === 'range' && $fromDate && $toDate) {
                $startDate = Carbon::parse($fromDate)->startOfDay();
                $endDate = Carbon::parse($toDate)->endOfDay();
            } else {
                // الافتراضي: شهر
                if (strpos($month, '-') !== false) {
                    [$year, $monthNum] = explode('-', $month);
                    $startDate = Carbon::createFromDate($year, $monthNum, 1)->startOfMonth();
                    $endDate = Carbon::createFromDate($year, $monthNum, 1)->endOfMonth();
                } else {
                    $startDate = now()->startOfMonth();
                    $endDate = now()->endOfMonth();
                }
            }

            // التحقق من صلاحيات المستخدم
            $user = auth()->user();
            $currentBranchId = $user->branch_id;
            $isMainBranch = false;

            if ($currentBranchId) {
                $branch = Branch::find($currentBranchId);
                $isMainBranch = $branch && $branch->is_main == 1;
            }

            // الفرع من الطلب فقط؛ الافتراضي = جميع الفروع
            if ($branchId === '0' || $branchId === '' || $branchId === null) {
                $effectiveBranchId = null;
            } else {
                $effectiveBranchId = $branchId;
            }

            $isMainBranchForQueries = ($effectiveBranchId === null) ? true : $isMainBranch;

            // الحصول على بيانات أداء الموظفين
            $employeesPerformance = $this->getEmployeesPerformance(
                $startDate,
                $endDate,
                $effectiveBranchId,
                $employeeId,
                $isMainBranchForQueries
            );

            // تطبيق فلتر الهدف
            if ($targetFilter === 'achieved') {
                $employeesPerformance = $employeesPerformance->filter(fn ($emp) => $emp['achievement_percentage'] >= 100);
            } elseif ($targetFilter === 'not_achieved') {
                $employeesPerformance = $employeesPerformance->filter(fn ($emp) => $emp['achievement_percentage'] < 100);
            }

            // الحصول على قائمة الفروع للفلترة
            $branches = Branch::where('status', 'active')->get();

            // الحصول على قائمة الموظفين للفلترة (كل الفروع ما لم يُختر فرع)
            $employees = $this->scopeToEmployees(
                User::whereNotNull('employee_id')
                    ->whereHas('employee', fn ($query) => $query->active()),
                'employee_id'
            )
                ->when($effectiveBranchId, fn ($q) => $q->whereAccountOrEmployeeBranchTree($effectiveBranchId))
                ->orderBy('name')
                ->get();

            // الإحصائيات الإجمالية: المبيعات/التحصيلات/المردودات = نفس لوحة المبيعات (حسب فرع العميل)
            // وليس مجموع صفوف الموظفين (created_by_employee) لتطابق الداشبورد عند «جميع الموظفين»
            $totalStats = $this->calculateTotalStats($employeesPerformance);
            // أرقامُ المنشأة لمن نطاقُه المنشأةُ كلُّها؛ ومن ضاق نطاقُه فمجموعُ صفوف من يراهم وحدهم
            if (! $employeeId && $this->accessibleEmployeeIds() === null) {
                $totalStats['total_sales'] = (float) $this->getDashboardKpiTotalSales(
                    $effectiveBranchId,
                    $isMainBranchForQueries,
                    $startDate,
                    $endDate
                );
                $totalStats['total_collections'] = (float) $this->getDashboardKpiTotalCollections(
                    $effectiveBranchId,
                    $isMainBranchForQueries,
                    $startDate,
                    $endDate
                );
                $totalStats['total_returns'] = (float) $this->getDashboardKpiTotalReturns(
                    $effectiveBranchId,
                    $isMainBranchForQueries,
                    $startDate,
                    $endDate
                );
            }

            $showBranchFilter = true;

            /*
                الجدولُ كان يعرض المجموعة كاملةً بلا ترقيم صفحات — عشراتُ
                الموظفين في صفحةٍ واحدة. الإحصائياتُ الإجمالية تُحسب أعلاه
                على المجموعة الكاملة قبل التقطيع، فلا يتأثر مجموعُ الفرز
                بصفحة العرض الحالية.
            */
            $perPage = (int) $request->input('per_page', 10);
            if (! in_array($perPage, [10, 25, 50, 100], true)) {
                $perPage = 10;
            }
            $employeesPerformance = $employeesPerformance->values();
            $currentPage = \Illuminate\Pagination\LengthAwarePaginator::resolveCurrentPage();
            $employeesPerformance = new \Illuminate\Pagination\LengthAwarePaginator(
                $employeesPerformance->forPage($currentPage, $perPage)->values(),
                $employeesPerformance->count(),
                $perPage,
                $currentPage,
                ['path' => \Illuminate\Pagination\LengthAwarePaginator::resolveCurrentPath(), 'query' => $request->query()]
            );

            return view('hr::employee-performance.index', compact(
                'employeesPerformance',
                'month',
                'day',
                'fromDate',
                'toDate',
                'filterType',
                'branches',
                'employees',
                'effectiveBranchId',
                'employeeId',
                'targetFilter',
                'isMainBranch',
                'showBranchFilter',
                'totalStats'
            ));

        } catch (\Exception $e) {
            Log::error('Employee Performance Error: '.$e->getMessage());

            return redirect()->back()->withErrors(['error' => 'حدث خطأ: '.$e->getMessage()]);
        }
    }

    /**
     * الحصول على بيانات أداء الموظفين
     * Generated by Copilot - دعم الفلاتر المتعددة + استبعاد غير النشطين
     */
    private function getEmployeesPerformance($startDate, $endDate, $branchId, $employeeId = null, $isMainBranch = false)
    {
        // الحصول على جميع المستخدمين الذين لديهم employee_id
        $employeesQuery = User::whereNotNull('employee_id')
            ->whereHas('employee', fn ($query) => $query->active());

        // نطاقُ الرؤية: `users.employee_id` هو محورُ الموظف في هذا الاستعلام
        $this->scopeToEmployees($employeesQuery, 'employee_id');

        // تطبيق فلتر الفرع إذا تم تحديده (حساب المستخدم أو سجل الموظف)
        if ($branchId) {
            $employeesQuery->whereAccountOrEmployeeBranchTree($branchId);
        }

        // تطبيق فلتر الموظف إذا تم تحديده
        if ($employeeId) {
            $employeesQuery->where('id', $employeeId);
        }

        $employees = $employeesQuery->with(['employee', 'branch'])->get();

        Log::info('عدد الموظفين المسترجعين', ['count' => $employees->count()]);

        return $employees->map(function ($employee) use ($startDate, $endDate, $branchId, $isMainBranch) {
            $employeeData = $employee->employee;

            if (! $employeeData) {
                return null;
            }

            return array_merge([
                'employee_id' => $employee->id,
                'employee_db_id' => $employeeData->id,
                'employee_name' => $employee->name,
                'employee_photo' => $employeeData->employee_photo ?? null,
                'branch_name' => optional($employee->branch)->name ?? 'غير محدد',
                'job_title' => optional($employeeData->job_title)->name ?? 'غير محدد',
                'clients_count' => $this->getEmployeeClientsCount($employee->id, $employeeData->id),
                'sales' => $this->getEmployeeSales($employee->id, $startDate, $endDate, $branchId, $isMainBranch),
                'collections' => $this->getEmployeeCollections($employee->id, $startDate, $endDate, $branchId, $isMainBranch),
                'returns' => $this->getEmployeeReturns($employee->id, $startDate, $endDate, $branchId, $isMainBranch),
                'expenses' => $this->getEmployeeExpenses($employee->id, $startDate, $endDate),
                'target' => $this->getEmployeeTarget($employee->id),
                'achievement_percentage' => 0, // تُحسب أدناه متى وُجد هدف
            ], $this->getAttendanceMetrics($employeeData->id, $startDate, $endDate),
                $this->getLeaveMetrics($employeeData->id, $startDate, $endDate),
                $this->getPayrollImpact($employeeData->id, $startDate, $endDate));
        })->filter()->map(function ($performance) {
            if ($performance['target'] !== null && $performance['target'] > 0) {
                $performance['achievement_percentage'] = round(($performance['sales'] / $performance['target']) * 100, 2);
            }

            /*
                قسمُ المبيعات يخصّ من يبيع. الشاشةُ كانت تعرض المبيعات
                والتحصيلات والمردودات والهدف لكلِّ موظفٍ في المنشأة — فيظهر
                المحاسبُ وأمينُ المخزن بصفٍّ من الأصفار ونسبة تحقيقٍ 0%،
                وكأنهم مقصّرون في عملٍ ليس عملهم.

                التمييزُ هنا من البيانات لا من إعدادٍ إضافي: من أُسنِد إليه
                هدفٌ في `employee_targets`، أو تحرّك له بيعٌ أو تحصيلٌ أو
                مردودٌ في الفترة — فهو صاحبُ نشاطٍ تجاري ويُعرض له القسم.
            */
            $performance['has_commercial_activity'] = $performance['target'] !== null
                || $performance['sales'] > 0
                || $performance['collections'] > 0
                || $performance['returns'] > 0;

            return $performance;
        })->sortByDesc('sales')->values();
    }

