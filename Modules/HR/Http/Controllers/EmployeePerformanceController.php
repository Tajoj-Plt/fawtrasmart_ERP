    /**
     * هدفُ الموظف الشهري من `employee_targets`.
     *
     * كانت هذه الدالّة تتجاهل المُعامل الذي تستقبله وتُرجع رقماً ثابتاً —
     * `Target::find(1)->value ?? 35000` — لكلّ موظفٍ في النظام. أي أن عمود
     * «الهدف» و«نسبة التحقيق» في شاشة الأداء كانا مبنيَّين على رقمٍ مختلق،
     * وجدولُ `employee_targets` المخصَّص لهذا الغرض — وله شاشةُ إدارةٍ
     * قائمة — لا يُقرأ منه حرف.
     *
     * والآن يُقرأ منه. ومن لا هدفَ له يُرجَع له null لا صفر: الفرق أن
     * الشاشة تُخفي عنه قسم المبيعات كلَّه بدل أن تعرضه بنسبة تحقيقٍ 0%
     * وكأنه مقصّر في هدفٍ لم يُسنَد إليه أصلاً.
     *
     * @param  int  $userId  معرّف المستخدم — الجدول يربط بـ user_id
     */
    private function getEmployeeTarget($userId): ?float
    {
        $target = DB::table('employee_targets')
            ->where('user_id', $userId)
            ->value('monthly_target');

        return $target !== null ? (float) $target : null;
    }

