    public const SECTION_ROUTES = 'production-routes';

    /**
     * التكاليف غير المباشرة — البادئة IC، العمود `indirect_costs.code`.
     *
     * كان هذا المستندُ الوحيد في الوحدة بلا رقمٍ إطلاقاً: يُشار إليه في
