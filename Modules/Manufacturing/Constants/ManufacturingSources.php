    /** إرجاع مواد خام غير مستهلكة إلى المستودع. */
    public const PERMIT_RETURNED_MATERIALS = 16;

    /** صرف المواد الخام من المستودع إلى الإنتاج. */
    public const PERMIT_ISSUE_MATERIALS = 17;

    // ─────────────────────────────────────────────────────────────────
    // نوع الإذن — من عمود permission_type
    // ─────────────────────────────────────────────────────────────────

    /** إذن إضافة (وارد). */
    public const TYPE_ADD = 1;

    /** إذن صرف (صادر). */
    public const TYPE_ISSUE = 2;

    // ─────────────────────────────────────────────────────────────────
    // حالة الإذن
    // ─────────────────────────────────────────────────────────────────

    /**
     * إذن معتمد — يؤثر في المخزون فوراً.
     *
     * ⚠️ القيمة `'apporod'` بخطأ إملائي **متعمَّد**: هي قيمة الموافقة
     * المعتمدة في هذا النظام فعلاً، مكتوبةً هكذا في الجدول وفي أكثر من
     * ثلاثين موضعاً في الكود.
     *
     * ولا يكفي أن تكون قريبة: `StorehouseController` يحسب رصيد المستودع
     * بمطابقةٍ حرفية واحدة لا تقبل بديلاً —
     *
     *     WarehousePermits::where('status', 'apporod')     // :654، :799، :981
     *
     * فأيّ قيمة أخرى — `1` أو `'approved'` — تُخرج الإذن من حساب الرصيد
     * ومن شاشة الأذون الموافَق عليها بينما المخزون تحرّك به فعلاً. وهذا
     * ما يحدث الآن لـ`ProductsController:2539` وحده إذ يكتب `'approved'`.
     *
     * العمود `VARCHAR(50)` منذ الهجرة `2026_05_02_195659`، فالقيمة نصّ لا
     * عدد. التصحيح الإملائي الشامل ممكن لكنه ترحيلٌ يمسّ خمسة موديولات —
     * لا مكان له هنا. نطابق ما هو قائم.
     */
    public const STATUS_APPROVED = 'apporod';

    // ─────────────────────────────────────────────────────────────────
    // مفاتيح الحسابات المحاسبية — من شاشة «الحسابات المحاسبية»
    // ─────────────────────────────────────────────────────────────────
    //
    // تُقرأ عبر AccountingSettings::id($key, $fallback)، فما يربطه
    // المحاسب في الشاشة يسري فوراً، والثابت البرمجي احتياط لا أكثر.

    /** مخزون المواد الخام — يُقرض عند صرف المواد للإنتاج. */

