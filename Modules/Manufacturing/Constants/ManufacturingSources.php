    /**
     * خطط الإنتاج — البادئة PP، العمود `production_plans.code`.
     *
     * القسمُ كان معلَناً في `DocumentSections` بجدولٍ `null` قبل أن يوجد
     * الجدول: مستندٌ يُضبط ترقيمُه في الشاشة ولا شيء خلفه. أُنشئ الجدول
     * في هجرة الوحدة `2026_09_10_000001` ورُبط القسمُ به.
