    /** إذن إضافة مخزون — البادئة WIN */
    public const SECTION_PERMIT_ADD = 'warehouse-add';

    /** إذن صرف مخزون — البادئة WOUT */
    public const SECTION_PERMIT_ISSUE = 'warehouse-dispose';

    /** قوائم مواد الإنتاج — البادئة BOM */
    public const SECTION_BOM = 'production-material-lists';

    /** محطات العمل — البادئة WS */
