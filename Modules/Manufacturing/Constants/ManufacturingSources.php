    public const ACCOUNT_RAW_MATERIALS = 'raw_materials_inventory';

    /** مخزون تحت التشغيل (WIP) — يُدين بالتكاليف ويُقرض بالمنتَج. */
    public const ACCOUNT_WIP = 'work_in_progress_inventory';

    /** مخزون البضاعة الجاهزة — يُدين بالمنتج التام. */
    public const ACCOUNT_FINISHED_GOODS = 'finished_goods_inventory';

    /** مخزون المواد الهالكة. */
    public const ACCOUNT_WASTE = 'waste_inventory';

    /** تكاليف التشغيل والتصنيع — الطرف الدائن لأجور المحطات. */
    public const ACCOUNT_OVERHEAD = 'manufacturing_overhead';

