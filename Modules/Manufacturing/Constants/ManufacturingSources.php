     * المواد، الحالات اليدوية)، وكان تبديلُها يمرّ بلا سطرٍ في أيّ سجلّ.
     *
     * ولا علاقةَ لها في [\App\Models\Log]: الإعدادات صفٌّ واحد لا مستندٌ
     * له خطٌّ زمنيّ في شاشته، فتُقرأ من شاشة «سجلّ النشاط» العامّة.
     */
    public const LOG_SETTINGS = 'manufacturing_settings';
}
