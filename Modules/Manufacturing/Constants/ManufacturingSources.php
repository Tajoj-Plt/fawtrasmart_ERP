<?php

namespace Modules\Manufacturing\Constants;

/**
 * مصادر الإذونات المخزنية وحسابات التصنيع — بأسمائها لا بأرقامها.
 *
 * ── لماذا هذا الملف ──────────────────────────────────────────────────
 *
 * الموديول ينثر الأرقام `15` و`17` و`3` في الكود بلا اسم، وأحدها خطأ:
 *
 *   PermissionSourcesSeeder يعرّف:
 *      3  → أمر تصنيع المنتج الرئيسي
 *      4  → أمر تصنيع المواد الهالكة
 *      15 → تحويل وارد لنقطة البيع        ← ليس تصنيعاً إطلاقاً
 *      16 → أمر تصنيع البنود المرتجعة
 *      17 → أمر تصنيع لصرف المواد
 *
 * و`completeOrder` و`receiveMaterials` و`returnMaterials` تكتب `15`.
 * أي أن كل إذونات التصنيع مسجَّلة تحت «تحويل وارد لنقطة البيع»، فتقارير
 * المخزون تنسب إنتاج المصنع إلى الكاشير، وأي فلترة بالمصدر تُخطئ الوجهة.
 *
 * و`finishOrder` كانت تكتب `3` — وهي **الصحيحة** — لكنها الدالة الميتة
 * التي لا تستدعيها أي واجهة.
 *
 * ── ملاحظة ترحيل ─────────────────────────────────────────────────────
 *
 * تصحيح الرقم يغيّر مصدرَ الإذونات الجديدة وحدها. الإذونات القائمة تحت 15
 * تحتاج تصحيحاً منفصلاً — انظر `docs/manufacturing-data-repair.md`، ولا
 * تُصحَّح إلا بعد التأكد أنها من التصنيع لا من نقطة البيع فعلاً:
 *
 *     SELECT permission_source_id, COUNT(*)
 *     FROM warehouse_permits
 *     WHERE reference_id IN (SELECT id FROM manufactur_orders)
 *     GROUP BY permission_source_id;
 */
final class ManufacturingSources
{
    // ─────────────────────────────────────────────────────────────────
    // مصادر الإذونات المخزنية — من جدول permission_sources
    // ─────────────────────────────────────────────────────────────────

