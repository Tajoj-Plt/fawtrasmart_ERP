    // ═════════════════════════════════════════════════════════════════

    /*
        العكسُ يجب أن يكون انتقائياً بمرحلته.

        `undoCompletion` تتراجع عن الإتمام وحده، فلا يصحّ أن تعكس معه
        قيدَ صرف المواد المُرحَّل في مرحلةٍ سابقة — وإذنُ الصرف لا
        يُعكَس، فتبقى المواد مستهلَكةً ويعود ثمنُها إلى الدفتر.
    */
