{{--
    وصف سطر السجلّ — نقطة عرض واحدة لكل سجلّات المديول.

    ── لماذا ────────────────────────────────────────────────────────────

    كان يُعرض في خمسة قوالب هكذا:

        {!! Str::markdown($log->description ?? 'لا يوجد وصف') !!}

    و`Str::markdown` في Laravel 11 تمرّر HTML الخام كما هو افتراضاً، ووصف
    السجلّ يُبنى بدمج مُدخَلات المستخدم:

        OperationLog::record(…, 'تم اضافة امر تصنيع **'.$order->name.'**');

    فاسمُ أمرٍ مثل `<img src=x onerror=…>` يصير شيفرةً تُنفَّذ في متصفّح كل
    من يفتح ذلك السجلّ — ومنهم المدير. ثغرة XSS مخزَّنة مؤكَّدة بالتشغيل على
    Laravel 11.55.1.

    ── الحل ─────────────────────────────────────────────────────────────

    `html_input => 'escape'` يُهرّب الوسوم ويُبقي تنسيق Markdown عاملاً،
    فيظل `**النص**` عريضاً كما كان. و`strip` كان يحذف الاسم نفسه إن حوى
    قوساً، فلا يصلح.

    و`allow_unsafe_links` يُغلق `javascript:` في أي رابط داخل الوصف.

    ── الاستعمال ────────────────────────────────────────────────────────

        @include('manufacturing::partials.log-description', ['log' => $log])

    جزئيةٌ واحدة لا خمس نسخ: الإصلاح الأمني في موضع واحد، ولا يعود العيب
    بنسخِ سطرٍ من قالبٍ إلى آخر.
--}}
{!! Str::markdown(
    $log->description ?? 'لا يوجد وصف',
    ['html_input' => 'escape', 'allow_unsafe_links' => false]
) !!}
