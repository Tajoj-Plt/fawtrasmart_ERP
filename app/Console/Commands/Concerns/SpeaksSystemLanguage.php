<?php

namespace App\Console\Commands\Concerns;

use App\Models\SystemLanguage;

/**
 * ضبطُ لغة الأمر المجدول على لغة النظام الافتراضية.
 *
 * ══════════════════════════════════════════════════════════════════════
 *  العطل
 * ══════════════════════════════════════════════════════════════════════
 *
 * `config/app.php` يثبّت `'locale' => 'en'` ولا يقرأ `APP_LOCALE` من
 * البيئة. وفي الطلب لا أثر لذلك: `mcamara/laravel-localization` يضبط
 * اللغة من المسار، و`LanguageSettings::apply()` من «اللغات». أمّا في سطر
 * الأوامر فلا واحدٌ منهما يعمل، فتبقى اللغة `en`.
 *
 * والأثر أنّ **كلّ إشعارٍ تكتبه مهمّةٌ مجدولة يُحفَظ بالإنجليزية** في
 * منشأةٍ عربية: يفتح المستخدم جرس الإشعارات فيجد سطراً بلغةٍ لا يقرؤها
 * بين أسطرٍ عربية كتبتها الشاشات.
 *
 * ولا يُعالَج بتغيير `config/app.php`: ذاك يقلب لغةَ كلّ ما يُولَّد خارج
 * الطلب في النظام كلِّه — أوامرَ ومهامَّ وسجلّاتِ أخطاء — وهو أثرٌ أوسع
 * ممّا يُراد.
 *
 * ══════════════════════════════════════════════════════════════════════
 *  والعلاج
 * ══════════════════════════════════════════════════════════════════════
 *
 * `$this->useSystemLanguage()` في أوّل `handle()`: تقرأ اللغة الموسومة
 * افتراضيةً في جدول «اللغات» وتضبطها. فما يُكتب في الإشعار بلغة النظام
 * لا بلغة الإطار.
 *
 * وتصمت إن لم تكن هناك لغةٌ افتراضية أو لم يُهيَّأ الجدول بعد: مهمّةٌ
 * تسقط لأنّ لغةً لم تُضبَط أسوأ من مهمّةٍ تعمل بالإنجليزية.
 */
trait SpeaksSystemLanguage
{
    /**
     * ترتيب البحث عن اللغة:
     *
     *   ١. الموسومة افتراضيةً في «اللغات».
     *   ٢. أوّلُ لغةٍ مفعَّلة فيها.
     *   ٣. `APP_LOCALE` من البيئة — و`.env` في هذا النظام يقول `ar`
     *      بينما `config/app.php` يثبّت `'en'` ولا يقرؤه. لا يُصلَح ذلك
     *      من هنا: تغييرُ الإعداد يقلب لغةَ كلّ ما يُولَّد خارج الطلب في
     *      النظام كلِّه، وهو قرارٌ أوسع من هذه المهمّة.
     *   ٤. وإلّا تُترَك لغةُ الإطار كما هي.
     */
    protected function useSystemLanguage(): void
    {
        try {
            $language = SystemLanguage::default()
                ?: SystemLanguage::where('is_active', true)->first();

            $locale = $language?->locale ?: $language?->code;
        } catch (\Throwable $e) {
            // جدولٌ غير مهيّأ — تُجرَّب البيئة
            $locale = null;
        }

        $locale = $locale ?: env('APP_LOCALE');

        if (is_string($locale) && $locale !== '') {
            app()->setLocale($locale);
        }
    }
}
