<?php

namespace App\Constants\planFeatures;

/**
 * خريطة وحدة العملاء على كتالوج باقة «فوترة» — **وحدودُها الغائبة**.
 *
 * ═══════════════ لماذا هذا الملفّ مختصر؟ ═══════════════
 *
 * لأنّ الكتالوج لا يحمل مفتاحاً واحداً للعملاء. فُحص `UsageReporter::catalog()`
 * كلُّه — ستّةٌ وستّون مفتاحاً — فلا `clients` ولا `customers` ولا `visits`
 * ولا `itineraries` بينها. أقربُ ما فيها إلى الوحدة `employees` و
 * `territory_groups`، وكلاهما يخصّ غيرَها.
 *
 * **ولذلك لا يُخترَع مفتاح.** `SubscriptionGate` تعامل المفتاح المجهول
 * «مسموحاً بلا حدّ» — وهو الصواب لكتالوجٍ قد يسبق النظام أو يتأخّر عنه —
 * فمفتاحٌ مخترَعٌ هنا يُنتج حارساً يعود `true` أبداً: سطرُ حراسةٍ يقرؤه من
 * يراجع الشيفرة فيطمئنّ، ولا يحرس شيئاً. وقد وقع هذا فعلاً في وحدة
 * المشتريات — خمسةُ نداءات `allows()` تمرّر مفاتيح استهلاكٍ إلى خريطة
 * الصلاحيات فتعود `true` دائماً.
 *
 * فالملفّ هنا **سجلُّ ما لا يوجد**: يُقرأ ليُعرف أنّ غياب حراسة الباقة عن
 * شاشات العملاء مقصودٌ لا منسيّ، وليَجد من يضيف المفتاح إلى لوحة فوترة
 * لاحقاً موضعَه جاهزاً.
 *
 * ═══════════════ ما يحرس شاشات العملاء اليوم ═══════════════
 *
 *   ١. **نشاط الاشتراك** — `EnsureSubscription` على مجموعتَي `web` و`api`
 *      معاً، فلا يبلغ متحكّمَ عميلٍ طلبٌ واشتراكُ المنشأة موقوف. وهذه
 *      الطبقةُ وحدها تعمل اليوم على الوحدة.
 *   ٢. **صلاحيات النظام** — [\App\Constants\permissions\ClientsPermissions]:
 *      من يفعل ماذا داخل المنشأة.
 *
 * والطبقتان لا تُغنيان عن الثالثة: صلاحيةُ النظام تقول «من»، وحدُّ الباقة
 * يقول «كم». الثانية غائبةٌ للعملاء حتى تُضيفها اللوحة.
 *
 * ═══════════════ متى يُملأ هذا الملفّ؟ ═══════════════
 *
 * حين تُضيف لوحة فوترة مفتاحاً للعملاء، خطوتان لا أكثر:
 *
 *   ١. ثابتٌ هنا باسم المفتاح **كما تكتبه اللوحة حرفياً** — لا كما نتوقّعه.
 *   ٢. مدخلٌ في `UsageReporter::catalog()` يعدّ الصفوف محلياً، وإلّا بقي
 *      الحدُّ يُقرأ من لقطةٍ عمرُها ربعُ ساعة.
 *
 * ثمّ — وليس قبلُ — تُنادى `allows()`/`checkLive()` في `ClientController`.
 *
 * @see \Modules\Sales\Http\Controllers\Concerns\ChecksSubscriptionLimits النمط حين يوجد مفتاح
 * @see docs/Subscription_Plan_Enforcement_Guide.md طبقات الحراسة الأربع
 */
class ClientsPlanFeatures
{
    /**
     * مفاتيحُ استهلاكٍ في الكتالوج تلامس الوحدة ولا تخصّها.
     *
     * تُذكر لتُعرف حدودُها ولا تُخلط: `employees` سقفُ مقاعدِ الموظفين في
     * الموارد البشرية — يُصيب من يُسنَد إليه العميل، ولا يعدّ العملاء.
     * و`territory_groups` سقفُ مجموعات المناطق في الفروع — تُبنى عليها
     * خطوطُ السير، ولا تعدّ خطوطَ السير.
     *
     * @var array<string, string>
     */
    public const ADJACENT_LIMITS = [
        'employees' => 'مقاعد الموظفين (الموارد البشرية) — يحدّ من يُسنَد إليه العملاء',
        'territory_groups' => 'مجموعات المناطق (الفروع) — تُبنى عليها خطوط السير',
    ];

    /**
     * أشاشاتُ العملاء محدودةٌ بالباقة؟
     *
     * `false` دائماً اليوم — ولا تُبنى عليها حراسةٌ صامتة. الغرضُ أن يكتب
     * الاستدعاءُ الشرطَ صراحةً بدل أن يفترض، فيبقى موضعُ التغيير واحداً حين
     * يُضاف المفتاح.
     */
    public static function hasPlanLimit(): bool
    {
        return false;
    }

    /**
     * مفتاحُ الحدّ المقابل لصلاحية باقة — لا شيء اليوم.
     *
     * توقيعُها مطابقٌ لنظائرها في الوحدات الأخرى (`SalesPlanFeatures::limitOf()`)
     * عمداً: من ينسخ نمطاً من هناك يجد الدالّة هنا فيرى `null` ويقرأ السبب،
     * بدل أن يفترض أنّ الملفّ ناقص.
     */
    public static function limitOf(string $permission): ?string
    {
        return null;
    }
}
