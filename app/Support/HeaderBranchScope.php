<?php

namespace App\Support;

use App\Models\Branch;

/**
 * ══════════════════════════════════════════════════════════════════════
 * ماذا يعني الفرعُ المختار في الشريط العلويّ؟
 * ══════════════════════════════════════════════════════════════════════
 *
 * مبدّلُ الفروع في الشريط يكتب `users.branch_id`، و`current_branch_id()`
 * تقرؤه. لكنّ قراءتَه وحدها لا تكفي لترشيح قائمة: هناك حالتان تعنيان
 * «المنشأة كلَّها» لا عقدةً بعينها —
 *
 *   • **لا فرعَ مختاراً** (`null`): المستخدم على «كلّ الفروع».
 *   • **الفرع الرئيسيّ** (`is_main`): يعني المنشأة كلَّها بالاصطلاح لا
 *     شجرتَه هو. وهذا مقصودٌ بطلب المستخدم، وله سببٌ في البيانات: الرئيسيُّ
 *     في هذا التركيب عقدةُ جذرٍ لا يتبعها إلّا ابنٌ واحد — ٤١٠ عميلاً من
 *     ٣٨٥٢ — فترشيحُ القوائم على شجرته يُخفي تسعةَ أعشار عملاء المنشأة عمّن
 *     يقف عليه، وهو الوضعُ الافتراضيّ لأكثر المستخدمين.
 *
 * ولذلك تُقرأ `is_main` لا `parent_id === null`: الجذورُ في هذه الشجرة
 * كثيرة («منطقة الرياض» جذرٌ أيضاً)، وهي مناطقُ يجب أن تُرشِّح لا أن تفتح.
 *
 * ── الاستعمال ──
 *
 *     $node = HeaderBranchScope::nodeId();
 *
 *     // عميلٌ يتعلّق بعقدةٍ بثلاثة طرق — `Client::scopeInTreeNode` تعرفها
 *     $clients->when($node, fn ($q) => $q->inTreeNode($node));
 *
 *     // ومورِّدٌ له `branch_id` وحده — `BelongsToBranch::scopeForBranch`
 *     $suppliers->when($node, fn ($q) => $q->forBranch($node));
 *
 * والنطاقان كلاهما **شاملٌ لما تحت العقدة**: من اختار منطقةً رأى عملاء
 * منافذها، وإلّا بدت المنطقةُ فارغةً وعملاؤها كلُّهم معلَّقون تحت أبنائها.
 */
final class HeaderBranchScope
{
    /**
     * العقدةُ التي تُرشَّح عليها القوائم — أو `null` حين لا ترشيح.
     *
     * @param  int|null  $override  عقدةٌ صريحة بدل ما في الشريط
     */
    public static function nodeId(?int $override = null): ?int
    {
        $nodeId = $override ?? current_branch_id();

        if (! $nodeId) {
            return null;
        }

        if (! self::meansWholeOrganisation($nodeId)) {
            return (int) $nodeId;
        }

        /*
            الرئيسيّ يرفع قيدَ المكان عن القوائم — لكن لا يمنح أحداً ما ليس
            له. كان يُرجع `null` لكل من وقف عليه، فشاشةٌ لا تحرس إلّا بهذه
            العقدة تعرض المنشأةَ كلَّها لموظف فرعٍ فرعيٍّ بدّل إليه من الشريط.

              • بلا قيد ({@see DataScope::isUnrestricted()}) — مالكُ
                `data_scope_all`، ومن ليس موظفاً، ومديرُ الرئيسيّ ذو نطاق
                الفرع/المنطقة: المنشأةُ كلُّها.
              • محورُ أشخاص (موظفٌ عاديّ/مشرف): الرئيسيّ فرعٌ كغيره — مستنداتُه
                ومستنداتُ فريقه **في الرئيسيّ**. رفعُ قيد المكان عنه كان يجمع
                له مستنداتِه من الفروع كلِّها فتقفز الأرقامُ بالوقوف على
                الرئيسيّ (موظفٌ: ١٢ ← ١٦٥، مشرفٌ: ٢٣ ← ٥٨٣).
              • نطاقُ فرعٍ/منطقةٍ فرعُه الأساسيّ غيرُ الرئيسيّ: يُردّ إلى جذر
                نطاقه ({@see DataScope::clampNode()}) — فرعُه هو.
        */
        if (DataScope::isUnrestricted()) {
            return null;
        }

        return DataScope::clampNode((int) $nodeId);
    }

    /** أتعني هذه العقدةُ المنشأةَ كلَّها؟ — الفرعُ الرئيسيّ وحدَه. */
    public static function meansWholeOrganisation(int $nodeId): bool
    {
        $node = Branch::findCached($nodeId);

        return $node ? (bool) $node->is_main : false;
    }
}
