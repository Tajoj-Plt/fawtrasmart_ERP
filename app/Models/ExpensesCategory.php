<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;

class ExpensesCategory extends Model
{
    use HasFactory;
    protected $table = 'expenses_categories';
    protected $fillable = ['id', 'name', 'status', 'description', 'is_client_default', 'created_at', 'updated_at'];

    protected $casts = ['is_client_default' => 'boolean'];

    /**
     * «التصنيف الافتراضي لسند صرف العميل» — يُختار سلفاً لنوع «لعميل» ويُملأ
     * عند الحفظ متى تُرك. تصنيفٌ واحد، غيرُ معطَّل (`status = 1` تعطيلٌ هنا).
     * بلا عمودٍ بعدُ (ترحيلٌ لم يُشغَّل) ⇒ null، فيبقى السلوك القديم.
     */
    public static function clientDefaultId(): ?int
    {
        try {
            $id = static::where('is_client_default', true)
                ->where(fn ($q) => $q->where('status', '!=', 1)->orWhereNull('status'))
                ->value('id');
        } catch (\Throwable $e) {
            return null;
        }

        return $id ? (int) $id : null;
    }

    /**
     * حساباتُ المصروفات المربوطة بالتصنيف — تُضبط من «تصنيفات المصروفات».
     * من لا يملك `account.expenses.all_accounts` لا يرى في سند الصرف العام غيرها.
     */
    public function linkedAccounts()
    {
        return $this->belongsToMany(Account::class, 'expenses_category_accounts', 'expenses_category_id', 'account_id')->withTimestamps();
    }

    /**
     * خريطة «تصنيف ⇐ معرّفات حساباته». بلا الجدول (ترحيلٌ لم يُشغَّل) ⇒ null،
     * فلا يُقيَّد أحد على أساسٍ لا وجود له.
     *
     * @return array<int, array<int>>|null
     */
    public static function linkedAccountMap(): ?array
    {
        static $map = false;

        if ($map !== false) {
            return $map;
        }

        if (! \Illuminate\Support\Facades\Schema::hasTable('expenses_category_accounts')) {
            return $map = null;
        }

        $map = [];
        foreach (\Illuminate\Support\Facades\DB::table('expenses_category_accounts')->get(['expenses_category_id', 'account_id']) as $row) {
            $map[(int) $row->expenses_category_id][] = (int) $row->account_id;
        }

        return $map;
    }

    /**
     * الحصول على الحسابات المرتبطة بهذا الصنف
     * Generated by Copilot
     */
    public function accounts()
    {
        // البحث عن الحسابات التي تطابق اسم الصنف
        return Account::where(function($query) {
            $query->where('name', 'LIKE', '%' . $this->name . '%')
                  ->orWhere('name', $this->name);
        })
        ->where('is_active', 1)
        ->get();
    }
    
    /**
     * الحصول على معرفات الحسابات المرتبطة بهذا الصنف
     * Generated by Copilot
     */
    public function getAccountIds()
    {
        return $this->accounts()->pluck('id')->toArray();
    }
}
