<?php

namespace App\Services\Fawtra;

use App\Models\FawtraSubscription;
use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Facades\Log;
use Throwable;

/**
 * رفعٌ فوريّ للاستهلاك عقب الإنشاء — **بعد إرسال الاستجابة، لا قبلها**.
 *
 * ─────────────────── المشكلة التي يحلّها ───────────────────
 *
 * الرفع الدوري (كل ١٥ دقيقة عبر `fawtra:sync`) يعني أن لوحة فوترة تتأخّر
 * ربع ساعة عن الواقع — وفي نظامٍ لم يُضبط فيه `schedule:run` أصلاً تتأخّر
 * إلى الأبد، فتبقى أرقام الاستهلاك عندهم صفراً مهما أُنشئ محلياً. وهو ما
 * وقع فعلاً: مستودعاتٌ تجاوزت سقفها ولوحةُ الاشتراك تعرضها فارغة.
 *
 * ─────────────────── ولماذا لا يُنادى فوترة داخل الحفظ؟ ───────────────────
 *
 * لأن نداءً متزامناً في مسار الحفظ يشتري دقّةَ اللحظة بأربعة أثمان:
 *
 *   ١. **زمن رحلةٍ كاملة يُضاف إلى كل حفظ** — والمستخدم ينتظر أمام الشاشة.
 *   ٢. **حدّ الطلبات ١٢٠/دقيقة**: فرعٌ نشط يُنشئ أكثر من ذلك بسهولة، فتُرفض
 *      طلباتٌ صحيحة ويتعطّل الرفع كلّه لا هذه العملية وحدها.
 *   ٣. **انقطاع الشبكة عند فوترة يوقف الإنشاء عندنا** — ووثيقة الواجهة
 *      تنهى عن هذا صراحةً: «لا توقف نظام العميل لعطل شبكة عندنا».
 *   ٤. **النداء داخل معاملة** يُبقي أقفال الجداول مفتوحةً طوال الرحلة.
 *
 * ─────────────────── الحلّ: أثِر الآن، وارفع بعد الاستجابة ───────────────────
 *
 * الإنشاء **يُعلِّم** الميزة بأنها تغيّرت (`mark()`)، ولا يُنادي شيئاً. وبعد
 * أن تُرسَل الاستجابة إلى المتصفّح (`app()->terminating`) تُرفَع الميزات
 * المُعلَّمة وحدها. فالمستخدم لا ينتظر شيئاً، واللوحة تتحدّث خلال ثوانٍ لا
 * ربع ساعة.
 *
 * وهو النمط نفسه الذي يستعمله [\App\Http\Middleware\EnsureSubscription] في
 * المزامنة التلقائية — لا آليةَ جديدة تُضاف إلى النظام.
 *
 * **لماذا `terminating` لا طابور؟** لأن `QUEUE_CONNECTION=sync` في هذا
 * النظام، فالمهمّة «المؤجَّلة» تُنفَّذ داخل الطلب فوراً — أي أنها النداء
 * المتزامن نفسه بثوبٍ آخر. و`terminating` يعمل بلا عامل طابور ولا تغييرِ
 * بنية. ومن يشغّل عاملاً حقيقياً يربح متانةً أكثر، وحينها يصلح تحويل هذا
 * إلى مهمّة.
 *
 * ─────────────────── الكبح ───────────────────
 *
 * خمسون إنشاءً في طلبٍ واحد = رفعٌ واحد (تُجمَّع الميزات ثم تُرفع مرّة).
 * وخمسون طلباً متتالياً = رفعٌ واحد كل `cooldown` ثانية (٦٠ افتراضاً)، وما
 * فات يبقى مُعلَّماً فيُرفع في النافذة التالية أو في الدورة الدورية. فلا
 * يقترب النظام من حدّ الطلبات مهما اشتدّ العمل.
 */
class UsagePush
{
    /** الميزات المُعلَّمة انتظاراً للرفع — تعيش بين الطلبات. */
    private const PENDING_KEY = 'fawtra.usage.pending';

    /** كابح النافذة — وجودُه يعني أن رفعاً جرى قريباً. */
    private const COOLDOWN_KEY = 'fawtra.usage.push_cooldown';

    /** هل سُجِّل خطّاف ما بعد الاستجابة في هذا الطلب؟ */
    private static bool $hooked = false;

    /**
     * تعليم ميزةٍ بأن استهلاكها تغيّر.
     *
     * تُستدعى من [\App\Observers\PlanLimitObserver] عند كل إنشاء أو حذف.
     * لا نداءَ شبكة هنا ولا استعلام — كتابةٌ في الكاش وحدها، فكلفتُها لا
     * تُحسّ ولو في استيرادٍ من آلاف الأسطر.
     */
    public static function mark(string $feature): void
    {
        if (! config('fawtra.usage.report', true) || ! config('fawtra.usage.push_on_write', true)) {
            return;
        }

        try {
            $pending = (array) Cache::get(self::PENDING_KEY, []);

            if (! in_array($feature, $pending, true)) {
                $pending[] = $feature;
                // عمرٌ أطول من دورة المزامنة: ميزةٌ عُلِّمت ولم تُرفع لانقطاع
                // شبكة يجب أن تبقى معلَّمة حتى تنجح، لا أن تُنسى بصمت
                Cache::put(self::PENDING_KEY, $pending, 3600);
            }
        } catch (Throwable $e) {
            // الكاش خدمةٌ مساعدة: تعذّرُ الكتابة فيه لا يُفشل حفظاً نجح.
            // والدورة الدورية تلتقط ما فات على كل حال
            return;
        }

        self::hook();
    }

    /**
     * تغييرٌ جماعي لا يمرّ بأحداث النموذج — يُعلَن عنه صراحةً.
     *
     * ─────────────────── لماذا يلزم نداءٌ يدوي هنا؟ ───────────────────
     *
     * `Model::whereIn(...)->delete()` و`->truncate()` تُنفَّذان في المحرّك
     * مباشرةً **بلا أن تُطلق حدث `deleted`**. فـ[\App\Observers\PlanLimitObserver]
     * لا يراها، ويبقى الرقم المرفوع إلى فوترة على ما كان قبل الحذف — فيظلّ
     * العميل ممنوعاً من الإنشاء عند سقفٍ أفرغه بيده.
     *
     * وهي تُبطل شيئين معاً، ولهذا نداءٌ واحد يعالجهما:
     *
     *   • **العدّاد المحفوظ للطلب** في [SubscriptionGate] — لم يُنقَص لأن
     *     `bumpLiveCount()` تُستدعى من حدثٍ لم يقع. فيُمسَح ليُعاد العدّ.
     *   • **الرقم عند فوترة** — يُعلَّم ليُرفَع بعد الاستجابة.
     *
     * تُستدعى بعد كل حذفٍ أو إدراجٍ جماعي على جدولٍ له حدّ. والمواضع اليوم
     * أربعة: `ProductsController::bulkDelete()`، وموضعان في
     * `InventoryManagementController` (إلغاء الجرد وحذفه)، وواحد في
     * `ProductExchangeController`.
     */
    public static function markBulkChange(string $feature): void
    {
        // القياس الحيّ في هذا الطلب صار كاذباً — يُعاد العدّ عند أوّل سؤال
        SubscriptionGate::forgetLiveCounts();

        self::mark($feature);
    }

    /**
     * تصريف ما بقي معلَّقاً — يُستدعى على **كل طلب**، لا عند الإنشاء وحده.
     *
     * ─────────────────── العطل الذي يُصلحه ───────────────────
     *
     * الكابح كان **يُسقط** الرفع لا يؤجّله: من أنشأ إذناً بعد ثوانٍ من رفعٍ
     * سابق وجد `flush()` ترتدّ عند الكابح، فتبقى ميزتُه معلَّقة — **ولا شيء
     * يعود إليها**، لأن `flush()` لم تكن تُستدعى إلا من `mark()` أي عند
     * إنشاءٍ جديد. فمن أضاف شيئاً واحداً ثم توقّف بقيت لوحتُه على الرقم
     * القديم إلى أن تعمل الدورة الدورية — وهي لا تعمل أصلاً في نظامٍ لم
     * يُضبط فيه `schedule:run`. وقد وقع فعلاً: إذنٌ مخزني أُنشئ بعد ٢٦ ثانية
     * من رفعٍ سابق فبقي غيرَ مرفوع.
     *
     * فبهذا النداء يصير أي تنقّلٍ تالٍ فرصةَ تصريف: تنتهي نافذة الكبح
     * فيُرفَع المعلَّق مع أوّل صفحة تُفتح بعدها.
     *
     * والكلفة قراءةُ كاشٍ واحدة حين لا شيء معلَّق — والغالب أن لا شيء معلَّق.
     */
    public static function ensureDrain(): void
    {
        if (self::$hooked || ! config('fawtra.usage.report', true) || ! config('fawtra.usage.push_on_write', true)) {
            return;
        }

        try {
            if ((array) Cache::get(self::PENDING_KEY, []) === []) {
                return;
            }
        } catch (Throwable) {
            return;
        }

        self::hook();
    }

    /**
     * تسجيل الرفع ليقع **بعد** إرسال الاستجابة — مرّةً واحدة لكل طلب.
     *
     * الحارس `$hooked` ضروري: مئة إنشاءٍ في طلبٍ واحد تستدعي `mark()` مئة
     * مرّة، وبلا الحارس تُسجَّل مئةُ خطّاف فيقع مئةُ رفع.
     */
    protected static function hook(): void
    {
        if (self::$hooked) {
            return;
        }

        self::$hooked = true;

        try {
            app()->terminating(function () {
                self::flush();
            });
        } catch (Throwable $e) {
            // خارج سياق طلب HTTP (أمر طرفية، مهمّة طابور) لا `terminating`.
            // الرفع يقع في الدورة الدورية — وهو الصواب لأمرٍ قد يُنشئ آلاف
            // الصفوف ولا ينبغي أن يُنادي فوترة عند كل واحد
            self::$hooked = false;
        }
    }

    /**
     * رفع الميزات المُعلَّمة — يُنفَّذ بعد الاستجابة.
     *
     * كل ما هنا محروسٌ بـ`try`: هذا يعمل بعد أن رأى المستخدم صفحته، فأيّ
     * استثناءٍ يُفلت منه لا يجد من يعرضه ولا يفيد أحداً — يُسجَّل ويُنسى،
     * والدورة الدورية تُصحّح ما فات.
     */
    public static function flush(): void
    {
        try {
            $pending = (array) Cache::get(self::PENDING_KEY, []);

            if ($pending === []) {
                return;
            }

            // الكابح: رفعٌ جرى قريباً، فما عُلِّم يبقى معلَّماً للنافذة التالية
            $cooldown = (int) config('fawtra.usage.push_cooldown', 60);

            if ($cooldown > 0 && ! Cache::add(self::COOLDOWN_KEY, true, $cooldown)) {
                return;
            }

            $client = FawtraClient::fromConfig();
            $record = FawtraSubscription::current();

            if ($client === null || $record === null || ! $record->snapshot) {
                return;
            }

            // تُنزع الآن لا بعد النجاح: لو أُبقيت حتى النجاح لأعاد كل طلبٍ
            // تاليٍ رفعَ الميزة نفسها بلا داعٍ. وما يُخفق يُصحَّح في الدورة
            // الدورية — فالرفع تراكميّ لا ذرّي (انظر `pushQuota`: العلامة
            // المائية تمنع الاحتساب المضاعف)
            Cache::forget(self::PENDING_KEY);

            $summary = app(UsageReporter::class)->push($client, $record, $pending);

            if (($summary['reported'] ?? 0) > 0 || ($summary['caps'] ?? 0) > 0) {
                Log::info('فوترة: رُفع الاستهلاك فور الإنشاء', [
                    'features' => $pending,
                    'reported' => $summary['reported'] ?? 0,
                    'caps' => $summary['caps'] ?? 0,
                ]);
            }
        } catch (Throwable $e) {
            Log::warning('فوترة: تعذّر الرفع الفوري للاستهلاك', ['error' => $e->getMessage()]);
        }
    }
}
